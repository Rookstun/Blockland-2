// blockyard/wgen.mjs: BLOCK YARD, an original block-building arcade game (FlavouredGames asked for a brick-building
// game cabinet with chiptune, 2026-11-06; original design, nothing copied). A 40 x 24 side-view yard of 4x4-pixel
// cells on a 160x96 screen; arrows move a blinking cursor, Space places a block, right mouse removes one. The yard is
// kept while the server runs (players leave their builds for the next one). One Square voice plays an original
// looping chiptune; place/remove blips cut in. Rows are rebuilt from runs of filled cells (Night Pong's row trick).
export const W = 160, H = 96, STRIP = 24, CW = 40, CH = 24, CS = 4;
export const PAL = ['000000'];
// original tune: (pitch multiplier, steps of 0.15 s); 0 = rest. A-minor-ish bounce, 32 steps.
export const TUNE = [[1, 2], [1.19, 1], [1.5, 1], [1.33, 2], [1.19, 2], [1, 1], [0, 1], [0.89, 2], [1, 2], [1.19, 2], [1.5, 2], [1.78, 2], [1.5, 1], [1.33, 1], [1.19, 2], [1, 4], [0, 4]];

export function generate({ cell = 0.5 } = {}) {
  const NS = H / STRIP, q = JSON.stringify, strips = Array.from({ length: NS }, (_, k) => k);
  const mel = TUNE.flatMap(([p, n]) => Array(n).fill(p));
  const src = `// GENERATED by blockyard/wgen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}
const MEL = [${mel.map(v => v.toFixed(2)).join(', ')}]
var rows: string[]
var dfl: int[]
var dl: int[]
var sdf: int[]
var g: int[]
${strips.map(k => `var st${k}: string = ""\nvar pb${k}: string = ""`).join('\n')}
var pubDirty: bool = false
var hudv: string = ""
var titlev: string = "BLOCK YARD"
var cx: int = ${CW / 2}
var cy: int = ${CH - 3}
var blink: bool = true
var blinkT: float = 0.0
var moveT: float = 0.0
var lastBa: bool = false
var lastBb: bool = false
var placed: int = 0
var started: bool = false
var was: bool = false
var lastT: float = 0.0
var melT: float = 0.0
var melPos: int = 0
var blipN: int = 0
var blipP: float = 1.0
var aP0: float = 1.0
var aV0: float = 0.0
var s: string = ""
var cur: float = 0.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "arrows move  -  SPACE place  -  right mouse remove"
@right out hud_: string = hudv
@right out title_: string = titlev
@right out lh_: float = ${+(cell * 0.645).toFixed(4)}
@right out ws_: float = 2.0
@right out P0: float = aP0
@right out V0: float = aV0

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { pb${k} = v }`).join('\n')}
  pubDirty = true
}
mod publish() {
${strips.map(k => `  st${k} = pb${k}`).join('\n')}
  pubDirty = false
}
mod mark(r: int) {
  if r >= 0 && r < ${H} {
    if dfl.get(r) == 0 {
      dfl[r] = 1
      dl.push(r)
    }
  }
}
mod markCell(y: int) {
  for k in 0..${CS} { mark(y * ${CS} + k) }
}
// one pixel row: runs of filled cells in its cell row, plus the cursor outline (top/bottom edge or the two sides)
mod renderRow(r: int) {
  let yc = r / ${CS}
  let sub = r % ${CS}
  s = ""
  cur = 0.0
  // no while loops in wirescript: walk the cells once, skipping past each run (nx = next cell to look at)
  var nx: int = 0
  for x in 0..${CW} {
    if x >= nx {
      let filled = g.get(yc * ${CW} + x) == 1
      let curHere = blink && yc == cy && x == cx
      let a = x * ${CS}
      if curHere && filled == false {
        // hollow cursor: full edge on the top/bottom pixel rows, two side pixels otherwise
        if sub == 0 || sub == ${CS - 1} {
          s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, ${CS})
        } else {
          s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, 1) .. SP.Substring(0, ${CS - 2}) .. BL.Substring(0, 1)
        }
        cur = a + ${CS}.0
        nx = x + 1
      } else { if filled {
        // run of filled cells from x (a blinking cursor on a filled cell just shows the block)
        var e: int = x
        e = x
        var going: bool = true
        going = true
        for e2 in x..${CW} {
          if going {
            if g.get(yc * ${CW} + e2) == 1 { e = e2 + 1 } else { going = false }
          }
        }
        let b = e * ${CS}
        s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, b - a)
        cur = b
        nx = e
      } }
    }
  }
  rows[r] = s .. SP.Substring(0, ${W}.0 - cur)
  sdf[r / ${STRIP}] = 1
}
mod flush() {
  for j in 0..dl.length() {
    let r = dl.get(j)
    dfl[r] = 0
    renderRow(r)
  }
  dl.resize(0, 0)
  for k in 0..${NS} {
    if sdf.get(k) == 1 {
      sdf[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}
mod blip(p: float) {
  blipN = 3
  blipP = p
}
mod step() {
  let now = ServerUptime()
  let dt = min(max(now - lastT, 0.0), 0.2)
  lastT = now
  // music: one note a step, blips cut in
  melT += dt
  if melT >= 0.15 {
    melT -= 0.15
    melPos = (melPos + 1) % MEL.length()
  }
  if blipN > 0 {
    aP0 = blipP
    aV0 = 0.5
    blipN -= 1
  } else {
    aP0 = max(MEL[melPos], 0.1)
    aV0 = if MEL[melPos] > 0.0 then 0.25 else 0.0
  }
  if started == false {
    if ba && lastBa == false {
      started = true
      titlev = ""
    }
    lastBa = ba
    lastBb = bb
    return
  }
  // cursor: move once on press, then repeat every 0.12 s while held
  let dx = (if right then 1 else 0) - (if left then 1 else 0)
  let dy = (if down then 1 else 0) - (if up then 1 else 0)
  if dx != 0 || dy != 0 {
    moveT -= dt
    if moveT <= 0.0 {
      moveT = 0.12
      markCell(cy)
      cx = min(max(cx + dx, 0), ${CW - 1})
      cy = min(max(cy + dy, 0), ${CH - 1})
      markCell(cy)
    }
  } else { moveT = 0.0 }
  if ba && lastBa == false && g.get(cy * ${CW} + cx) == 0 {
    g[cy * ${CW} + cx] = 1
    placed += 1
    blip(1.5)
    markCell(cy)
  }
  if bb && lastBb == false && g.get(cy * ${CW} + cx) == 1 {
    g[cy * ${CW} + cx] = 0
    placed = max(placed - 1, 0)
    blip(0.7)
    markCell(cy)
  }
  lastBa = ba
  lastBb = bb
  blinkT += dt
  if blinkT >= 0.4 {
    blinkT = 0.0
    blink = blink == false
    markCell(cy)
  }
  hudv = "BLOCKS \${placed}  -  CURSOR \${cx},\${cy}"
}
on ServerUptime() {
  if seated {
    if was == false {
      was = true
      if g.length() == 0 {
        g.resize(${CW * CH}, 0)
        for x in 0..${CW} { g[${(CH - 1) * CW} + x] = 1 } // ground row
      }
      rows.resize(${H}, "")
      dfl.resize(${H}, 0)
      sdf.resize(${NS}, 0)
      started = false
      titlev = "BLOCK YARD"
      hudv = "PRESS SPACE TO BUILD"
      lastT = ServerUptime()
      for r in 0..${H} { mark(r) }
    }
    step()
    flush()
    if pubDirty { publish() }
  } else {
    if was {
      was = false
      aV0 = 0.0
    }
  }
}
`;
  return { src, W, H, STRIP, PAL, textColor: 'ffffff', clockWhenSeated: true, noClock: true, titleMid: true, titleLH: 4, exactScreen: true, textPorts: true, synths: ['Square'] };
}
