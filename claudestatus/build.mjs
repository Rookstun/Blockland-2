// node claudestatus/build.mjs -> claudestatus/claudestatus.brz: one hidden chip that shows Claude's status at the top of
// every player's screen (owner 2026-11-06). It Sweeps down onto the beacon brick tools/chat/status.mjs re-places
// (orange = working, grey = idle) and DisplayTexts a CLI-style spinning star: "✻ claude is working" / "· claude idle",
// plus the 5-hour / weekly usage read from two beacon heights, coloured by how full (owner: moved here from chat),
// in the monospaced MonaspaceKrypton font, a little higher than first placed.
// Load: br.Prefab.Load "claudestatus" -5600 -12600 7990 0 16 (the chip sits 90 above the beacon).
import fs from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundle } from '../tools/wsbundle.mjs';
import { BEACON } from '../tools/chat/status.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OWNER = { id: 'c1a0de00-0000-4b0b-9a11-0000005a7a76', name: 'Claude Status HUD', display_name: 'Claude Status HUD' };
const STAR = ['✢', '✳', '✶', '✻', '✽', '✻', '✶', '✳'];
export const src = `// GENERATED by claudestatus/build.mjs
var players: controller[]
var busy: bool = false
var seen: bool = false
var h5: int = 0
var wk: int = 0
var f: int = 0
var slow: int = 0
const STAR = [${STAR.map(s => JSON.stringify(s)).join(', ')}]
mod col(p: int) -> string {
  return if p >= 90 then "ff4444" else if p >= 75 then "ff9933" else if p >= 50 then "eedd33" else "55dd55"
}
on Clock(interval = 0.15) {
  let probe = Sweep(Vec(${BEACON[0]}.0, ${BEACON[1]}.0, ${BEACON[2] + 60}.0), Vec(0.0, 0.0, -1.0), 100.0, detectBricks = true, detectMap = false, ignoreOwningGrid = false)
  on probe.Hit {
    seen = true
    busy = probe.HitColor.ToHex().ToLower().Substring(0, 2) == "d9"
  }
  on probe.Miss {
    seen = false
  }
  // usage beacons: each brick's height above the beacon base = percent used
  let u5 = Sweep(Vec(${BEACON[0] + 20}.0, ${BEACON[1]}.0, ${BEACON[2] + 120}.0), Vec(0.0, 0.0, -1.0), 150.0, detectBricks = true, detectMap = false, ignoreOwningGrid = false)
  on u5.Hit {
    h5 = round(u5.HitLocation.z - ${BEACON[2]}.0)
  }
  let uw = Sweep(Vec(${BEACON[0] + 40}.0, ${BEACON[1]}.0, ${BEACON[2] + 120}.0), Vec(0.0, 0.0, -1.0), 150.0, detectBricks = true, detectMap = false, ignoreOwningGrid = false)
  on uw.Hit {
    wk = round(uw.HitLocation.z - ${BEACON[2]}.0)
  }
  f = (f + 1) % ${STAR.length}
  slow += 1
  // working: spin every tick; idle: refresh once a second (cheap)
  if busy || slow >= 7 {
    slow = 0
    players.fillFromPlayers()
    let head = if busy then "<color=\\"d97757\\">" .. STAR[f] .. "</> claude is working" else "<color=\\"888888\\">·</> claude idle"
    let text = if seen == false then "" else "<font=\\"MonaspaceKrypton\\">" .. head .. "   5h <color=\\"" .. col(h5) .. "\\">\${h5}%</>  wk <color=\\"" .. col(wk) .. "\\">\${wk}%</></>"
    for p in 0..players.length() {
      players.get(p).DisplayText(text, positionX = 0.0, positionY = -500.0, fontSize = 20, lifetime = if busy then 0.4 else 1.3, textId = 9705)
    }
  }
}
`;
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  fs.writeFileSync(join(here, 'claudestatus.gen.ws'), src);
  const sdk = join(here, '..', 'tools', 'wspkg');
  const wasm = await import(pathToFileURL(join(sdk, 'wasm.js')).href);
  if (typeof wasm.default === 'function') await wasm.default({ module_or_path: fs.readFileSync(join(sdk, 'wasm_bg.wasm')) });
  const diag = wasm.wirescript_diagnostics ?? wasm.default?.wirescript_diagnostics, compile = wasm.wirescript_compile ?? wasm.default?.wirescript_compile;
  const ds = JSON.parse(diag(src, 'claudestatus', '{}') || '[]').filter(d => /error/i.test(d.severity));
  if (ds.length) { for (const d of ds) console.error(`${d.code} line ${d.startLine}: ${d.message}`); process.exit(1); }
  const b = await bundle(new Uint8Array(compile(src, 'claudestatus', '{}', '{}')), { owner: OWNER, hide: true });
  fs.writeFileSync(join(here, 'claudestatus.brz'), b.finish({ description: 'claude status hud' }));
  console.log('wrote claudestatus.brz');
}
