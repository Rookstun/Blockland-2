// wsgen.mjs: songs (chart.mjs) -> the cabinet's Wirescript source.
// One chip runs the whole 2-player machine: each Seat's Sitting Character
// comes in on player0 / player1, playerN.InputReader() (the Seat Control
// Splitter / Input Splitter gate) gives W/A/S/D = UP/LEFT/DOWN/RIGHT, the
// chart scrolls on the cabinet's TextDisplay screen (out ports wired to the
// text bricks; `scroll` = the fraction of the current row, wired to every
// lane's LineOffset so arrows glide between rows), the music plays on synth
// speakers wired from P<v>/V<v>. Both dancers play the same song in sync.
import { LANES } from './chart.mjs';

export const WIN = 12;          // rows on screen
export const LEAD_SEC = 4;      // countdown before the first row
export const PLAYERS = 2;
const W = { perfect: 0.05, great: 0.1, good: 0.16 };
export const LANE_ON = [[255, 70, 210], [60, 210, 255], [90, 255, 120], [255, 170, 40]];
const DIM_REC = 'ColorSRGB(70, 70, 80, 255)', DIM_PAD = 'ColorSRGB(40, 40, 50, 255)';
// W/A/S/D through the input splitter: [axis, sign] per lane (LEFT, DOWN, UP, RIGHT)
const KEYS = [['Right', '<', '-0.5'], ['Forward', '<', '-0.5'], ['Forward', '>', '0.5'], ['Right', '>', '0.5']];

const f = x => { const s = (+x).toFixed(3).replace(/0+$/, ''); return s.endsWith('.') ? s + '0' : s; };
const q = s => JSON.stringify(s);
const arr = (type, xs) => `[${xs.map(type === 'float' ? f : type === 'string' ? q : String).join(', ')}]`;
const col = ([r, g, b]) => `ColorSRGB(${r}, ${g}, ${b}, 255)`;

export function generate(songs, voiceSynths) {
  const S = songs.length, V = voiceSynths.length, L = [0, 1, 2, 3], P = [...Array(PLAYERS).keys()];
  const lead = songs.map(s => Math.ceil(LEAD_SEC / s.rowDur) + 1);
  // lane strings: lead blanks + one 2-char cell (glyph or space, newline) per row + WIN+1 blanks
  const laneStr = songs.map((s, i) => L.map(k => {
    const cells = new Array(lead[i] + s.rowsTotal + WIN + 1).fill(' \n');
    for (const n of s.lanes[k]) cells[lead[i] + n.row] = LANES[k] + '\n';
    return cells.join('');
  }));
  const offs = per => { const o = [0]; for (const x of per) o.push(o[o.length - 1] + x.length); return o; };
  const out = [];
  const D = (name, type, xs) => out.push(`var ${name}: ${type}[] = ${arr(type, xs)}`);
  const J = (xs, fn, sep = '\n') => xs.map(fn).join(sep);
  const eachP = fn => J(P, fn), eachL = fn => J(L, fn), eachPL = fn => J(P, p => J(L, k => fn(p, k)));
  const eachV = fn => J([...Array(V).keys()], fn);
  out.push('// GENERATED by ddr/build.mjs (wsgen.mjs) from ddr/songs/*.mid: edit those, not this file.', '');
  out.push(...P.map(p => `@right in player${p}: character`), '');
  D('NAMES', 'string', songs.map(s => s.name));
  D('LEN', 'float', songs.map(s => s.length));
  D('ROWD', 'float', songs.map(s => s.rowDur));
  D('LEAD', 'int', lead);
  D('BPM', 'int', songs.map(s => s.bpm));
  D('STEPS', 'int', songs.map(s => s.steps));
  for (const k of L) {
    D(`LS${k}`, 'string', laneStr.map(x => x[k]));
    D(`NT${k}`, 'float', songs.flatMap(s => s.lanes[k].map(n => n.t)));
    D(`NR${k}`, 'int', songs.flatMap(s => s.lanes[k].map(n => n.row)));
    D(`NO${k}`, 'int', offs(songs.map(s => s.lanes[k])));
  }
  for (let v = 0; v < V; v++) {
    const ns = songs.map(s => s.voices[v]?.notes ?? []);
    D(`VT${v}`, 'float', ns.flat().map(n => n.t)); D(`VE${v}`, 'float', ns.flat().map(n => n.end));
    D(`VP${v}`, 'float', ns.flat().map(n => n.pitch)); D(`VV${v}`, 'float', ns.flat().map(n => n.vol));
    D(`VO${v}`, 'int', offs(ns));
  }
  out.push(`
var none: character
var state: int = 0          // 0 nobody seated, 1 song select, 2 dancing, 3 results
var song: int = 0
var t0: float = 0.0
var lastRow: int = -99999
var lead: int = 0
var rowD: float = 0.1
var frac: float = 0.0
var title: string = "SIT DOWN TO DANCE\\n1 OR 2 PLAYERS"
var best: Map<string, int>
${eachP(p => `var act${p}: bool = false
var rdy${p}: bool = false
var score${p}: int = 0
var combo${p}: int = 0
var maxCombo${p}: int = 0
var nP${p}: int = 0
var nG${p}: int = 0
var nO${p}: int = 0
var nM${p}: int = 0
var judge${p}: string = ""
var jcol${p}: color = ColorSRGB(255, 255, 255, 255)
var info${p}: string = ""
var comboTxt${p}: string = ""`)}
${eachPL((p, k) => `var live${p}${k}: string = ""
var scr${p}${k}: string = ""
var ni${p}${k}: int = 0
var ne${p}${k}: int = 0
var flash${p}${k}: float = -9.0
var rcol${p}${k}: color = ${DIM_REC}
var pcol${p}${k}: color = ${DIM_PAD}`)}
${eachV(v => `var vi${v}: int = 0
var ve${v}: int = 0
var vp${v}: float = 1.0
var vv${v}: float = 0.0
var vo${v}: float = 0.0`)}

out title_t: string = title
out scroll: float = frac
${eachP(p => `out judge${p}_t: string = judge${p}
out judge${p}_c: color = jcol${p}
out info${p}_t: string = info${p}
out combo${p}_t: string = comboTxt${p}`)}
${eachPL((p, k) => `out lane${p}${k}: string = scr${p}${k}
out rec${p}${k}: color = rcol${p}${k}
out pad${p}${k}: color = pcol${p}${k}`)}
${eachV(v => `out P${v}: float = vp${v}
out V${v}: float = vv${v}`)}

mod silence() {
${eachV(v => `  vv${v} = 0.0`)}
}

mod redraw() {
  let base: int = max(0, lastRow + lead) * 2
${eachPL((p, k) => `  scr${p}${k} = if act${p} then live${p}${k}.Substring(base, ${(WIN + 1) * 2}) else ""`)}
}

mod clearScreen() {
${eachPL((p, k) => `  scr${p}${k} = ""`)}
${eachP(p => `  judge${p} = ""
  info${p} = ""
  comboTxt${p} = ""`)}
  frac = 0.0
}

// the ready-up: every seated dancer presses UP, then the song starts
mod readyInfo() {
${eachP(p => `  info${p} = if player${p} == none then "P${p + 1} SIT DOWN" else if rdy${p} then "P${p + 1} READY!" else "P${p + 1} PRESS ↑"`)}
}

mod menu() {
  state = 1
  silence()
  clearScreen()
  let who = if player0 != none then player0 else player1
  let key = "\${song}:\${who.ControllerOf().GetUserId()}"
  let b = best.get(key)
  let bestTxt = if b.Found then "BEST \${b.Value}" else "NO SCORE YET"
  title = "◄ \${NAMES[song]} ►\\n\${BPM[song]} BPM  \${STEPS[song]} STEPS  \${bestTxt}\\n← → PICK   ↑ START"
${eachP(p => `  rdy${p} = false`)}
  readyInfo()
}


mod start() {
  rowD = ROWD[song]
  lead = LEAD[song]
${eachP(p => `  act${p} = player${p} != none
  score${p} = 0
  combo${p} = 0
  maxCombo${p} = 0
  nP${p} = 0
  nG${p} = 0
  nO${p} = 0
  nM${p} = 0
  judge${p} = if act${p} then "READY" else ""
  jcol${p} = ColorSRGB(255, 255, 255, 255)
  info${p} = if act${p} then "0" else ""
  comboTxt${p} = ""`)}
${eachPL((p, k) => `  live${p}${k} = LS${k}[song]
  ni${p}${k} = NO${k}[song]
  ne${p}${k} = if act${p} then NO${k}[song + 1] else NO${k}[song]`)}
${eachV(v => `  vi${v} = VO${v}[song]
  ve${v} = VO${v}[song + 1]`)}
  t0 = ServerUptime() + ${f(LEAD_SEC)}
  lastRow = -99999
  title = NAMES[song]
  state = 2
}

${eachP(p => `mod points${p}() {
  info${p} = "\${floor(score${p} * 1000000.0 / max(1.0, 3.0 * STEPS[song]))}"
  comboTxt${p} = if combo${p} >= 4 then "\${combo${p}} COMBO" else ""
}

mod judgeHit${p}(dt: float) {
  if dt <= ${f(W.perfect)} {
    nP${p} = nP${p} + 1
    score${p} = score${p} + 3
    judge${p} = "PERFECT"
    jcol${p} = ColorSRGB(255, 225, 60, 255)
  } else if dt <= ${f(W.great)} {
    nG${p} = nG${p} + 1
    score${p} = score${p} + 2
    judge${p} = "GREAT"
    jcol${p} = ColorSRGB(90, 255, 120, 255)
  } else {
    nO${p} = nO${p} + 1
    score${p} = score${p} + 1
    judge${p} = "GOOD"
    jcol${p} = ColorSRGB(80, 180, 255, 255)
  }
  combo${p} = combo${p} + 1
  maxCombo${p} = max(maxCombo${p}, combo${p})
  points${p}()
}

mod missed${p}() {
  nM${p} = nM${p} + 1
  combo${p} = 0
  judge${p} = "MISS"
  jcol${p} = ColorSRGB(255, 50, 50, 255)
  points${p}()
}

mod result${p}() {
  if act${p} && player${p} != none {
    let pct = score${p} / max(1.0, 3.0 * STEPS[song])
    let pts: int = floor(pct * 1000000.0)
    let grade = if nG${p} + nO${p} + nM${p} == 0 then "AAA" else if pct >= 0.93 then "AA" else if pct >= 0.8 then "A" else if pct >= 0.65 then "B" else if pct >= 0.45 then "C" else "D"
    let coins: int = floor(25.0 * pct * pct)
    let ctrl = player${p}.ControllerOf()
    if coins > 0 {
      ctrl.IncLeaderboard("coins", coins)
    }
    let key = "\${song}:\${ctrl.GetUserId()}"
    let b = best.get(key)
    if !b.Found || pts > b.Value {
      best.set(key, pts)
    }
    judge${p} = "\${grade}  \${pts}"
    jcol${p} = ColorSRGB(255, 225, 60, 255)
    info${p} = "P\${nP${p}} G\${nG${p}} OK\${nO${p}} X\${nM${p}}"
    comboTxt${p} = "MAX \${maxCombo${p}}  +\${coins}c"
    BroadcastChatMessage("<color=\\"ff60d0\\">\${ctrl.GetUserName()} danced \${NAMES[song]}: \${grade} (\${pts})</>")
  }
}`, '\n\n')}

mod finish() {
  state = 3
  silence()
  clearScreen()
${eachP(p => `  result${p}()`)}
  title = "\${NAMES[song]}\\nCLEARED!\\n↑ NEXT"
}

${eachP(p => `mod menuKey${p}(k: int) {
  if k == 0 {
    song = (song + ${S - 1}) % ${S}
    menu()
  } else if k == 3 {
    song = (song + 1) % ${S}
    menu()
  } else if k == 1 {
    rdy${p} = false
    readyInfo()
  } else if k == 2 {
    rdy${p} = true
    readyInfo()
    if ${P.map(q => `(player${q} == none || rdy${q})`).join(' && ')} {
      start()
    }
  }
}`, '\n\n')}

${eachPL((p, k) => `mod press${p}${k}() {
  if state == 2 {
    if act${p} && ni${p}${k} < ne${p}${k} {
      let t = ServerUptime() - t0
      let dt = abs(t - NT${k}[ni${p}${k}])
      if dt <= ${f(W.good)} {
        judgeHit${p}(dt)
        flash${p}${k} = t
        let at: int = (NR${k}[ni${p}${k}] + lead) * 2
        live${p}${k} = live${p}${k}.Substring(0, at) .. " " .. live${p}${k}.Substring(at + 1, live${p}${k}.Length() - at - 1)
        ni${p}${k} = ni${p}${k} + 1
        redraw()
      }
    }
  } else if state == 1 {
    menuKey${p}(${k})
  } else if state == 3 {
    menu()
  }
}`, '\n\n')}

mod seats() {
  if player0 == none && player1 == none {
    state = 0
    silence()
    clearScreen()
    title = "SIT DOWN TO DANCE\\n1 OR 2 PLAYERS"
  } else if state == 2 {
${eachP(p => `    if player${p} == none && act${p} {
      act${p} = false
${eachL(k => `      ne${p}${k} = ni${p}${k}`)}
      judge${p} = "LEFT"
      redraw()
    }`)}
    if ${P.map(p => `!act${p}`).join(' && ')} {
      menu()                  // nobody dancing is still seated (e.g. P1 hopped into P2's seat): back to song select
    } else {
${eachP(p => `      if player${p} != none && !act${p} {
        info${p} = "NEXT SONG"
      }`)}
    }
  } else {
    menu()
  }
}

${eachP(p => `on player${p} {
  seats()
}
let inp${p} = player${p}.InputReader()
${eachL(k => { const [ax, op, th] = KEYS[k]; return `on inp${p}.${ax} ${op} ${th} {
  if inp${p}.${ax} ${op} ${th} {
    pcol${p}${k} = ${col(LANE_ON[k])}
    press${p}${k}()
  } else {
    pcol${p}${k} = ${DIM_PAD}
  }
}`; })}`)}

on Clock(interval = 0.02, enabled = state == 2) {
  let t = ServerUptime() - t0
  if t > LEN[song] + 1.5 {
    finish()
  } else {
    let rows = t / rowD
    let row: int = floor(rows)
    frac = rows - row
    if row != lastRow {
      lastRow = row
      redraw()
    }
${eachPL((p, k) => `    if ni${p}${k} < ne${p}${k} && t > NT${k}[ni${p}${k}] + ${f(W.good)} {
      missed${p}()
      ni${p}${k} = ni${p}${k} + 1
    }
    rcol${p}${k} = if t - flash${p}${k} < 0.12 then ${col(LANE_ON[k])} else ${DIM_REC}`)}
${eachV(v => `    if vi${v} < ve${v} && t >= VT${v}[vi${v}] {
      vp${v} = VP${v}[vi${v}]
      vo${v} = VE${v}[vi${v}]
      vv${v} = VV${v}[vi${v}]
      vi${v} = vi${v} + 1
    } else if t >= vo${v} {
      vv${v} = 0.0
    }`)}
    if t < 0.0 {
      let c: int = ceil(-t)
      title = "\${NAMES[song]}\\nGET READY\\n\${c}"
    } else if t < 1.0 {
      title = "\${NAMES[song]}\\nGO!"
    } else if title != NAMES[song] {
      title = NAMES[song]
    }
${eachP(p => `    if act${p} && t < 0.0 {
      judge${p} = "READY"
    } else if act${p} && t < 1.0 && judge${p} == "READY" {
      judge${p} = "GO!"
    }`)}
  }
}
`);
  return out.join('\n');
}
