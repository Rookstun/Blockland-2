// wsgen.mjs: songs (chart.mjs) -> the cabinet's Wirescript source (1 player).
// The Seat's Sitting Character comes in on `player`; player.InputReader()
// (the Seat Control Splitter / Input Splitter gate) gives W/A/S/D =
// UP/LEFT/DOWN/RIGHT, Q or E stops the song. The chart scrolls on the
// cabinet's TextDisplay screen (out ports wired to the text bricks), the
// music plays on synth speakers wired from P<v>/V<v>, drums (chart.mjs DRUMS) on synth speakers from DP<d>/DA<d>:
// each hit bumps dn<d>, and dn - Tween(dn, dur) is a 1 -> 0 envelope the game runs every frame. DEBUG lines go to chat.
import { LANES } from './chart.mjs';

// smooth scroll: each lane = K strip panels, each shows one arrow slid by its TextDisplay Offset
// (Offset.Y = up in world units, measured in game). Arrow z on the screen = RECEPTOR_Z - dt * SPEED.
const NL = String.fromCharCode(10);
export const K = 6;             // arrow sprites per lane (strips)
export const STRIP_Z0 = 18, STRIP_H = 12;   // strips at z 18..90 (cabinet.mjs builds them from these)
export const RECEPTOR_Z = 94, LOOK = 1.6;          // receptor centre; seconds of lookahead on screen
const SPEED = (RECEPTOR_Z - STRIP_Z0) / LOOK;
const NBSP = ' ';
export const LEAD_SEC = 4;      // countdown before the first row
export const GAIN = 2.0;              // master volume (owner: "too soft" at 1.0)
export const PREVIEW = 12;            // song select: seconds of music previewed (looped), from the busiest stretch
export const RAINBOW_COMBO = 10;      // combo that turns the arrow outlines rainbow
const DEBUG = false;            // [ddr] lines in chat (owner: use chat for logs)
export const W = { perfect: 0.05, great: 0.1, good: 0.16 };
export const LANE_ON = [[255, 70, 210], [60, 210, 255], [90, 255, 120], [255, 170, 40]];
const DIM_REC = 'ColorSRGB(70, 70, 80, 255)', DIM_PAD = 'ColorSRGB(40, 40, 50, 255)';
// W/A/S/D through the input splitter: [axis, op, threshold] per lane (LEFT, DOWN, UP, RIGHT)
const KEYS = [['Right', '<', '-0.5'], ['Forward', '<', '-0.5'], ['Forward', '>', '0.5'], ['Right', '>', '0.5']];

const f = x => { const s = (+x).toFixed(3).replace(/0+$/, ''); return s.endsWith('.') ? s + '0' : s; };
const q = s => JSON.stringify(s);
const arr = (type, xs) => `[${xs.map(type === 'float' ? f : type === 'string' ? q : String).join(', ')}]`;
const col = ([r, g, b]) => `ColorSRGB(${r}, ${g}, ${b}, 255)`;

export function generate(songs, voiceDefs, drumDefs = []) {
  const S = songs.length, V = voiceDefs.length, DK = drumDefs.length, eachD = fn => [...Array(DK).keys()].map(fn).join(NL), CLICK = voiceDefs.map(([, g]) => g === 'click'), L = [0, 1, 2, 3];
  const lead = songs.map(s => Math.ceil(LEAD_SEC / s.rowDur) + 1);
  const offs = per => { const o = [0]; for (const x of per) o.push(o[o.length - 1] + x.length); return o; };
  const out = [];
  const D = (name, type, xs) => out.push(`var ${name}: ${type}[] = ${arr(type, xs)}`);
  const eachL = fn => L.map(fn).join('\n'), eachV = fn => [...Array(V).keys()].map(fn).join('\n');
  out.push('// GENERATED by ddr/build.mjs (wsgen.mjs) from ddr/songs/*.mid: edit those, not this file.', '');
  out.push('@right in player: character', '');
  D('NAMES', 'string', songs.map(s => s.name));
  D('LEN', 'float', songs.map(s => s.length));
  D('ROWD', 'float', songs.map(s => s.rowDur));
  D('LEAD', 'int', lead);
  D('BPM', 'int', songs.map(s => s.bpm));
  D('STEPS', 'int', songs.map(s => s.steps));
  D('DIFF', 'int', songs.map(s => Math.max(1, Math.min(10, Math.round(s.steps / s.length * 1.6)))));  // difficulty 1-10 from the steps a second
  for (const k of L) {
    D(`NT${k}`, 'float', songs.flatMap(s => s.lanes[k].map(n => n.t)));
    D(`NO${k}`, 'int', offs(songs.map(s => s.lanes[k])));
  }
  for (let v = 0; v < V; v++) {
    const ns = songs.map(s => s.voices[v]?.notes ?? []);
    D(`VT${v}`, 'float', ns.flat().map(n => n.t)); D(`VE${v}`, 'float', ns.flat().map(n => n.end));
    D(`VP${v}`, 'float', ns.flat().map(n => n.pitch)); D(`VV${v}`, 'float', ns.flat().map(n => n.vol));
    D(`VO${v}`, 'int', offs(ns));
  }
  for (let d = 0; d < DK; d++) {
    const hs = songs.map(s => s.drums[d]);
    D(`DT${d}`, 'float', hs.flat().map(h => h.t)); D(`DV${d}`, 'float', hs.flat().map(h => h.vol));
    if (drumDefs[d].kind === 'tom') D(`DS${d}`, 'float', hs.flat().map(h => h.s));
    D(`DO${d}`, 'int', offs(hs));
  }
  // preview start per song: the PREVIEW-second window (1 s steps) with the most chart steps + notes
  const pvs = songs.map(s => {
    const ts = [...s.lanes.flatMap(l => l.map(n => n.t)), ...s.voices.flatMap(v => v.notes.map(n => n.t))].sort((a, b) => a - b);
    let best = 0, bestN = -1;
    for (let st = 0; st + PREVIEW <= s.length; st += 1) {
      let n = 0; for (const t of ts) if (t >= st && t < st + PREVIEW) n++;
      if (n > bestN) { bestN = n; best = st; }
    }
    return best;
  });
  D('PVS', 'float', pvs);
  for (let v = 0; v < V; v++) {
    let o = 0;
    D(`PVI${v}`, 'int', songs.map((s, i) => { const ns = s.voices[v]?.notes ?? []; let k = ns.findIndex(n => n.t >= pvs[i]); if (k < 0) k = ns.length; const r = o + k; o += ns.length; return r; }));
  }
  for (let d = 0; d < DK; d++) {
    let o = 0;
    D(`PDI${d}`, 'int', songs.map((s, i) => { const hs = s.drums[d]; let k = hs.findIndex(h => h.t >= pvs[i]); if (k < 0) k = hs.length; const r = o + k; o += hs.length; return r; }));
  }
  // one Clock tick of drum d: a hit restarts its envelope
  const drumStep = (d, fade) => `      if di${d} < de${d} && t >= DT${d}[di${d}] {
        dn${d} = dn${d} + 1.0
        dg${d} = DV${d}[di${d}]${fade}${drumDefs[d].kind === 'tom' ? `
        ds${d} = DS${d}[di${d}]` : ''}
        di${d} = di${d} + 1
      }`;
  const drumReset = (d, idx) => `  di${d} = ${idx}${d}[song]
  de${d} = DO${d}[song + 1]
  dg${d} = 0.0`;
  // one Clock tick of voice v at song time t, volume scaled by fade
  const voiceStep = (v, fade) => `      if vi${v} < ve${v} && t >= VT${v}[vi${v}] {
        vp${v} = VP${v}[vi${v}]
        vo${v} = VE${v}[vi${v}]
        va${v} = VV${v}[vi${v}] * ${f(GAIN)}
        vs${v} = t
        vv${v} = va${v}${fade}
        vi${v} = vi${v} + 1
      } else if t >= vo${v} {
        vv${v} = 0.0
      } else {
        vv${v} = va${v}${fade} * ${CLICK[v] ? `max(0.3, 1.0 - (t - vs${v}) * 5.0)    // clicky: fast decay` : `max(0.7, 1.0 - (t - vs${v}) * 1.0)    // pluck: decay to a 70% sustain`}
      }`;
  const dbg = msg => DEBUG ? `  BroadcastChatMessage("<color=\\"8080ff\\">[ddr] ${msg}</>")` : '';
  out.push(`
var none: character
var state: int = 0          // 0 seat empty, 1 song select, 2 dancing, 3 results
var song: int = 0
var t0: float = 0.0
var pt0: float = 0.0        // song select preview: uptime at song time 0
var lead: int = 0
var rowD: float = 0.1
var sync: float = 0.0       // /ddrsync: chart delay vs the music, seconds
var title: string = "SIT DOWN TO DANCE"
var best: Map<string, int>
var topn: Map<string, string>
var score: int = 0
var combo: int = 0
var maxCombo: int = 0
var nP: int = 0
var nG: int = 0
var nO: int = 0
var nM: int = 0
var judge: string = ""
var jcol: color = ColorSRGB(255, 255, 255, 255)
var info: string = ""
var comboTxt: string = ""
var beatC: color = ColorSRGB(60, 20, 50, 255)
var beatB: float = 0.0
var rainbow: color = ColorSRGB(0, 0, 0, 255)
var lampC: color = ColorSRGB(255, 60, 200, 255)
${eachL(k => `${[...Array(K).keys()].map(j => `var st${k}${j}: string = ""
var so${k}${j}: vector = Vec(0.0, 0.0, 0.0)`).join(NL)}
var ni${k}: int = 0
var ne${k}: int = 0
var flash${k}: float = -9.0
var rcol${k}: color = ${DIM_REC}
var pcol${k}: color = ${DIM_PAD}`)}
${eachV(v => `var vi${v}: int = 0
var ve${v}: int = 0
var vp${v}: float = 1.0
var vv${v}: float = 0.0
var vo${v}: float = 0.0
var va${v}: float = 0.0
var vs${v}: float = 0.0`)}
${eachD(d => `var di${d}: int = 0
var de${d}: int = 0
var dn${d}: float = 0.0
var dg${d}: float = 0.0
var ds${d}: float = 1.0`)}

out title_t: string = title
out judge_t: string = judge
out judge_c: color = jcol
out info_t: string = info
out combo_t: string = comboTxt
out beat_c: color = beatC
out beat_b: float = beatB
out rainbow_c: color = rainbow
out lamp_c: color = lampC
${eachL(k => `${[...Array(K).keys()].map(j => `out spr${k}${j}: string = st${k}${j}
out off${k}${j}: vector = so${k}${j}`).join(NL)}
out rec${k}: color = rcol${k}
out pad${k}: color = pcol${k}`)}
${eachV(v => `out P${v}: float = vp${v}
out V${v}: float = if state == 1 || state == 2 then ${CLICK[v] ? `vv${v}` : `min(vv${v}, Dampen(vv${v}, 0.025))`} else 0.0`)}   // smooth voices tween only incoming; clicky ones snap
${eachD(d => { const { kind, dur, hi, lo } = drumDefs[d]; return `let e${d} = min(1.0, max(0.0, dn${d} - Tween(dn${d}, ${f(dur)})))   // ${kind}
out DP${d}: float = ds${d} * (${f(lo)} + ${f(hi - lo)} * e${d} * e${d})
out DA${d}: float = if state == 1 || state == 2 then dg${d} * e${d} else 0.0`; })}

mod silence() {
${eachV(v => `  vv${v} = 0.0
  va${v} = 0.0
  vo${v} = -9999.0`)}
${eachD(d => `  dg${d} = 0.0`)}
}


mod clearScreen() {
  rainbow = ColorSRGB(0, 0, 0, 255)
  lampC = ColorSRGB(255, 60, 200, 255)
  beatC = ColorSRGB(60, 20, 50, 255)
  beatB = 0.0
${eachL(k => [...Array(K).keys()].map(j => `  st${k}${j} = ""`).join(NL))}
  judge = ""
  info = ""
  comboTxt = ""
}

// song select: play PREVIEW seconds of the song from PVS (looped by the Clock)
mod preview() {
${eachV(v => `  vi${v} = PVI${v}[song]
  ve${v} = VO${v}[song + 1]
  vv${v} = 0.0
  va${v} = 0.0
  vo${v} = -9999.0`)}
${eachD(d => drumReset(d, 'PDI'))}
  pt0 = ServerUptime() - PVS[song]
}

// the panel while nothing is being played: the selected song's high score and difficulty
mod showHigh() {
  let tp = best.get("\${song}:top")
  let tn = topn.get("\${song}:top")
  judge = "HIGH SCORE"
  jcol = ColorSRGB(255, 225, 60, 255)
  info = if tp.Found then "\${tn.Value}  \${tp.Value}" else "NO SCORE YET"
  comboTxt = "LV \${DIFF[song]}/10"
}

mod menu() {
${dbg('menu')}
  state = 1
  clearScreen()
  preview()
  let key = "\${song}:\${player.ControllerOf().GetUserId()}"
  let b = best.get(key)
  let bestTxt = if b.Found then "BEST \${b.Value}" else "NO SCORE YET"
  title = "◄ \${NAMES[song]} ►\\n\${BPM[song]} BPM  \${STEPS[song]} STEPS  LV \${DIFF[song]}\\n\${bestTxt}\\n← → PICK  ↑ START  SPACE STOP"
  showHigh()
}

mod start() {
  rowD = ROWD[song]
  lead = LEAD[song]
  score = 0
  combo = 0
  maxCombo = 0
  nP = 0
  nG = 0
  nO = 0
  nM = 0
  judge = "READY"
  jcol = ColorSRGB(255, 255, 255, 255)
  info = "0"
  comboTxt = ""
${eachL(k => `  ni${k} = NO${k}[song]
  ne${k} = NO${k}[song + 1]`)}
${eachV(v => `  vi${v} = VO${v}[song]
  ve${v} = VO${v}[song + 1]
  vv${v} = 0.0
  va${v} = 0.0
  vo${v} = -9999.0`)}
${eachD(d => drumReset(d, 'DO'))}   // fresh voices: a stale note end kept the old note droning
  t0 = ServerUptime() + ${f(LEAD_SEC)}
  title = NAMES[song]
  state = 2
${dbg('start \${NAMES[song]} t0=\${t0}')}
}

mod points() {
  info = "\${floor(score * 1000000.0 / max(1.0, 3.0 * STEPS[song]))}"
  comboTxt = if combo >= 4 then "\${combo} COMBO" else ""
}

mod judgeHit(dt: float) {
  if dt <= ${f(W.perfect)} {
    nP = nP + 1
    score = score + 3
    judge = "PERFECT"
    jcol = ColorSRGB(255, 225, 60, 255)
  } else if dt <= ${f(W.great)} {
    nG = nG + 1
    score = score + 2
    judge = "GREAT"
    jcol = ColorSRGB(90, 255, 120, 255)
  } else {
    nO = nO + 1
    score = score + 1
    judge = "GOOD"
    jcol = ColorSRGB(80, 180, 255, 255)
  }
  combo = combo + 1
  maxCombo = max(maxCombo, combo)
  points()
}

mod missed() {
  nM = nM + 1
  combo = 0
  judge = "MISS"
  jcol = ColorSRGB(255, 50, 50, 255)
  points()
}

mod finish() {
  state = 3
  silence()
  clearScreen()
  let pct = score / max(1.0, 3.0 * STEPS[song])
  let pts: int = floor(pct * 1000000.0)
  let grade = if nG + nO + nM == 0 then "AAA" else if pct >= 0.93 then "AA" else if pct >= 0.8 then "A" else if pct >= 0.65 then "B" else if pct >= 0.45 then "C" else "D"
  let coins: int = floor(25.0 * pct * pct)
  let ctrl = player.ControllerOf()
  if coins > 0 {
    ctrl.IncLeaderboard("coins", coins)
  }
  let key = "\${song}:\${ctrl.GetUserId()}"
  let b = best.get(key)
  if !b.Found || pts > b.Value {
    best.set(key, pts)
  }
  let tk = "\${song}:top"
  let tp = best.get(tk)
  if !tp.Found || pts > tp.Value {
    best.set(tk, pts)
    topn.set(tk, ctrl.GetUserName())
  }
  judge = "\${grade}  \${pts}"
  jcol = ColorSRGB(255, 225, 60, 255)
  info = "P\${nP} G\${nG} OK\${nO} X\${nM}"
  comboTxt = "MAX \${maxCombo}  +\${coins}c"
  title = "\${NAMES[song]}\\nCLEARED!\\n↑ NEXT"
  BroadcastChatMessage("<color=\\"ff60d0\\">\${ctrl.GetUserName()} danced \${NAMES[song]}: \${grade} (\${pts})</>")
}

mod menuKey(k: int) {
  if k == 0 {
    song = (song + ${S - 1}) % ${S}
    menu()
  } else if k == 3 {
    song = (song + 1) % ${S}
    menu()
  } else if k == 2 {
    start()
  }
}

${eachL(k => `mod press${k}() {
  if state == 2 {
    if ni${k} < ne${k} {
      let t = ServerUptime() - t0 - sync
      let dt = abs(t - NT${k}[ni${k}])
      if dt <= ${f(W.good)} {
        judgeHit(dt)
        flash${k} = t
        ni${k} = ni${k} + 1
      }
    }
  } else if state == 1 {
    menuKey(${k})
  } else if state == 3 {
    menu()
  }
}`).replace(/\n(?=mod press)/g, '\n\n')}

on player {
${dbg('seat state=\${state} sat=\${player != none}')}
  if player == none {
    state = 0
    silence()
    clearScreen()
    title = "SIT DOWN TO DANCE"
    showHigh()
  } else {
    menu()
  }
}

let inp = player.InputReader()
${eachL(k => { const [ax, op, th] = KEYS[k]; return `on inp.${ax} ${op} ${th} {
  if inp.${ax} ${op} ${th} {
    pcol${k} = ${col(LANE_ON[k])}
    press${k}()
  } else {
    pcol${k} = ${DIM_PAD}
  }
}`; })}
on ChatCommand("ddrsync", "DDR: shift the arrows vs the music, in ms (+ = arrows later)") -> (ctrl, args) {
  sync = args.Trim().ParseNumber() / 1000.0
  BroadcastChatMessage("<color=\\"ff60d0\\">DDR sync now \${floor(sync * 1000.0 + 0.5)} ms</>")
}

// Space: stop the song, back to song select
on inp.Up > 0.5 {
  if inp.Up > 0.5 && state == 2 {
${dbg('stopped')}
    menu()
  }
}

// always running (a Clock switched on/off through 'enabled' got stuck): only works while dancing
on Clock(interval = 0.02) {
  if state == 2 {
    let t = ServerUptime() - t0
    let tc = t - sync
    if t > LEN[song] + 1.5 {
      finish()
    } else {
${eachL(k => [...Array(K).keys()].map(j => { const zc = STRIP_Z0 + (j + 0.5) * STRIP_H; return `      // lane ${k} sprite ${j}: the next note with index = ${j} (mod ${K})
      let j${k}${j}: int = ni${k} + ((${j} - ni${k}) % ${K} + ${K}) % ${K}
      let d${k}${j} = NT${k}[j${k}${j}] - tc
      if j${k}${j} < ne${k} && d${k}${j} < ${f(LOOK)} {
        st${k}${j} = "${LANES[k]}"
        so${k}${j} = Vec(0.0, ${f(RECEPTOR_Z - zc)} - d${k}${j} * ${f(SPEED)}, 0.0)
      } else if st${k}${j} != "" {
        st${k}${j} = ""
      }`; }).join(NL))}
${eachL(k => `      if ni${k} < ne${k} && tc > NT${k}[ni${k}] + ${f(W.good)} {
        missed()
        ni${k} = ni${k} + 1
      }
      rcol${k} = if tc - flash${k} < 0.12 then ${col(LANE_ON[k])} else ${DIM_REC}`)}
${eachV(v => voiceStep(v, ''))}
${eachD(d => drumStep(d, ''))}
      // the BPM light: a flash at each beat that fades over a quarter beat
      let beats = tc * BPM[song] / 60.0
      let ph = beats - floor(beats)
      let pulse = max(0.0, 1.0 - ph * 4.0)
      beatB = pulse * 60.0
      beatC = if ph < 0.25 then ColorSRGB(255, 90, 220, 255) else ColorSRGB(60, 20, 50, 255)
      // combo of 10+: every arrow outline (lanes, receptors, pads) and the lamps' light cycle the rainbow
      if combo >= ${RAINBOW_COMBO} {
        let h = t * 5.0
        let cr: int = floor(127.5 + 127.5 * sin(h))
        let cg: int = floor(127.5 + 127.5 * sin(h + 2.094))
        let cb: int = floor(127.5 + 127.5 * sin(h + 4.189))
        rainbow = ColorSRGB(cr, cg, cb, 255)
        lampC = rainbow
      } else if combo == 0 && lampC != ColorSRGB(255, 60, 200, 255) {
        rainbow = ColorSRGB(0, 0, 0, 255)
        lampC = ColorSRGB(255, 60, 200, 255)
      }
      if t < 0.0 {
        let c: int = ceil(-t)
        title = "\${NAMES[song]}\\nGET READY  \${c}"
      } else if t < 1.0 {
        title = "\${NAMES[song]}\\nGO!"
        judge = if judge == "READY" then "GO!" else judge
      } else if title != NAMES[song] {
        title = NAMES[song]
      }
    }
  } else if state == 1 {
    let t = ServerUptime() - pt0
    if t > PVS[song] + ${f(PREVIEW)} {
      preview()
    } else {
      let fade = min(1.0, min(t - PVS[song], (PVS[song] + ${f(PREVIEW)} - t) / 1.5))
${eachV(v => voiceStep(v, ' * fade'))}
${eachD(d => drumStep(d, ' * fade'))}
    }
  }
}
`);
  return out.join('\n');
}
