const CKEYS = Object.keys(COL);
// per-row coloured spans of every sprite, flattened: sprite k row j -> SI[ROWBASE[k] + j] .. SI[ROWBASE[k] + j + 1]
function spriteTables() {
  const SI = [0], SS = [], SE = [], SC = [], ROWBASE = {};
  let rowsSoFar = 0;
  for (const [name, art] of Object.entries(SPRITES)) {
    ROWBASE[name] = rowsSoFar;
    for (const line of art) {
      for (let x = 0; x < line.length;) {
        const c = line[x];
        if (c === '.') { x++; continue; }
        let e = x; while (e < line.length && line[e] === c) e++;
        SS.push(x); SE.push(e); SC.push(CKEYS.indexOf(c)); x = e;
      }
      SI.push(SS.length); rowsSoFar++;
    }
  }
  return { SI, SS, SE, SC, ROWBASE };
}

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, q = JSON.stringify;
  const strips = Array.from({ length: NS }, (_, k) => k);
  const T = spriteTables();
  const DX = 6, DH = 16;                  // Daniel x, height (sprite 13 wide)
  const GH = 20, BODY = 5;                // goon sprite height; body (hitbox) starts 5 rows down, x 0..10
  const LINE = 24, GROUND = H - 5;
  // self-check: every sprite row has a table entry and colours resolve
  if (T.SI.length - 1 !== Object.values(SPRITES).reduce((n, a) => n + a.length, 0) || T.SC.some(c => c < 0)) throw Error('self-check: sprite tables');
  // looping tune (pitch x the Triangle base; 0 = rest), 3 ticks a step
  const N = { C: 1, D: 1.122, E: 1.26, F: 1.335, G: 1.498, A: 1.682, B: 1.888, c: 2, _: 0 };
  const MUS = 'EEG_A_GE D_DE G_E_ EEG_A_cA G_ED C___'.replace(/ /g, '').split('').map(ch => N[ch]);
  const src = `// GENERATED by dvi/gen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}
const COLS = [${CKEYS.map(k => q(`<color="${COL[k]}">`)).join(', ')}]
const SI = [${T.SI.join(', ')}]
const SS = [${T.SS.join(', ')}]
const SE = [${T.SE.join(', ')}]
const SC = [${T.SC.join(', ')}]
const MUS = [${MUS.join(', ')}]

var rows: string[]
var dfl: int[]
var dl: int[]
var sdf: int[]
var gx: float[]
var gy: float[]
var ux: float[]
var uy: float[]
var is: float[]
var ie: float[]
var ic: float[]
${strips.map(k => `var st${k}: string = ""`).join('\n')}
var hudv: string = ""
var titlev: string = "DANIEL VS ISIS"
var py: float = ${H / 2 - DH / 2}.0
var opy: float = -1.0
var score: int = 0
var best: int = 0
var lives: int = 3
var over: int = 0
var waiting: bool = false
var lastBa: bool = false
var was: bool = false
var forced: bool = false
var kt: float = 1.0
var lastT: float = 0.0
var nextSpawn: float = 0.0
var nextShot: float = 0.0
var s: string = ""
var cur: float = 0.0
var mel: float[]
var melPos: int = 0
var musT: int = 0
var aP0: float = 1.0
var aV0: float = 0.0
var aP1: float = 1.0
var aV1: float = 0.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "W/S move  SPACE shoot"
@right out hud_: string = hudv
@right out title_: string = titlev
@right out P0: float = aP0
@right out V0: float = aV0
@right out P1: float = aP1
@right out V1: float = aV1

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { st${k} = v }`).join('\n')}
}
mod mark(r: int) {
  if r >= 0 && r < ${H} {
    if dfl.get(r) == 0 {
      dfl[r] = 1
      dl.push(r)
    }
  }
}
mod markSpan(y: float, h: int) {
  let y0 = floor(y)
  for k in 0..h { mark(y0 + k) }
}
// one sprite row's coloured spans at x0 (sprite row base rb, row j)
mod spr(rb: int, j: int, x0: float) {
  for t in SI[rb + j]..SI[rb + j + 1] {
    is.push(x0 + SS[t])
    ie.push(x0 + SE[t])
    ic.push(SC[t])
  }
}
mod span(a: float, b: float, c: int) {
  is.push(a)
  ie.push(b)
  ic.push(c)
}
mod note(p: float, n: int) {
  for k in 0..n { mel.push(p) }
}
mod tune(a: float, b: float, c: float) {
  mel.resize(0, 0.0)
  melPos = 0
  note(a, 2)
  note(b, 2)
  note(c, 4)
}
mod clearAll() {
  for i in 0..gx.length() { markSpan(gy.get(i), ${GH}) }
  for i in 0..ux.length() { markSpan(uy.get(i), 2) }
  gx.resize(0, 0.0)
  gy.resize(0, 0.0)
  ux.resize(0, 0.0)
  uy.resize(0, 0.0)
}
mod reset() {
  clearAll()
  score = 0
  lives = 3
  over = 0
  markSpan(py, ${DH})
  py = ${H / 2 - DH / 2}.0
  markSpan(py, ${DH})
  nextSpawn = ServerUptime() + 1.0
  musT = 0
}
mod renderRow(r: int) {
  is.resize(0, 0.0)
  ie.resize(0, 0.0)
  ic.resize(0, 0.0)
  let dy0 = floor(py)
  if r >= dy0 && r < dy0 + ${DH} { spr(${T.ROWBASE.daniel}, r - dy0, ${DX}.0) }
  for i in 0..gx.length() {
    let x0 = floor(gx.get(i))
    let y0 = floor(gy.get(i))
    if x0 > -50.0 && r >= y0 && r < y0 + ${GH} { spr(${T.ROWBASE.goon}, r - y0, x0) }
  }
  for i in 0..ux.length() {
    let y0 = floor(uy.get(i))
    if ux.get(i) < ${W}.0 && r >= y0 && r < y0 + 2 { spr(${T.ROWBASE.bullet}, r - y0, floor(ux.get(i))) }
  }
  if r < 2 { span(0.0, ${W}.0, ${CKEYS.indexOf('l')}) }
  if r >= ${GROUND} { span(0.0, ${W}.0, ${CKEYS.indexOf('n')}) }
  if r >= 2 && r < ${GROUND} && r % 6 < 3 { span(${LINE - 1}.0, ${LINE}.0, ${CKEYS.indexOf('t')}) }
  is.sortMultiple(ie, ic)
  s = ""
  cur = 0.0
  for j in 0..is.length() {
    let a = max(max(is.get(j), cur), 0.0)
    let b = min(ie.get(j), ${W}.0)
    if b > a {
      s = s .. SP.Substring(0, a - cur) .. COLS[ic.get(j)] .. BL.Substring(0, b - a) .. "</>"
      cur = b
    }
  }
  rows[r] = s .. SP.Substring(0, ${W}.0 - cur)
  sdf[r / ${STRIP}] = 1
}
mod step() {
  let now = ServerUptime()
  kt = min(max((now - lastT) * 10.0, 0.0), 2.5)
  lastT = now
  if melPos < mel.length() {
    aP0 = max(mel.get(melPos), 0.1)
    aV0 = if mel.get(melPos) > 0.0 then 0.5 else 0.0
    melPos += 1
  } else { aV0 = 0.0 }
  if waiting {
    aV1 = 0.0
    if ba && lastBa == false {
      waiting = false
      titlev = ""
      if over > 0 { reset() }
    }
  } else {
    // music: a step every 3 ticks, looping
    let m = MUS[(musT / 3) % ${MUS.length}]
    aP1 = max(m * 0.5, 0.1)
    aV1 = if m > 0.0 then 0.25 else 0.0
    musT += 1
    if up { py -= 6.0 * kt }
    if down { py += 6.0 * kt }
    py = min(max(py, 3.0), ${GROUND - DH}.0)
    if py != opy {
      markSpan(opy, ${DH})
      markSpan(py, ${DH})
      opy = py
    }
    if ba && now >= nextShot {
      nextShot = now + 0.3
      var slot: int = -1
      slot = -1
      for i in 0..ux.length() { if ux.get(i) >= ${W}.0 { slot = i } }
      if slot < 0 {
        ux.push(${DX + 12}.0)
        uy.push(py + 7.0)
      } else {
        ux[slot] = ${DX + 12}.0
        uy[slot] = py + 7.0
      }
      aP0 = 2.0
      aV0 = 0.3
    }
    if now >= nextSpawn {
      nextSpawn = now + max(0.6, 2.2 - score * 0.05)
      let y = Random(3.0, ${GROUND - GH}.0)
      var gs: int = -1
      gs = -1
      for i in 0..gx.length() { if gx.get(i) <= -50.0 { gs = i } }
      if gs < 0 {
        gx.push(${W}.0)
        gy.push(y)
      } else {
        gx[gs] = ${W}.0
        gy[gs] = y
      }
    }
    let gsp = (1.2 + score * 0.04) * kt
    for i in 0..gx.length() {
      if gx.get(i) > -50.0 {
        markSpan(gy.get(i), ${GH})
        gx[i] = gx.get(i) - gsp
        if gx.get(i) < ${LINE}.0 {
          gx[i] = -100.0
          lives -= 1
          tune(1.0, 0.84, 0.7)
        }
      }
    }
    for b in 0..ux.length() {
      if ux.get(b) < ${W}.0 {
        markSpan(uy.get(b), 2)
        ux[b] = ux.get(b) + 12.0 * kt
        for i in 0..gx.length() {
          if gx.get(i) > -50.0 && ux.get(b) + 4.0 > gx.get(i) && ux.get(b) < gx.get(i) + 10.0 && uy.get(b) + 2.0 > gy.get(i) + ${BODY}.0 && uy.get(b) < gy.get(i) + ${GH}.0 {
            markSpan(gy.get(i), ${GH})
            gx[i] = -100.0
            ux[b] = ${W}.0
            score += 1
            tune(1.26, 1.5, 2.0)
          }
        }
        markSpan(uy.get(b), 2)
      }
    }
    for i in 0..gx.length() { if gx.get(i) > -50.0 { markSpan(gy.get(i), ${GH}) } }
    if lives <= 0 {
      if score > best { best = score }
      over = 1
      waiting = true
      clearAll()
      tune(0.9, 0.75, 0.6)
    }
  }
  lastBa = ba
  if waiting {
    if over > 0 { hudv = "GAME OVER  SCORE \${score}  BEST \${best}  -  SPACE" } else { hudv = "SPACE TO START  BEST \${best}" }
  } else { hudv = "SCORE \${score}  LIVES \${lives}  BEST \${best}" }
}
mod idle() {
  if was {
    was = false
    gx.resize(0, 0.0)
    gy.resize(0, 0.0)
    ux.resize(0, 0.0)
    uy.resize(0, 0.0)
    dl.resize(0, 0)
    dfl.fill(0)
    over = 0
    score = 0
    hudv = ""
    aV0 = 0.0
    aV1 = 0.0
    titlev = "DANIEL VS ISIS"
    mel.resize(0, 0.0)
    melPos = 0
${strips.map(k => `    st${k} = ""`).join('\n')}
  }
}
mod flush() {
  for j in 0..dl.length() {
    let r = dl.get(j)
    dfl[r] = 0
    renderRow(r)
  }
  dl.resize(0, 0)
  for k in 0..${NS} {
    if sdf.get(k) == 1 {
      sdf[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}

${debug ? `on ChatCommand("dvdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("dvrow|${k}|" .. st${k})`).join('\n')}
}
on ChatCommand("dvsit", "debug: play as if seated (toggle)") -> (ctrl, args) {
  forced = forced == false
}
on ChatCommand("dvgo", "debug: start the round (as Space)") -> (ctrl, args) {
  waiting = false
  titlev = ""
  if over > 0 { reset() }
}
` : ''}on tick {
  if seated || forced {
    if was == false {
      was = true
      rows.resize(${H}, "")
      dfl.resize(${H}, 0)
      sdf.resize(${NS}, 0)
      reset()
      waiting = true
      lastT = ServerUptime()
      for r in 0..${H} { mark(r) }
    }
    step()
    flush()
  } else {
    idle()
  }
}
on Change(seated) {
  if seated == false && forced == false { idle() }
}
`;
  return { src, W, H, STRIP, PAL, clockWhenSeated: !debug, titleMid: true, titleLH: 4, exactScreen: true, synths: ['Square', 'Triangle'] };
}
