// dvi/gen.mjs: DANIEL VS ISIS (owner renderman 2026-11-05: "a new game with the new engine called daniel vs isis").
// Same pure-wire row engine as pong/wgen.mjs (240x160 at 10x10 pixels a micro brick, rows rebuilt from object intervals,
// only touched strips re-joined). Arcade lane shooter, cartoon and generic: Daniel (left) moves W/S and shoots with
// Space; masked goons with blank black flags walk in from the right, faster as the score climbs. A goon that reaches
// Daniel's side costs a life; 3 lives. Space starts a round (after sitting or a game over); leaving the seat = idle.
export const W = 240, H = 160, STRIP = 20;
export const PAL = ['000000'];

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, q = JSON.stringify;
  const strips = Array.from({ length: NS }, (_, k) => k);
  const DX = 8, DW = 8, DH = 14;  // Daniel: x, width, height
  const GW = 8, GH = 14;          // goon body
  const BW = 6, BH = 2;           // bullet
  const LINE = 22;                // goons crossing x < LINE cost a life
  const src = `// GENERATED by dvi/gen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}

var rows: string[]
var dfl: int[]
var dl: int[]
var sdf: int[]
var gx: float[]
var gy: float[]
var ux: float[]
var uy: float[]
var is: float[]
var ie: float[]
${strips.map(k => `var st${k}: string = ""`).join('\n')}
var hudv: string = ""
var titlev: string = "DANIEL VS ISIS"
var py: float = ${H / 2 - DH / 2}.0
var opy: float = -1.0
var score: int = 0
var best: int = 0
var lives: int = 3
var over: int = 0
var waiting: bool = false
var lastBa: bool = false
var was: bool = false
var forced: bool = false
var kt: float = 1.0
var lastT: float = 0.0
var nextSpawn: float = 0.0
var nextShot: float = 0.0
var s: string = ""
var cur: float = 0.0
var mel: float[]
var melPos: int = 0
var aP0: float = 1.0
var aV0: float = 0.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "W/S move  SPACE shoot"
@right out hud_: string = hudv
@right out title_: string = titlev
@right out P0: float = aP0
@right out V0: float = aV0

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { st${k} = v }`).join('\n')}
}
mod mark(r: int) {
  if r >= 0 && r < ${H} {
    if dfl.get(r) == 0 {
      dfl[r] = 1
      dl.push(r)
    }
  }
}
mod markSpan(y: float, h: int) {
  let y0 = floor(y)
  for k in 0..h { mark(y0 + k) }
}
mod note(p: float, n: int) {
  for k in 0..n { mel.push(p) }
}
mod tune(a: float, b: float, c: float) {
  mel.resize(0, 0.0)
  melPos = 0
  note(a, 2)
  note(b, 2)
  note(c, 4)
}
mod clearAll() {
  for i in 0..gx.length() { markSpan(gy.get(i) - 4.0, ${GH + 4}) }
  for i in 0..ux.length() { markSpan(uy.get(i), ${BH}) }
  gx.resize(0, 0.0)
  gy.resize(0, 0.0)
  ux.resize(0, 0.0)
  uy.resize(0, 0.0)
}
mod reset() {
  clearAll()
  score = 0
  lives = 3
  over = 0
  markSpan(py, ${DH})
  py = ${H / 2 - DH / 2}.0
  markSpan(py, ${DH})
  nextSpawn = ServerUptime() + 1.0
}
// one row from the objects on it: Daniel (body + head notch), goons (body, flag on a pole), bullets
mod renderRow(r: int) {
  is.resize(0, 0.0)
  ie.resize(0, 0.0)
  let dy0 = floor(py)
  if r >= dy0 && r < dy0 + ${DH} {
    if r < dy0 + 4 {
      is.push(${DX + 2}.0)
      ie.push(${DX + DW - 2}.0)
    } else {
      is.push(${DX}.0)
      ie.push(${DX + DW}.0)
    }
  }
  for i in 0..gx.length() {
    let x0 = floor(gx.get(i))
    let y0 = floor(gy.get(i))
    if x0 > -50.0 {
      if r >= y0 && r < y0 + ${GH} {
        is.push(x0)
        ie.push(x0 + ${GW}.0)
      }
      if r >= y0 - 4 && r < y0 - 1 {
        is.push(x0 + ${GW - 1}.0)
        ie.push(x0 + ${GW + 5}.0)
      }
      if r == y0 - 1 {
        is.push(x0 + ${GW - 1}.0)
        ie.push(x0 + ${GW}.0)
      }
    }
  }
  for i in 0..ux.length() {
    let y0 = floor(uy.get(i))
    if ux.get(i) < ${W}.0 && r >= y0 && r < y0 + ${BH} {
      is.push(floor(ux.get(i)))
      ie.push(floor(ux.get(i)) + ${BW}.0)
    }
  }
  if r < 2 || r >= ${H - 2} {
    is.push(0.0)
    ie.push(${W}.0)
  }
  if r >= 2 && r < ${H - 2} && r % 6 < 3 {
    is.push(${LINE - 1}.0)
    ie.push(${LINE}.0)
  }
  is.sortMultiple(ie)
  s = ""
  cur = 0.0
  for j in 0..is.length() {
    let a = max(max(is.get(j), cur), 0.0)
    let b = min(ie.get(j), ${W}.0)
    if b > a {
      s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, b - a)
      cur = b
    }
  }
  rows[r] = s .. SP.Substring(0, ${W}.0 - cur)
  sdf[r / ${STRIP}] = 1
}
mod step() {
  let now = ServerUptime()
  kt = min(max((now - lastT) * 10.0, 0.0), 2.5)
  lastT = now
  if melPos < mel.length() {
    aP0 = max(mel.get(melPos), 0.1)
    aV0 = if mel.get(melPos) > 0.0 then 0.5 else 0.0
    melPos += 1
  } else { aV0 = 0.0 }
  if waiting {
    if ba && lastBa == false {
      waiting = false
      titlev = ""
      if over > 0 { reset() }
    }
  } else {
    // Daniel
    if up { py -= 6.0 * kt }
    if down { py += 6.0 * kt }
    py = min(max(py, 3.0), ${H - DH - 3}.0)
    if py != opy {
      markSpan(opy, ${DH})
      markSpan(py, ${DH})
      opy = py
    }
    // shooting: Space, at most 3 a second; reuse a spent bullet slot
    if ba && now >= nextShot {
      nextShot = now + 0.3
      var slot: int = -1
      slot = -1
      for i in 0..ux.length() { if ux.get(i) >= ${W}.0 { slot = i } }
      if slot < 0 {
        ux.push(${DX + DW}.0)
        uy.push(py + 6.0)
      } else {
        ux[slot] = ${DX + DW}.0
        uy[slot] = py + 6.0
      }
      aP0 = 2.0
      aV0 = 0.3
    }
    // goons spawn faster as the score climbs; reuse a dead slot (x <= -50)
    if now >= nextSpawn {
      nextSpawn = now + max(0.6, 2.2 - score * 0.05)
      let y = Random(8.0, ${H - GH - 4}.0)
      var gs: int = -1
      gs = -1
      for i in 0..gx.length() { if gx.get(i) <= -50.0 { gs = i } }
      if gs < 0 {
        gx.push(${W}.0)
        gy.push(y)
      } else {
        gx[gs] = ${W}.0
        gy[gs] = y
      }
    }
    let gsp = (1.2 + score * 0.04) * kt
    for i in 0..gx.length() {
      if gx.get(i) > -50.0 {
        markSpan(gy.get(i) - 4.0, ${GH + 4})
        gx[i] = gx.get(i) - gsp
        if gx.get(i) < ${LINE}.0 {
          gx[i] = -100.0
          lives -= 1
          tune(1.0, 0.84, 0.7)
        }
      }
    }
    for b in 0..ux.length() {
      if ux.get(b) < ${W}.0 {
        markSpan(uy.get(b), ${BH})
        ux[b] = ux.get(b) + 12.0 * kt
        // hit test against every live goon
        for i in 0..gx.length() {
          if gx.get(i) > -50.0 && ux.get(b) + ${BW}.0 > gx.get(i) && ux.get(b) < gx.get(i) + ${GW}.0 && uy.get(b) + ${BH}.0 > gy.get(i) && uy.get(b) < gy.get(i) + ${GH}.0 {
            markSpan(gy.get(i) - 4.0, ${GH + 4})
            gx[i] = -100.0
            ux[b] = ${W}.0
            score += 1
            tune(1.26, 1.5, 2.0)
          }
        }
        markSpan(uy.get(b), ${BH})
      }
    }
    for i in 0..gx.length() { if gx.get(i) > -50.0 { markSpan(gy.get(i) - 4.0, ${GH + 4}) } }
    if lives <= 0 {
      if score > best { best = score }
      over = 1
      waiting = true
      clearAll()
      tune(0.9, 0.75, 0.6)
    }
  }
  lastBa = ba
  if waiting {
    if over > 0 { hudv = "GAME OVER  SCORE \${score}  BEST \${best}  -  SPACE" } else { hudv = "SPACE TO START  BEST \${best}" }
  } else { hudv = "SCORE \${score}  LIVES \${lives}  BEST \${best}" }
}
mod idle() {
  if was {
    was = false
    gx.resize(0, 0.0)
    gy.resize(0, 0.0)
    ux.resize(0, 0.0)
    uy.resize(0, 0.0)
    dl.resize(0, 0)
    dfl.fill(0)
    over = 0
    score = 0
    hudv = ""
    aV0 = 0.0
    titlev = "DANIEL VS ISIS"
    mel.resize(0, 0.0)
    melPos = 0
${strips.map(k => `    st${k} = ""`).join('\n')}
  }
}
mod flush() {
  for j in 0..dl.length() {
    let r = dl.get(j)
    dfl[r] = 0
    renderRow(r)
  }
  dl.resize(0, 0)
  for k in 0..${NS} {
    if sdf.get(k) == 1 {
      sdf[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}

${debug ? `on ChatCommand("dvdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("dvrow|${k}|" .. st${k})`).join('\n')}
}
on ChatCommand("dvsit", "debug: play as if seated (toggle)") -> (ctrl, args) {
  forced = forced == false
}
on ChatCommand("dvgo", "debug: start the round (as Space)") -> (ctrl, args) {
  waiting = false
  titlev = ""
  if over > 0 { reset() }
}
` : ''}on tick {
  if seated || forced {
    if was == false {
      was = true
      rows.resize(${H}, "")
      dfl.resize(${H}, 0)
      sdf.resize(${NS}, 0)
      reset()
      waiting = true
      lastT = ServerUptime()
      for r in 0..${H} { mark(r) }
    }
    step()
    flush()
  } else {
    idle()
  }
}
on Change(seated) {
  if seated == false && forced == false { idle() }
}
`;
  return { src, W, H, STRIP, PAL, textColor: 'ffffff', clockWhenSeated: !debug, titleMid: true, titleLH: 4, exactScreen: true, synths: ['Square'] };
}
