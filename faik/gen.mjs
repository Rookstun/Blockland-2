// faik/gen.mjs: FAIK PLATFORMER on the Super Sigmas engine (tools/wspkg + supersigmas/cabinet.mjs).
// A one-screen platformer in ONE microchip: 24 x 16 tiles of 2 x 2 coloured block cells (48 x 32 picture).
// Faik (black hat, teal band) walks and jumps 4 tiles; collect every coin, then reach the green door; spikes and the
// red walkers cost a life (3). 3 levels (The Lawn, The Fridge, The Pit), then they loop a bit faster.
//   inputs: tick (20 Hz), seated, left right up down, a (Space / RMB), b (LMB / E)   jump = W or Space
//   outputs: strip0..strip7, msg_, hud_, title_, P0/V0 coin ping, P1/V1 jump + death
export const W = 48, H = 32, STRIP = 4;
const TW = 24, TH = 16, N = TW * TH;
export const PAL = ['0a0e24', '8a5a3a', '5a3a24', '40c060', 'c8c8d0', 'f0c830', 'd0ffd0', '18181c', '28c8d0', '8a8490', '3860d0', 'e03030', '801818', 'f6f6f6', 'f0c830', '20285a'];

// platforms [row, c0, c1], spikes [row, c], extra coins [row, c], walkers [row, c, dir], start [row, c]
const LEVELS = [
  { name: 'THE LAWN', plats: [[14, 1, 22], [11, 3, 8], [11, 15, 20], [8, 9, 14], [5, 2, 7], [5, 16, 22], [2, 9, 14]],
    spikes: [[13, 6], [13, 7], [13, 18]], extra: [[13, 11], [13, 21]], walkers: [[13, 12, 1], [10, 17, -1], [7, 11, 1]], start: [13, 2], exit: [1, 12] },
  { name: 'THE FRIDGE', plats: [[14, 1, 22], [11, 1, 5], [11, 10, 13], [11, 18, 22], [8, 6, 9], [8, 14, 17], [5, 2, 5], [5, 10, 13], [5, 19, 22], [2, 6, 9]],
    spikes: [[13, 4], [13, 5], [13, 12], [13, 13]], extra: [[13, 8]], walkers: [[13, 16, -1], [10, 20, 1], [4, 11, -1], [7, 15, 1]], start: [13, 2], exit: [1, 8] },
  { name: 'THE PIT', plats: [[14, 1, 3], [14, 20, 22], [11, 5, 8], [11, 12, 15], [8, 9, 11], [8, 17, 20], [5, 3, 6], [5, 12, 15], [5, 21, 22], [2, 8, 11], [2, 16, 19]],
    spikes: [...Array(16)].map((_, i) => [14, 4 + i]), extra: [], walkers: [[10, 13, 1], [4, 13, -1], [7, 18, 1], [1, 9, -1]], start: [13, 2], exit: [1, 17] },
];
const NLV = LEVELS.length;
// tile kinds: 0 air, 1 brick, 2 spike, 3 coin, 4 door, 5 faik (dark eyes over a grey body), 6 walker, 7 grass brick, 8 faik's black hat + teal band (drawn on the tile above him)
const LOOK = [[0, 0, 0, 0], [1, 2, 2, 1], [0, 4, 4, 4], [0, 5, 5, 0], [13, 6, 6, 13], [7, 7, 9, 9], [11, 11, 12, 11], [3, 3, 1, 2], [7, 7, 8, 8]];

const q = s => JSON.stringify(s);
const A = xs => `[${xs.join(', ')}]`;
const AS = xs => `[${xs.map(q).join(', ')}]`;

function build(lv) {
  const g = [...Array(TH)].map(() => Array(TW).fill(0));
  for (let r = 0; r < TH; r++) for (let c = 0; c < TW; c++) if (r === 0 || r === TH - 1 || c === 0 || c === TW - 1) g[r][c] = 1;
  for (const [r, c0, c1] of lv.plats) for (let c = c0; c <= c1; c++) g[r][c] = 1;
  for (const [r, c] of lv.spikes) g[r][c] = 2;
  const coins = new Set();
  for (const [r, c0, c1] of lv.plats) {
    if (r === 14) continue;
    coins.add(`${r - 1},${c0}`); coins.add(`${r - 1},${c1}`);
    if (c1 - c0 >= 4) coins.add(`${r - 1},${(c0 + c1) >> 1}`);
  }
  for (const [r, c] of lv.extra) coins.add(`${r},${c}`);
  coins.delete(`${lv.exit[0]},${lv.exit[1]}`);
  let n = 0;
  for (const k of coins) { const [r, c] = k.split(',').map(Number); if (g[r][c] === 0) { g[r][c] = 3; n++; } }
  g[lv.exit[0]][lv.exit[1]] = 4;
  for (let r = 1; r < TH; r++) for (let c = 0; c < TW; c++) if (g[r][c] === 1 && g[r - 1][c] === 0) g[r][c] = 7;
  return { map: g.flat(), n };
}

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, PH = 2, ROWS_PH = TH / PH;
  const L = LEVELS.map(build);
  const K = [0, 1, 2, 3];
  const wk = (i, k, j) => { const w = LEVELS[i].walkers[k]; return w ? w[j] : 0; };
  const EA0 = LEVELS.flatMap((_, i) => K.map(k => LEVELS[i].walkers[k] ? 1 : 0));
  const ER0 = LEVELS.flatMap((_, i) => K.map(k => wk(i, k, 0)));
  const EC0 = LEVELS.flatMap((_, i) => K.map(k => wk(i, k, 1)));
  const ED0 = LEVELS.flatMap((_, i) => K.map(k => wk(i, k, 2) || 1));
  const OPEN = PAL.map((h, i) => i === 0 ? '' : `<color="${h}">`), CLOSE = PAL.map((_, i) => i === 0 ? '' : '</>');
  const BLK = Array.from({ length: W + 1 }, (_, n) => '█'.repeat(n));
  const each = fn => K.map(fn).join('\n');
  const stripCode = ks => ks.map(k => `    st${k} = ${Array.from({ length: STRIP }, (_, j) => `rows[${k * STRIP + j}]`).join(' .. "\\n" .. ')}`).join('\n');
  const push = (s, c) => `      if ${c} == c${s} { n${s} += 1 } else {
        if n${s} > 0 { s${s} = s${s} .. OPEN[c${s}] .. BLK[n${s}] .. CLOSE[c${s}] }
        c${s} = ${c}
        n${s} = 1
      }`;
  const phaseStrips = ph => Array.from({ length: NS / PH }, (_, j) => ph * (NS / PH) + j);

  const src = `// GENERATED by faik/gen.mjs: edit that, not this file.
// FAIK PLATFORMER: logic every 'tick' (20 Hz) while 'seated'; the picture renders half a frame a tick.

@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in a: bool
@left in b: bool

const MAPK = ${A(L.flatMap(l => l.map))}
const CNT = ${A(L.map(l => l.n))}
const SR = ${A(LEVELS.map(l => l.start[0]))}
const SC = ${A(LEVELS.map(l => l.start[1]))}
const EA0 = ${A(EA0)}
const ER0 = ${A(ER0)}
const EC0 = ${A(EC0)}
const ED0 = ${A(ED0)}
const LVNAME = ${AS(LEVELS.map(l => l.name))}
const LOOK = ${A(LOOK.flat())}
const OPEN = ${AS(OPEN)}
const CLOSE = ${AS(CLOSE)}
const BLK = ${AS(BLK)}

var state: int = 0           // 0 title, 1 playing, 2 dying, 3 level clear, 4 game over
var stT: int = 0
var t: int = 0
var booted: bool = false
var cur: int[] = [${Array(N).fill(0).join(', ')}]
var act: int[] = [${Array(N).fill(0).join(', ')}]
var oldA: int[] = [0, 0, 0, 0, 0, 0]
var ea: int[] = [0, 0, 0, 0]
var er: int[] = [0, 0, 0, 0]
var ec: int[] = [0, 0, 0, 0]
var ed: int[] = [1, 1, 1, 1]
var lvl: int = 0
var lives: int = 3
var score: int = 0
var hi: int = 0
var coinsLeft: int = 0
var pr: int = 13
var pc: int = 2
var jt: int = 0
var kL: bool = false
var kR: bool = false
var kJ: bool = false
var pJ: bool = false
var msg: string = ""
var msgT: int = 0
var hud: string = ""
var pingT: int = -99
var pingHi: bool = false
var fxT: int = -99
var fxKind: int = 0
var aP0: float = 1.0
var aV0: float = 0.0
var aP1: float = 1.0
var aV1: float = 0.0
var rows: string[] = [${Array(H).fill('""').join(', ')}]
${Array.from({ length: NS }, (_, k) => `var st${k}: string = ""`).join('\n')}

${Array.from({ length: NS }, (_, k) => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = msg
@right out hud_: string = hud
@right out title_: string = if state == 0 then "FAIK" else ""
@right out P0: float = aP0
@right out V0: float = aV0
@right out P1: float = aP1
@right out V1: float = aV1
@right out state_: int = state

mod solid(i: int) -> bool {
  let k = cur[i]
  return k == 1 || k == 7
}

mod showHud() {
  hud = if state == 0 then "A D WALK   W OR SPACE JUMP" else ("SCORE " .. score .. "   LIVES " .. lives .. "   COINS " .. coinsLeft)
}

mod stamp() {
  for k in 0..6 { act[oldA[k]] = 0 }
  for k in 0..4 {
    if ea[k] == 1 {
      let ei = er[k] * ${TW} + ec[k]
      act[ei] = 6
      oldA[k + 1] = ei
    } else {
      oldA[k + 1] = 0
    }
  }
  if state != 2 || (stT / 3) % 2 == 0 {
    let pi = pr * ${TW} + pc
    act[pi] = 5
    act[pi - ${TW}] = 8
    oldA[0] = pi
    oldA[5] = pi - ${TW}
  } else {
    oldA[0] = 0
    oldA[5] = 0
  }
}

mod resetRound() {
  let m = lvl % ${NLV}
  pr = SR[m]
  pc = SC[m]
  jt = 0
  for k in 0..4 {
    ea[k] = EA0[m * 4 + k]
    er[k] = ER0[m * 4 + k]
    ec[k] = EC0[m * 4 + k]
    ed[k] = ED0[m * 4 + k]
  }
  state = 1
  stT = 0
  msg = LVNAME[m]
  msgT = 30
  showHud()
}

mod loadLevel() {
  let m = lvl % ${NLV}
  for i in 0..${N} { cur[i] = MAPK[m * ${N} + i] }
  coinsLeft = CNT[m]
  resetRound()
}

mod newGame() {
  lvl = 0
  lives = 3
  score = 0
  loadLevel()
}

mod sfx(kind: int) {
  fxT = t
  fxKind = kind
}

mod hurt() {
  state = 2
  stT = 0
  sfx(2)
}

mod walkersHit() {
  for k in 0..4 {
    if ea[k] == 1 && er[k] == pr && ec[k] == pc { hurt() }
  }
}

mod playerStep() {
  var ax: int = 0
  if kL { ax = -1 }
  if kR { ax = 1 }
  if ax != 0 && !solid(pr * ${TW} + pc + ax) { pc += ax }
  let g = solid((pr + 1) * ${TW} + pc)
  if g && jt == 0 && kJ {
    jt = 4
    sfx(1)
  }
  if jt > 0 {
    if !solid((pr - 1) * ${TW} + pc) {
      pr -= 1
      jt -= 1
    } else {
      jt = 0
    }
  } else if !g {
    pr += 1
  }
  let i = pr * ${TW} + pc
  let k = cur[i]
  if k == 2 { hurt() }
  if k == 3 {
    cur[i] = 0
    coinsLeft -= 1
    score += 10
    pingT = t
    pingHi = !pingHi
    showHud()
  }
  walkersHit()
  if k == 4 && coinsLeft <= 0 && state == 1 {
    state = 3
    stT = 0
    score += 100 * (lvl + 1) + 50 * lives
    msg = "LEVEL CLEAR"
    msgT = 0
    showHud()
  }
}

mod walkersStep() {
  for k in 0..4 {
    if ea[k] == 1 {
      let r = er[k]
      let nc = ec[k] + ed[k]
      if solid(r * ${TW} + nc) || !solid((r + 1) * ${TW} + nc) {
        ed[k] = 0 - ed[k]
      } else {
        ec[k] = nc
      }
    }
  }
  walkersHit()
}

mod compose(r0: int, r1: int) {
  for ty in r0..r1 {
    var sT: string = ""
    var cT: int = -1
    var nT: int = 0
    var sB: string = ""
    var cB: int = -1
    var nB: int = 0
    for tx in 0..${TW} {
      let i = ty * ${TW} + tx
      var k: int = act[i]
      if k == 0 { k = cur[i] }
      let o = k * 4
      let a = LOOK[o]
      let b = LOOK[o + 1]
      let c = LOOK[o + 2]
      let d = LOOK[o + 3]
${push('T', 'a')}
${push('T', 'b')}
${push('B', 'c')}
${push('B', 'd')}
    }
    rows[ty * 2] = sT .. OPEN[cT] .. BLK[nT] .. CLOSE[cT]
    rows[ty * 2 + 1] = sB .. OPEN[cB] .. BLK[nB] .. CLOSE[cB]
  }
}

mod powerOn() {
  booted = true
  lvl = 0
  lives = 3
  score = 0
  loadLevel()
  state = 0
  msg = "JUMP TO START"
  msgT = 0
  showHud()
}

mod powerOff() {
  booted = false
  state = 0
  msg = ""
  hud = ""
  fxKind = 0
${Array.from({ length: NS }, (_, k) => `  st${k} = ""`).join('\n')}
  aV0 = 0.0
  aV1 = 0.0
}

${debug ? `var dbk: string = ""
var dumpReq: bool = false
on ChatCommand("fk", "FAIK debug: /fk <keys o(sit) l r u j> | dump | lvl") -> (ctrl, args) {
  if args == "dump" { dumpReq = true }
  else if args == "lvl" {
    lvl += 1
    loadLevel()
  }
  else { dbk = args }
}
` : ''}on tick {
${debug ? `  let pwr = seated || dbk.Contains("o")` : `  let pwr = seated`}
  if !pwr {
    if booted { powerOff() }
  } else {
    if !booted { powerOn() }
${debug ? `    kL = left || dbk.Contains("l")
    kR = right || dbk.Contains("r")
    kJ = up || a || b || dbk.Contains("u") || dbk.Contains("j")
    if t % 20 == 0 { PrintToConsole("fkdbg|" .. t .. "|" .. state .. "|" .. pr .. "," .. pc .. "|coins " .. coinsLeft .. "|lives " .. lives .. "|score " .. score) }
    if dumpReq && t % 2 == 1 {
      dumpReq = false
      for r in 0..${H} { PrintToConsole("fkrow|" .. r .. "|" .. rows[r]) }
    }` : `    kL = left
    kR = right
    kJ = up || a || b`}
    t += 1
    if state == 0 || state == 4 {
      if stT < 100 { stT += 1 }
      if stT > 20 && kJ && !pJ { newGame() }
    } else if state == 1 {
      stT += 1
      if t % 2 == 0 { playerStep() }
      if state == 1 && t % ${Math.round(5 / 1)} == 0 { walkersStep() }
    } else if state == 2 {
      stT += 1
      if stT >= 24 {
        lives -= 1
        if lives <= 0 {
          if score > hi { hi = score }
          state = 4
          stT = 0
          msg = "GAME OVER"
          msgT = 0
          showHud()
        } else {
          resetRound()
        }
      }
    } else if state == 3 {
      stT += 1
      if stT >= 40 {
        lvl += 1
        loadLevel()
      }
    }
    if msgT > 0 {
      msgT -= 1
      if msgT == 0 { msg = "" }
    }
    // sound: coin ping on voice 0, jump / death on voice 1
    aV0 = if t - pingT < 2 then 0.6 else 0.0
    aP0 = if pingHi then 1.9 else 1.5
    let fe = t - fxT
    if fxKind == 1 && fe < 4 {
      aP1 = 0.6 + fe * 0.15
      aV1 = 0.4
    } else if fxKind == 2 && fe < 20 {
      aP1 = max(0.15, 1.2 - fe * 0.05)
      aV1 = 0.6
    } else {
      aV1 = 0.0
    }
    stamp()
    let ph = t % ${PH}
    compose(ph * ${ROWS_PH}, ph * ${ROWS_PH} + ${ROWS_PH})
    if ph == 0 {
${stripCode(phaseStrips(0))}
    } else {
${stripCode(phaseStrips(1))}
    }
    pJ = kJ
  }
}
`;
  return { src, W, H, STRIP, PAL, synths: ['Square', 'Triangle'] };
}
