// finches/gen.mjs: GRUMPY FINCHES on the Super Sigmas engine (tools/wspkg + supersigmas/cabinet.mjs). An original
// sling-a-bird-at-the-hogs game (faik's wish, "angry birds game machine"): 24 x 16 tiles of 2 x 2 block cells (48 x 32 picture).
// W/S aim (15-75 degrees), HOLD Space / RMB / LMB / E: the power swings up and down, RELEASE to fling the finch.
// The finch breaks the first block it hits (neighbouring wood goes too, stone cracks to wood) and kills hogs it touches;
// hogs fall when the ground goes. Clear every hog before the finches run out. 3 levels, then they loop.
//   inputs: tick (20 Hz), seated, left right up down, a (Space / RMB), b (LMB / E)
//   outputs: strip0..strip7, msg_, hud_, title_, P0/V0 fling, P1/V1 crash
export const W = 48, H = 32, STRIP = 4;
const TW = 24, TH = 16, N = TW * TH;
export const PAL = ['5aa0e0', '6a4a2a', '3a2614', '40c060', 'c89050', '8a5a30', 'aab0b8', '70767e', '70d040', '3a7a20', 'e03030', '801818', 'f6f6f6', 'f0c830', 'f6f6f6', '5a3a24'];
// tile kinds: 0 sky, 1 dirt, 2 grass, 3 wood, 4 stone, 5 hog, 6 finch, 7 aim dot, 8 sling
const LOOK = [[0, 0, 0, 0], [1, 2, 2, 1], [3, 3, 1, 2], [4, 5, 5, 4], [6, 7, 7, 6], [8, 12, 9, 9], [10, 10, 11, 13], [0, 14, 14, 0], [15, 0, 15, 15]];
const SLX = 2, SLY = 13;   // sling tile

// rectangles [r0, r1, c0, c1, kind], hogs [row, col]
const LEVELS = [
  { name: 'THE FARM', birds: 4, rects: [[10, 13, 16, 16, 3], [10, 13, 19, 19, 3], [9, 9, 15, 20, 3]], hogs: [[13, 17], [8, 17], [13, 21]] },
  { name: 'THE WALL', birds: 5, rects: [[9, 13, 15, 15, 4], [8, 8, 15, 20, 3], [9, 13, 20, 20, 3], [12, 13, 22, 22, 3]], hogs: [[13, 17], [13, 18], [7, 18], [13, 21]] },
  { name: 'THE TOWER', birds: 5, rects: [[10, 13, 15, 16, 4], [6, 13, 18, 18, 3], [6, 13, 21, 21, 3], [5, 5, 17, 22, 4], [9, 9, 17, 22, 3]], hogs: [[8, 19], [8, 20], [4, 19], [13, 19], [13, 20]] },
];
const NLV = LEVELS.length;

const q = s => JSON.stringify(s);
const A = xs => `[${xs.join(', ')}]`;
const AS = xs => `[${xs.map(q).join(', ')}]`;

function build(lv) {
  const g = [...Array(TH)].map(() => Array(TW).fill(0));
  for (let c = 0; c < TW; c++) { g[14][c] = 2; g[15][c] = 1; }
  for (const [r0, r1, c0, c1, k] of lv.rects) for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) g[r][c] = k;
  for (const [r, c] of lv.hogs) g[r][c] = 5;
  g[SLY][SLX] = 8;
  return { map: g.flat(), hogs: lv.hogs.length };
}

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, PH = 2, ROWS_PH = TH / PH;
  const L = LEVELS.map(build);
  const OPEN = PAL.map((h, i) => i === 0 ? '' : `<color="${h}">`), CLOSE = PAL.map((_, i) => i === 0 ? '' : '</>');
  const BLK = Array.from({ length: W + 1 }, (_, n) => '█'.repeat(n));
  const stripCode = ks => ks.map(k => `    st${k} = ${Array.from({ length: STRIP }, (_, j) => `rows[${k * STRIP + j}]`).join(' .. "\\n" .. ')}`).join('\n');
  const push = (s, c) => `      if ${c} == c${s} { n${s} += 1 } else {
        if n${s} > 0 { s${s} = s${s} .. OPEN[c${s}] .. BLK[n${s}] .. CLOSE[c${s}] }
        c${s} = ${c}
        n${s} = 1
      }`;
  const phaseStrips = ph => Array.from({ length: NS / PH }, (_, j) => ph * (NS / PH) + j);

  const src = `// GENERATED by finches/gen.mjs: edit that, not this file.
// GRUMPY FINCHES: logic every 'tick' (20 Hz) while 'seated'; the picture renders half a frame a tick.

@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in a: bool
@left in b: bool

const MAPK = ${A(L.flatMap(l => l.map))}
const HOGS = ${A(L.map(l => l.hogs))}
const BIRDS = ${A(LEVELS.map(l => l.birds))}
const LVNAME = ${AS(LEVELS.map(l => l.name))}
const LOOK = ${A(LOOK.flat())}
const OPEN = ${AS(OPEN)}
const CLOSE = ${AS(CLOSE)}
const BLK = ${AS(BLK)}

var state: int = 0           // 0 title, 1 aiming, 2 charging, 3 flying, 4 settling, 5 level clear, 6 game over
var stT: int = 0
var t: int = 0
var booted: bool = false
var cur: int[] = [${Array(N).fill(0).join(', ')}]
var act: int[] = [${Array(N).fill(0).join(', ')}]
var oldA: int[] = [0, 0, 0, 0, 0]
var lvl: int = 0
var score: int = 0
var birds: int = 0
var hogs: int = 0
var ang: int = 45
var pw: int = 0
var pdir: int = 1
var fire: bool = false
var pF: bool = false
var bx: float = 0.0
var by: float = 0.0
var vx: float = 0.0
var vy: float = 0.0
var msg: string = ""
var msgT: int = 0
var hud: string = ""
var flingT: int = -99
var crashT: int = -99
var aP0: float = 1.0
var aV0: float = 0.0
var aP1: float = 1.0
var aV1: float = 0.0
var rows: string[] = [${Array(H).fill('""').join(', ')}]
${Array.from({ length: NS }, (_, k) => `var st${k}: string = ""`).join('\n')}

${Array.from({ length: NS }, (_, k) => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = msg
@right out hud_: string = hud
@right out title_: string = if state == 0 then "GRUMPY FINCHES" else ""
@right out P0: float = aP0
@right out V0: float = aV0
@right out P1: float = aP1
@right out V1: float = aV1
@right out state_: int = state

mod showHud() {
  hud = if state == 0 then "W S AIM    HOLD SPACE, RELEASE TO FLING" else ("SCORE " .. score .. "   FINCHES " .. birds .. "   HOGS " .. hogs .. "   ANGLE " .. ang .. "   POWER " .. pw)
}

mod say(s: string, n: int) {
  msg = s
  msgT = n
}

mod stamp() {
  for k in 0..5 { act[oldA[k]] = 0 }
  for k in 0..5 { oldA[k] = 0 }
  if state == 1 || state == 2 {
    let a = ang * 0.0174533
    let len = 1.5 + pw * 0.04
    for k in 1..5 {
      let dx = SLX_F + cos(a) * len * k * 0.5
      let dy = SLY_F - sin(a) * len * k * 0.5
      let ix: int = floor(dx)
      let iy: int = floor(dy)
      if ix >= 0 && ix < ${TW} && iy >= 0 && iy < ${TH} {
        let i = iy * ${TW} + ix
        if cur[i] == 0 {
          act[i] = 7
          oldA[k] = i
        }
      }
    }
  }
  if state == 3 {
    let ix: int = floor(bx)
    let iy: int = floor(by)
    if ix >= 0 && ix < ${TW} && iy >= 0 && iy < ${TH} {
      let i = iy * ${TW} + ix
      act[i] = 6
      oldA[0] = i
    }
  }
}

mod loadLevel() {
  let m = lvl % ${NLV}
  for i in 0..${N} { cur[i] = MAPK[m * ${N} + i] }
  hogs = HOGS[m]
  birds = BIRDS[m]
  ang = 45
  pw = 0
  state = 1
  stT = 0
  say(LVNAME[m], 40)
  showHud()
}

mod newGame() {
  lvl = 0
  score = 0
  loadLevel()
}

mod killHog(i: int) {
  cur[i] = 0
  hogs -= 1
  score += 500
}

mod hitTile(i: int) {
  let k = cur[i]
  if k == 3 {
    cur[i] = 0
    score += 10
  } else if k == 4 {
    cur[i] = 3
  } else if k == 5 {
    killHog(i)
  }
}

mod crash(i: int) {
  hitTile(i)
  let r = floor(i / ${TW})
  let c = i % ${TW}
  if c > 0 && cur[i - 1] != 4 && cur[i - 1] != 1 && cur[i - 1] != 2 && cur[i - 1] != 8 { hitTile(i - 1) }
  if c < ${TW - 1} && cur[i + 1] != 4 && cur[i + 1] != 1 && cur[i + 1] != 2 && cur[i + 1] != 8 { hitTile(i + 1) }
  if r > 0 && cur[i - ${TW}] != 4 && cur[i - ${TW}] != 1 && cur[i - ${TW}] != 2 && cur[i - ${TW}] != 8 { hitTile(i - ${TW}) }
  if r < ${TH - 2} && cur[i + ${TW}] != 4 && cur[i + ${TW}] != 1 && cur[i + ${TW}] != 2 && cur[i + ${TW}] != 8 { hitTile(i + ${TW}) }
  crashT = t
  birds -= 1
  state = 4
  stT = 0
  showHud()
}

mod flyStep() {
  bx += vx
  by += vy
  vy += 0.012
  if bx < -1.0 || bx >= ${TW}.0 || by >= ${TH}.0 {
    birds -= 1
    state = 4
    stT = 0
    showHud()
  } else if by >= 0.0 && bx >= 0.0 {
    let ix: int = floor(bx)
    let iy: int = floor(by)
    let i = iy * ${TW} + ix
    let k = cur[i]
    if k >= 1 && k <= 5 { crash(i) }
  }
}

mod settle() {
  for rr in 0..14 {
    let r = 13 - rr
    for c in 0..${TW} {
      let i = r * ${TW} + c
      if cur[i] == 5 && cur[i + ${TW}] == 0 {
        cur[i + ${TW}] = 5
        cur[i] = 0
      }
    }
  }
}

mod compose(r0: int, r1: int) {
  for ty in r0..r1 {
    var sT: string = ""
    var cT: int = -1
    var nT: int = 0
    var sB: string = ""
    var cB: int = -1
    var nB: int = 0
    for tx in 0..${TW} {
      let i = ty * ${TW} + tx
      var k: int = act[i]
      if k == 0 { k = cur[i] }
      let o = k * 4
      let a = LOOK[o]
      let b = LOOK[o + 1]
      let c = LOOK[o + 2]
      let d = LOOK[o + 3]
${push('T', 'a')}
${push('T', 'b')}
${push('B', 'c')}
${push('B', 'd')}
    }
    rows[ty * 2] = sT .. OPEN[cT] .. BLK[nT] .. CLOSE[cT]
    rows[ty * 2 + 1] = sB .. OPEN[cB] .. BLK[nB] .. CLOSE[cB]
  }
}

mod powerOn() {
  booted = true
  lvl = 0
  score = 0
  loadLevel()
  state = 0
  say("HOLD SPACE TO START", 0)
  showHud()
}

mod powerOff() {
  booted = false
  state = 0
  msg = ""
  hud = ""
${Array.from({ length: NS }, (_, k) => `  st${k} = ""`).join('\n')}
  aV0 = 0.0
  aV1 = 0.0
}

${debug ? `var dbk: string = ""
var dumpReq: bool = false
on ChatCommand("fi", "FINCHES debug: /fi <keys o(sit) u d f(fire)> | dump | lvl") -> (ctrl, args) {
  if args == "dump" { dumpReq = true }
  else if args == "lvl" {
    lvl += 1
    loadLevel()
  }
  else { dbk = args }
}
` : ''}on tick {
${debug ? `  let pwr = seated || dbk.Contains("o")` : `  let pwr = seated`}
  if !pwr {
    if booted { powerOff() }
  } else {
    if !booted { powerOn() }
${debug ? `    fire = a || b || dbk.Contains("f")
    let kU = up || dbk.Contains("u")
    let kD = down || dbk.Contains("d")
    if t % 20 == 0 { PrintToConsole("fidbg|" .. t .. "|" .. state .. "|ang " .. ang .. "|pw " .. pw .. "|birds " .. birds .. "|hogs " .. hogs .. "|score " .. score) }
    if dumpReq && t % 2 == 1 {
      dumpReq = false
      for r in 0..${H} { PrintToConsole("firow|" .. r .. "|" .. rows[r]) }
    }` : `    fire = a || b
    let kU = up
    let kD = down`}
    t += 1
    if state == 0 || state == 6 {
      if stT < 100 { stT += 1 }
      if stT > 20 && fire && !pF { newGame() }
    } else if state == 1 || state == 2 {
      if kU && ang < 75 { ang += 1 }
      if kD && ang > 15 { ang -= 1 }
      if state == 1 && fire && !pF {
        state = 2
        pw = 10
        pdir = 1
      } else if state == 2 {
        if fire {
          pw += pdir * 3
          if pw >= 100 {
            pw = 100
            pdir = -1
          }
          if pw <= 10 {
            pw = 10
            pdir = 1
          }
        } else {
          let a = ang * 0.0174533
          let v = pw * 0.0049
          bx = ${SLX}.5
          by = ${SLY}.5
          vx = cos(a) * v
          vy = 0.0 - sin(a) * v
          state = 3
          flingT = t
        }
      }
      showHud()
    } else if state == 3 {
      flyStep()
    } else if state == 4 {
      stT += 1
      if stT % 2 == 0 { settle() }
      if stT >= 24 {
        if hogs <= 0 {
          state = 5
          stT = 0
          score += 200 * birds
          say("HOGS CLEARED", 0)
        } else if birds <= 0 {
          state = 6
          stT = 0
          say("OUT OF FINCHES", 0)
        } else {
          state = 1
          pw = 0
        }
        showHud()
      }
    } else if state == 5 {
      stT += 1
      if stT >= 50 {
        lvl += 1
        loadLevel()
      }
    }
    if msgT > 0 {
      msgT -= 1
      if msgT == 0 { msg = "" }
    }
    // sound: fling on voice 0 (a rising chirp), crash on voice 1 (noise)
    let fe = t - flingT
    aV0 = if fe < 6 then 0.5 else 0.0
    aP0 = 0.6 + fe * 0.1
    let ce = t - crashT
    aV1 = if ce < 8 then 0.6 else 0.0
    aP1 = 1.0
    stamp()
    let ph = t % ${PH}
    compose(ph * ${ROWS_PH}, ph * ${ROWS_PH} + ${ROWS_PH})
    if ph == 0 {
${stripCode(phaseStrips(0))}
    } else {
${stripCode(phaseStrips(1))}
    }
    pF = fire
  }
}
`.replace(/SLX_F/g, `${SLX}.5`).replace(/SLY_F/g, `${SLY}.5`);
  return { src, W, H, STRIP, PAL, synths: ['Triangle', 'Noise'] };
}
