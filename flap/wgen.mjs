// flap/wgen.mjs: SOGGY SPARROW, an original flap-through-the-gaps game in pure wires (FlavouredGames asked for a
// working flappy-style cabinet, owner 2026-11-06: "do what he says"). Same engine as Night Pong (pong/wgen.mjs):
// rows are rebuilt from intervals (bird sprite rows, drainpipe columns outside their gap, ground), only changed rows
// are redrawn, strips are swapped in whole at most FPS times a second. Space / right mouse (ba) = flap.
export const W = 120, H = 80, STRIP = 20;
export const PAL = ['000000'];

export function generate({ debug = false, cell = 0.4 } = {}) {
  const lh0 = +(cell * 0.645).toFixed(4), ws0 = 2.0;
  const NS = H / STRIP, q = JSON.stringify;
  const strips = Array.from({ length: NS }, (_, k) => k);
  const BX = 24, GROUND = H - 6, CW = 12, GAP = 30, SPACING = 56, NC = 3;
  // the sparrow: a round-ish 7x6 blob with a beak; per sprite row [start, end) offsets from the bird's x
  const SPR = [[2, 5], [1, 6], [0, 8], [0, 7], [1, 6], [2, 5]];
  const SH = SPR.length;
  if (SPR.some(([a, b]) => a < 0 || b > 8 || a >= b) || BX + 8 >= W) throw Error('self-check: sprite');
  const src = `// GENERATED by flap/wgen.mjs: edit that, not this file.
var FPS: float = 60.0
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}
const SA = [${SPR.map(s => s[0]).join(', ')}]
const SE = [${SPR.map(s => s[1]).join(', ')}]

var rows: string[]
var dfl: int[]
var dl: int[]
var sdf: int[]
var cx: float[]
var cg: float[]
var cs: int[]
var is: float[]
var ie: float[]
${strips.map(k => `var st${k}: string = ""\nvar pb${k}: string = ""`).join('\n')}
var pubT: float = 0.0
var pubDirty: bool = false
var hudv: string = ""
var by: float = 30.0
var vy: float = 0.0
var oby: int = -100
var scroll: float = 0.0
var oscroll: int = 0
var score: int = 0
var best: int = 0
var over: int = 0
var was: bool = false
var forced: bool = false
var kt: float = 1.0
var lastT: float = 0.0
var beep: int = 0
var sb: float = 1.0
var lhv: float = ${lh0}
var wsv: float = ${ws0}
var titlev: string = "SOGGY SPARROW"
var mel: float[]
var melPos: int = 0
var waiting: bool = false
var lastBa: bool = false
var aP0: float = 1.0
var aV0: float = 0.0
var s: string = ""
var cur: float = 0.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "SPACE flaps  -  slip through the drainpipes"
@right out hud_: string = hudv
@right out title_: string = titlev
@right out lh_: float = lhv
@right out ws_: float = wsv
@right out P0: float = aP0
@right out V0: float = aV0

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { pb${k} = v }`).join('\n')}
  pubDirty = true
}
mod publish() {
${strips.map(k => `  st${k} = pb${k}`).join('\n')}
  pubDirty = false
}
mod mark(r: int) {
  if r >= 0 && r < ${H} {
    if dfl.get(r) == 0 {
      dfl[r] = 1
      dl.push(r)
    }
  }
}
mod markBird(y: int) {
  for k in 0..${SH} { mark(y + k) }
}
mod markAll() {
  for r in 0..${GROUND} { mark(r) }
}
// a new drainpipe pair at world x, gap top somewhere in the middle band
mod newColumn(x: float) {
  cx.push(x)
  cg.push(floor(Random(8.0, ${GROUND - GAP - 8}.0)))
  cs.push(0)
}
mod reset() {
  cx.resize(0, 0.0)
  cg.resize(0, 0.0)
  cs.resize(0, 0)
  scroll = 0.0
  oscroll = 0
  for k in 0..${NC} { newColumn(${W + 20}.0 + k * ${SPACING}.0) }
  by = 30.0
  vy = 0.0
  score = 0
  over = 0
  markAll()
}
mod renderRow(r: int) {
  is.resize(0, 0.0)
  ie.resize(0, 0.0)
  let y0 = floor(by)
  if r >= y0 && r < y0 + ${SH} {
    is.push(${BX}.0 + SA[r - y0])
    ie.push(${BX}.0 + SE[r - y0])
  }
  if r < ${GROUND} {
    for i in 0..cx.length() {
      let g = cg.get(i)
      if r < g || r >= g + ${GAP}.0 {
        let x0 = floor(cx.get(i) - scroll)
        is.push(x0)
        ie.push(x0 + ${CW}.0)
      }
    }
  } else {
    is.push(0.0)
    ie.push(${W}.0)
  }
  is.sortMultiple(ie)
  s = ""
  cur = 0.0
  for j in 0..is.length() {
    let a = max(max(is.get(j), cur), 0.0)
    let b = min(ie.get(j), ${W}.0)
    if b > a {
      s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, b - a)
      cur = b
    }
  }
  rows[r] = s .. SP.Substring(0, ${W}.0 - cur)
  sdf[r / ${STRIP}] = 1
}
mod note(p: float, n: int) {
  for k in 0..n { mel.push(p) }
}
mod sadTune() {
  mel.resize(0, 0.0)
  melPos = 0
  note(0.9, 4)
  note(0.8, 4)
  note(0.0, 1)
  note(0.6, 10)
}
mod dingTune() {
  mel.resize(0, 0.0)
  melPos = 0
  note(1.5, 2)
  note(2.0, 3)
}
mod die() {
  if score > best { best = score }
  over = 1
  waiting = true
  sadTune()
}
mod step() {
  let now = ServerUptime()
  kt = min(max((now - lastT) * 10.0, 0.0), 2.5)
  lastT = now
  if melPos < mel.length() {
    aP0 = max(mel.get(melPos), 0.1)
    aV0 = if mel.get(melPos) > 0.0 then 0.5 else 0.0
    melPos += 1
    beep = 0
  } else { if beep > 0 {
    aP0 = sb * (1.0 + (3 - beep) * 0.35)
    aV0 = 0.4
    beep -= 1
  } else { aV0 = 0.0 } }
  let press = ba && lastBa == false
  lastBa = ba
  if waiting {
    if press {
      waiting = false
      titlev = ""
      if over > 0 { reset() }
      vy = -3.6
    }
  } else {
    // flap: a fixed upward kick; gravity in pixels per 0.1 s per 0.1 s
    if press {
      vy = -3.6
      sb = 1.3
      beep = 3
    }
    vy = min(vy + 0.75 * kt, 6.0)
    by = by + vy * kt
    if by < 0.0 {
      by = 0.0
      vy = 0.0
    }
    // drainpipes scroll left; one that leaves the screen comes back behind the last one with a new gap
    scroll = scroll + 2.2 * kt
    if floor(scroll) != oscroll {
      oscroll = floor(scroll)
      markAll()
    }
    var far: float = 0.0
    for i in 0..cx.length() { far = max(far, cx.get(i)) }
    for i in 0..cx.length() {
      let sx = cx.get(i) - scroll
      if sx < ${-CW}.0 {
        cx[i] = far + ${SPACING}.0
        cg[i] = floor(Random(8.0, ${GROUND - GAP - 8}.0))
        cs[i] = 0
        far = cx.get(i)
      } else {
        // passed it: score; touching it outside the gap: dead
        if cs.get(i) == 0 && sx + ${CW}.0 < ${BX}.0 {
          cs[i] = 1
          score += 1
          dingTune()
        }
        if sx < ${BX + 8}.0 && sx + ${CW}.0 > ${BX}.0 {
          let g = cg.get(i)
          if by < g || by + ${SH}.0 > g + ${GAP}.0 { die() }
        }
      }
    }
    if by + ${SH}.0 >= ${GROUND}.0 {
      by = ${GROUND - SH}.0
      die()
    }
  }
  let ny = floor(by)
  if ny != oby {
    markBird(oby)
    markBird(ny)
    oby = ny
  }
  if waiting {
    if over > 0 { hudv = "SPLAT.  SCORE \${score}  BEST \${best}  -  SPACE TO FLAP AGAIN" } else { hudv = "PRESS SPACE TO FLAP  BEST \${best}" }
  } else { hudv = "SCORE \${score}  BEST \${best}" }
}
mod idle() {
  if was {
    was = false
    cx.resize(0, 0.0)
    cg.resize(0, 0.0)
    cs.resize(0, 0)
    dl.resize(0, 0)
    dfl.fill(0)
    over = 0
    score = 0
    aV0 = 0.0
    titlev = "SOGGY SPARROW"
    mel.resize(0, 0.0)
    melPos = 0
    hudv = ""
${strips.map(k => `    st${k} = ""\n    pb${k} = ""`).join('\n')}
  }
}
mod flush() {
  for j in 0..dl.length() {
    let r = dl.get(j)
    dfl[r] = 0
    renderRow(r)
  }
  dl.resize(0, 0)
  for k in 0..${NS} {
    if sdf.get(k) == 1 {
      sdf[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}

${debug ? `on ChatCommand("fsdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("fsrow|${k}|" .. st${k})`).join('\n')}
}
on ChatCommand("fssit", "debug: play as if seated (toggle)") -> (ctrl, args) {
  forced = forced == false
}
on ChatCommand("fsflap", "debug: one flap") -> (ctrl, args) {
  if waiting {
    waiting = false
    titlev = ""
    if over > 0 { reset() }
  }
  vy = -3.6
}
` : ''}on ChatCommand("fscal", "Soggy Sparrow screen fit: h+ h- (row height) w+ w- (width)") -> (ctrl, args) {
  if args == "h+" { lhv = lhv * 1.05 }
  if args == "h-" { lhv = lhv / 1.05 }
  if args == "w+" { wsv = wsv * 1.05 }
  if args == "w-" { wsv = wsv / 1.05 }
  ctrl.DisplayText("row height \${lhv}  width \${wsv}", positionY = -300.0, fontSize = 30, lifetime = 3.0, textId = 9704)
  PrintToConsole("fscal|\${lhv}|\${wsv}")
}
on ServerUptime() {
  if seated || forced {
    if was == false {
      was = true
      rows.resize(${H}, "")
      dfl.resize(${H}, 0)
      sdf.resize(${NS}, 0)
      reset()
      waiting = true
      lastT = ServerUptime()
      oby = -100
      for r in 0..${H} { mark(r) }
    }
    step()
    flush()
    if pubDirty && ServerUptime() - pubT >= 1.0 / FPS - 0.001 {
      pubT = ServerUptime()
      publish()
    }
  } else {
    idle()
  }
}
on Change(seated) {
  if seated == false && forced == false { idle() }
}
`;
  return { src, W, H, STRIP, PAL, textColor: 'ffffff', clockWhenSeated: !debug, noClock: true, titleMid: true, titleLH: 4, exactScreen: true, textPorts: true, synths: ['Square'] };
}
