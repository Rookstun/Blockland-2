// landgrab/gen.mjs: LAND GRAB, a 4-player territory game on the Super Sigmas engine (tools/wspkg + landgrab/cabinet4.mjs).
// cake's wish ("4 player drop-in multiplayer land.io: like snake but hitting your own line flood-fills the area you enclose,
// 4 input seats, show the scores to the side"), original rules/art. 24 x 16 tiles of 2 x 2 block cells (48 x 32 picture).
//   Sit in any of the 4 seats to drop in (W A S D steers, you keep moving, no U-turns). Walking out of your colour leaves a trail;
//   when your head comes back onto your own colour or your own trail the loop closes and everything you enclosed becomes yours.
//   Cross another player's trail and THEY are knocked back to their corner. Rounds last 2 minutes; most land wins.
//   inputs: tick (20 Hz), seat0..3, l0..3 r0..3 u0..3 d0..3 (one set per seat)
//   outputs: strip0..strip7, msg_, hud_ (scores + time), title_, P0/V0 loop-closed blip, P1/V1 knock-back
export const W = 48, H = 32, STRIP = 4;
const TW = 24, TH = 16, N = TW * TH;
export const PAL = ['ececf4', 'd83030', '3060d8', '30b050', 'e8c020', 'f2a0a0', 'a0b8f2', 'a0dcae', 'f6e8a0', '101010'];
// tile kinds: 0 floor, 1-4 territory p0..p3, 5-8 trail p0..p3, 9-12 head p0..p3
const COL = [1, 2, 3, 4], TRAIL = [5, 6, 7, 8];
const LOOK = [[0, 0, 0, 0], ...COL.map(c => [c, c, c, c]), ...TRAIL.map(c => [c, c, c, c]), ...COL.map(c => [9, c, c, 9])];
const SX = [2, 21, 2, 21], SY = [2, 2, 13, 13], SD = [0, 2, 0, 2]; // start cell centre, direction 0 right 1 down 2 left 3 up
const ROUND = 2400;

const A = xs => `[${xs.join(', ')}]`;

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, PH = 2, ROWS_PH = TH / PH;
  const OPEN = PAL.map((h, i) => i === 0 ? '' : `<color="${h}">`), CLOSE = PAL.map((_, i) => i === 0 ? '' : '</>');
  const BLK = Array.from({ length: W + 1 }, (_, n) => '█'.repeat(n));
  const stripCode = ks => ks.map(k => `    st${k} = ${Array.from({ length: STRIP }, (_, j) => `rows[${k * STRIP + j}]`).join(' .. "\\n" .. ')}`).join('\n');
  const push = (s, c) => `      if ${c} == c${s} { n${s} += 1 } else {
        if n${s} > 0 { s${s} = s${s} .. OPEN[c${s}] .. BLK[n${s}] .. CLOSE[c${s}] }
        c${s} = ${c}
        n${s} = 1
      }`;
  const phaseStrips = ph => Array.from({ length: NS / PH }, (_, j) => ph * (NS / PH) + j);

  const src = `// GENERATED by landgrab/gen.mjs: edit that, not this file.
// LAND GRAB: logic every 'tick' (20 Hz) while somebody sits; a player steps once every 4 ticks; the picture renders half a frame a tick.

@left in tick: exec
${[0, 1, 2, 3].map(p => `@left in seat${p}: bool`).join('\n')}
${[0, 1, 2, 3].map(p => `@left in l${p}: bool\n@left in r${p}: bool\n@left in u${p}: bool\n@left in d${p}: bool`).join('\n')}

const SX = ${A(SX)}
const SY = ${A(SY)}
const SD = ${A(SD)}
const LOOK = ${A(LOOK.flat())}
const OPEN = ${JSON.stringify(OPEN)}
const CLOSE = ${JSON.stringify(CLOSE)}
const BLK = ${JSON.stringify(BLK)}
const NAMES = ["RED", "BLU", "GRN", "YLW"]

var state: int = 0           // 1 playing, 2 round over
var stT: int = 0
var t: int = 0
var stepT: int = 0
var timer: int = ${ROUND}
var booted: bool = false
var own: int[] = [${Array(N).fill(0).join(', ')}]
var trl: int[] = [${Array(N).fill(0).join(', ')}]
var seen: int[] = [${Array(N).fill(0).join(', ')}]
var q: int[] = [${Array(N).fill(0).join(', ')}]
var qh: int = 0
var qt: int = 0
var fillP: int = -1
var fillOn: bool = false
var act: int[] = [0, 0, 0, 0]
var sit: bool[] = [false, false, false, false]
var key: bool[] = [${Array(16).fill('false').join(', ')}]
var pxp: int[] = [0, 0, 0, 0]
var pyp: int[] = [0, 0, 0, 0]
var dr: int[] = [0, 0, 0, 0]
var tl: int[] = [0, 0, 0, 0]
var sc: int[] = [0, 0, 0, 0]
var heads: int[] = [0, 0, 0, 0]
var msg: string = ""
var msgT: int = 0
var hud: string = ""
var blipT: int = -99
var hitT: int = -99
var aP0: float = 1.0
var aV0: float = 0.0
var aP1: float = 1.0
var aV1: float = 0.0
var rows: string[] = [${Array(H).fill('""').join(', ')}]
${Array.from({ length: NS }, (_, k) => `var st${k}: string = ""`).join('\n')}

${Array.from({ length: NS }, (_, k) => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = msg
@right out hud_: string = hud
@right out title_: string = if state == 0 then "LAND GRAB" else ""
@right out P0: float = aP0
@right out V0: float = aV0
@right out P1: float = aP1
@right out V1: float = aV1
@right out state_: int = state

mod showHud() {
  hud = "R " .. sc[0] .. "  B " .. sc[1] .. "  G " .. sc[2] .. "  Y " .. sc[3] .. "   " .. floor(timer / 20) .. "s"
}

mod say(s: string, n: int) {
  msg = s
  msgT = n
}

mod recount() {
  for p in 0..4 { sc[p] = 0 }
  for i in 0..${N} {
    let o = own[i]
    if o > 0 { sc[o - 1] = sc[o - 1] + 1 }
  }
  showHud()
}

mod respawn(p: int) {
  pxp[p] = SX[p]
  pyp[p] = SY[p]
  dr[p] = SD[p]
  tl[p] = 0
}

mod join(p: int) {
  act[p] = 1
  respawn(p)
  for j in 0..9 {
    let r = SY[p] - 1 + floor(j / 3)
    let c = SX[p] - 1 + j % 3
    own[r * ${TW} + c] = p + 1
    trl[r * ${TW} + c] = 0
  }
  recount()
}

mod clearTrail(p: int) {
  for i in 0..${N} {
    if trl[i] == p + 1 { trl[i] = 0 }
  }
  tl[p] = 0
}

mod leave(p: int) {
  act[p] = 0
  for i in 0..${N} {
    if own[i] == p + 1 { own[i] = 0 }
    if trl[i] == p + 1 { trl[i] = 0 }
  }
  tl[p] = 0
  recount()
}

mod die(p: int) {
  clearTrail(p)
  respawn(p)
  hitT = t
}

mod pushQ(i: int) {
  if seen[i] == 0 && own[i] != fillP + 1 {
    seen[i] = 1
    q[qt] = i
    qt += 1
  }
}

mod closeLoop(p: int) {
  if !fillOn {
    for i in 0..${N} {
      if trl[i] == p + 1 {
        trl[i] = 0
        own[i] = p + 1
      }
    }
    tl[p] = 0
    fillP = p
    fillOn = true
    qh = 0
    qt = 0
    for i in 0..${N} { seen[i] = 0 }
    for c in 0..${TW} {
      pushQ(c)
      pushQ(${(TH - 1) * TW} + c)
    }
    for r in 1..${TH - 1} {
      pushQ(r * ${TW})
      pushQ(r * ${TW} + ${TW - 1})
    }
    blipT = t
  }
}

mod fillStep() {
  for k in 0..64 {
    if qh < qt {
      let i = q[qh]
      qh += 1
      let r = floor(i / ${TW})
      let c = i % ${TW}
      if c > 0 { pushQ(i - 1) }
      if c < ${TW - 1} { pushQ(i + 1) }
      if r > 0 { pushQ(i - ${TW}) }
      if r < ${TH - 1} { pushQ(i + ${TW}) }
    }
  }
  if qh >= qt {
    for i in 0..${N} {
      if seen[i] == 0 && own[i] != fillP + 1 {
        own[i] = fillP + 1
        trl[i] = 0
      }
    }
    fillOn = false
    fillP = -1
    recount()
  }
}

mod stepPlayer(p: int) {
  var d = dr[p]
  if key[p * 4 + 2] { d = 3 }
  else if key[p * 4 + 3] { d = 1 }
  else if key[p * 4] { d = 2 }
  else if key[p * 4 + 1] { d = 0 }
  if (d + 2) % 4 == dr[p] { d = dr[p] }
  dr[p] = d
  var nx = pxp[p]
  var ny = pyp[p]
  if d == 0 { nx += 1 }
  else if d == 1 { ny += 1 }
  else if d == 2 { nx -= 1 }
  else { ny -= 1 }
  if nx >= 0 && nx < ${TW} && ny >= 0 && ny < ${TH} {
    let i = ny * ${TW} + nx
    let tq = trl[i]
    if tq > 0 && tq != p + 1 { die(tq - 1) }
    pxp[p] = nx
    pyp[p] = ny
    if tq == p + 1 || (own[i] == p + 1 && tl[p] > 0) {
      closeLoop(p)
    } else if own[i] != p + 1 {
      trl[i] = p + 1
      tl[p] += 1
    }
  }
}

mod resetRound() {
  for i in 0..${N} {
    own[i] = 0
    trl[i] = 0
  }
  fillOn = false
  fillP = -1
  timer = ${ROUND}
  state = 1
  stepT = 0
  for p in 0..4 {
    if act[p] == 1 { join(p) }
  }
  recount()
  say("GO", 30)
}

mod endRound() {
  state = 2
  stT = 0
  var best: int = 0
  for p in 1..4 {
    if sc[p] > sc[best] { best = p }
  }
  say(NAMES[best] .. " WINS " .. sc[best], 0)
}

mod stamp() {
  for p in 0..4 { heads[p] = 0 }
}

mod compose(r0: int, r1: int) {
  for ty in r0..r1 {
    var sT: string = ""
    var cT: int = -1
    var nT: int = 0
    var sB: string = ""
    var cB: int = -1
    var nB: int = 0
    for tx in 0..${TW} {
      let i = ty * ${TW} + tx
      var k: int = own[i]
      if trl[i] > 0 { k = 4 + trl[i] }
      for p in 0..4 {
        if act[p] == 1 && pxp[p] == tx && pyp[p] == ty { k = 9 + p }
      }
      let o = k * 4
      let a = LOOK[o]
      let b = LOOK[o + 1]
      let c = LOOK[o + 2]
      let d = LOOK[o + 3]
${push('T', 'a')}
${push('T', 'b')}
${push('B', 'c')}
${push('B', 'd')}
    }
    rows[ty * 2] = sT .. OPEN[cT] .. BLK[nT] .. CLOSE[cT]
    rows[ty * 2 + 1] = sB .. OPEN[cB] .. BLK[nB] .. CLOSE[cB]
  }
}

mod powerOn() {
  booted = true
  for p in 0..4 { act[p] = 0 }
  resetRound()
  say("DROP IN: SIT IN ANY SEAT", 60)
}

mod powerOff() {
  booted = false
  state = 0
  msg = ""
  hud = ""
${Array.from({ length: NS }, (_, k) => `  st${k} = ""`).join('\n')}
  aV0 = 0.0
  aV1 = 0.0
}

${debug ? `var dbk: string = ""
var dumpReq: bool = false
on ChatCommand("lg", "LANDGRAB debug: /lg <S0..S3 sit, L0 R0 U0 D0 keys per player> | dump | end") -> (ctrl, args) {
  if args == "dump" { dumpReq = true }
  else if args == "end" { timer = 1 }
  else { dbk = args }
}
` : ''}on tick {
${debug ? `  let s0 = seat0 || dbk.Contains("S0")
  let s1 = seat1 || dbk.Contains("S1")
  let s2 = seat2 || dbk.Contains("S2")
  let s3 = seat3 || dbk.Contains("S3")` : `  let s0 = seat0
  let s1 = seat1
  let s2 = seat2
  let s3 = seat3`}
  let any = s0 || s1 || s2 || s3
  if !any {
    if booted { powerOff() }
  } else {
    if !booted { powerOn() }
    sit[0] = s0
    sit[1] = s1
    sit[2] = s2
    sit[3] = s3
${debug ? [0, 1, 2, 3].map(p => `    key[${p * 4}] = l${p} || dbk.Contains("L${p}")
    key[${p * 4 + 1}] = r${p} || dbk.Contains("R${p}")
    key[${p * 4 + 2}] = u${p} || dbk.Contains("U${p}")
    key[${p * 4 + 3}] = d${p} || dbk.Contains("D${p}")`).join('\n') : [0, 1, 2, 3].map(p => `    key[${p * 4}] = l${p}
    key[${p * 4 + 1}] = r${p}
    key[${p * 4 + 2}] = u${p}
    key[${p * 4 + 3}] = d${p}`).join('\n')}
${debug ? `    if t % 20 == 0 { PrintToConsole("lgdbg|" .. t .. "|" .. state .. "|timer " .. timer .. "|sc " .. sc[0] .. "," .. sc[1] .. "," .. sc[2] .. "," .. sc[3] .. "|p0 " .. pxp[0] .. "," .. pyp[0] .. " tl " .. tl[0] .. "|fill " .. fillOn) }
    if dumpReq && t % 2 == 1 {
      dumpReq = false
      for r in 0..${H} { PrintToConsole("lgrow|" .. r .. "|" .. rows[r]) }
    }` : ''}
    t += 1
    for p in 0..4 {
      if sit[p] && act[p] == 0 { join(p) }
      if !sit[p] && act[p] == 1 { leave(p) }
    }
    if state == 1 {
      stepT += 1
      if stepT >= 4 {
        stepT = 0
        for p in 0..4 {
          if act[p] == 1 { stepPlayer(p) }
        }
      }
      if fillOn { fillStep() }
      timer -= 1
      if timer % 20 == 0 { showHud() }
      if timer <= 0 { endRound() }
    } else if state == 2 {
      stT += 1
      if stT >= 100 { resetRound() }
    }
    if msgT > 0 {
      msgT -= 1
      if msgT == 0 { msg = "" }
    }
    let be = t - blipT
    aV0 = if be < 5 then 0.4 else 0.0
    aP0 = 1.4 + be * 0.2
    let he = t - hitT
    aV1 = if he < 8 then 0.6 else 0.0
    aP1 = 1.0
    let ph = t % ${PH}
    compose(ph * ${ROWS_PH}, ph * ${ROWS_PH} + ${ROWS_PH})
    if ph == 0 {
${stripCode(phaseStrips(0))}
    } else {
${stripCode(phaseStrips(1))}
    }
  }
}
`;
  return { src, W, H, STRIP, PAL, synths: ['Square', 'Noise'] };
}
