// node laptimer/build.mjs [halfWidth=200] -> laptimer/laptimer.brz. Load: br.Prefab.Load "laptimer" x y z <quarter turns> 16
// Start/finish line for a kart track: a flat BP_ZoneProjector slab across the track (zone up 200) wired into ONE hidden
// chip; each crossing by a player (debounced 5 s) = a lap for that name: HUD line to the racer + a gantry board
// (last 4 laps, best lap). Built for travel along +y at quarter turn 0 (board faces -y, toward the oncoming karts).
import fs from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundle } from '../tools/wsbundle.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const HW = +(process.argv[2] ?? 200);
const OWNER = { id: 'a9700000-0000-4b0b-9a11-00000000a970', name: 'Lap Timer', display_name: 'Lap Timer' };
const src = `// GENERATED by laptimer/build.mjs
in line: zone
var last: Map<string, float>
var best: float = 0.0
var bestName: string = "-"
var log: string = ""
var boardv: string = "START / FINISH\\ndrive through to start a lap"
var cs: int = 0
@right out board: string = boardv

mod fmt(t: float) -> string {
  cs = round(t * 100.0)
  let fr = cs % 100
  if fr < 10 { return "\${cs / 100}.0\${fr}" }
  return "\${cs / 100}.\${fr}"
}

on ZoneEntered(zone = line) -> (racer) {
  let c = racer.ControllerOf()
  let name = c.GetUserName()
  let now = ServerUptime()
  let g = last.get(name)
  if g.Found {
    let lap = now - g.Value
    if lap > 5.0 {
      last.set(name, now)
      let s = fmt(lap)
      var tag: string = ""
      tag = ""
      if best == 0.0 || lap < best {
        best = lap
        bestName = name
        tag = "  NEW BEST"
      }
      c.DisplayText("LAP \${s}\${tag}", positionY = -250.0, fontSize = 40, lifetime = 4.0, textId = 9701)
      log = "\${name}  \${s}\\n" .. log.Substring(0, 120)
      boardv = "BEST \${fmt(best)}  \${bestName}\\n" .. log
    }
  } else {
    last.set(name, now)
    c.DisplayText("LAP STARTED", positionY = -250.0, fontSize = 40, lifetime = 3.0, textId = 9701)
  }
}
`;
fs.writeFileSync(join(here, 'laptimer.gen.ws'), src);
const sdk = join(here, '..', 'tools', 'wspkg');
const wasm = await import(pathToFileURL(join(sdk, 'wasm.js')).href);
if (typeof wasm.default === 'function') await wasm.default({ module_or_path: fs.readFileSync(join(sdk, 'wasm_bg.wasm')) });
const compile = wasm.wirescript_compile ?? wasm.default?.wirescript_compile, diag = wasm.wirescript_diagnostics ?? wasm.default?.wirescript_diagnostics;
const ds = JSON.parse(diag(src, 'laptimer', '{}') || '[]');
for (const d of ds) console.error(`${d.severity} ${d.code} line ${d.startLine}: ${d.message}`);
if (ds.some(d => /error/i.test(d.severity))) throw Error('wirescript errors');
const b = await bundle(new Uint8Array(compile(src, 'laptimer', '{}', '{}')), { owner: OWNER, offset: [HW + 40, 0, 230], hide: true, bare: true });
const { w, C, O } = b;
const assets = [...b.ext];
const fontIdx = (() => { assets.push({ type: 'BrickFontDescriptor', name: 'Bungee' }); return assets.length - 1; })();
const MB = 'PB_DefaultMicroBrick', box = (x0, y0, z0, x1, y1, z1, m = {}) => w.addBrick({ asset: MB, color: [40, 40, 44], ...m,
  size: [(x1 - x0) / 2, (y1 - y0) / 2, (z1 - z0) / 2], position: [(x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2], owner_index: O });
// zone slab on the road (4 units thick, no player collision), zone 200 up; checker strip painted on it
const zone = w.addBrick({ asset: 'BP_ZoneProjector', size: [HW, 10, 2], position: [0, 0, 2], color: [240, 240, 240], owner_index: O, collision: { player: false, weapon: false, interaction: false, tool: true, physics: false }, // z half 2 as realestate/lotchip.mjs (half 1 = 'Missing brick type')
  components: [{ type: 'Component_Internal_AttachedZone', data: { ZoneStartDistance: 0, ZoneEndDistance: 200, bIsBuildingZone: false, bIsLooseZone: false,
    bIsShareZone: false, bWater: false, bDetectPlayers: true, bDetectPlayers1: true, bDetectPlayers2: true, bDetectPlayers3: true } }] });
// gantry: two posts outside the track + a beam with the board facing -y
box(-HW - 30, -10, 0, -HW - 10, 10, 260); box(HW + 10, -10, 0, HW + 30, 10, 260);
box(-HW - 30, -10, 260, HW + 30, 10, 280, { color: [200, 30, 40] });
const TEXT = { Font: fontIdx, Rotation: 0, Skew: 0, Kerning: 0, LineHeight: 9, WidthScale: 1, LineOffset: 0, Anchor: { X: 0.5, Y: 0.5 }, Offset: { X: 0, Y: 0, Z: 0.2 },
  Color: { R: 255, G: 230, B: 90, A: 255 }, MaterialSlider: 10, ShadingWidth: 0, OutlineColor: { R: 0, G: 0, B: 0, A: 255 }, OutlineWidth: 2, ScuffWidth: 0, GraffitiDepthLimit: 5,
  GraffitiAngleLimit: 45, GraffitiLayer: 0, bEnabled: true, Face: 3, bAlignToWedge: false, bOverrideColor: true, Typeface: 0, Billboard: 0, Material: 0, Shading: 0,
  bFlipShading: false, Outline: 2, bSharpCorners: true, bSharpOutlines: true, bOverrideOutlineColor: true, bForeground: false, Text: '' };
const board = box(-HW + 20, -12, 180, HW - 20, -10, 258, { color: [12, 12, 16], components: [{ type: C.TextDisplay.NAME, data: TEXT }] });
w.addWire({ brick: zone, component_type: 'Component_Internal_AttachedZone', port: 'ZoneRef' }, { brick: b.portIn('line'), component_type: 'BrickComponentType_Internal_MicrochipInput', port: 'RER_Input' });
w.addWire({ brick: b.portOut('board'), component_type: 'BrickComponentType_Internal_MicrochipOutput', port: 'RER_Output' }, { brick: board, component_type: C.TextDisplay.NAME, port: 'Text' });
fs.writeFileSync(join(here, 'laptimer.brz'), b.finish({ extraAssets: assets.slice(b.ext.length), description: 'lap timer' }));
console.log(`wrote laptimer.brz (track half width ${HW})`);
