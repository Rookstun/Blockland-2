// linescreen/wgen.mjs: a 64x96 raster screen that draws one line between two 2D vector inputs (Computational En2ty,
// 2026-11-06): inputs `a` and `b` (vector; x = column, y = row, (0,0) = top left, y grows downward). A 1-px line
// covers one contiguous run of pixels on each row it crosses, so every row is ONE interval, drawn as SP/BL substrings
// (Night Pong's row trick); the screen is redrawn on any input change. /line x0 y0 x1 y1 sets it from chat too.
export const W = 96, H = 64, STRIP = 16; // v2 (Computational En2ty): 96 wide x 64 tall, one 2-unit micro brick a pixel
export const PAL = ['000000'];

export function generate({ cell = 2 } = {}) {
  const NS = H / STRIP, q = JSON.stringify, strips = Array.from({ length: NS }, (_, k) => k);
  const src = `// GENERATED by linescreen/wgen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool
@left in a: vector
@left in b: vector

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}
${strips.map(k => `var st${k}: string = ""`).join('\n')}
var x0: float = 0.0
var y0: float = 0.0
var x1: float = ${W - 1}.0
var y1: float = ${H - 1}.0
var hudv: string = ""
var sel: int = 0
var lastUp: bool = false
var lastDown: bool = false
var lastT: float = 0.0
var lhv: float = ${+(cell * 0.645).toFixed(4)}
var wsv: float = 2.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "sit: W/S pick a slider, A/D slide it  -  inputs a, b (vector) or /line x0 y0 x1 y1"
@right out hud_: string = hudv
@right out title_: string = ""
@right out lh_: float = lhv
@right out ws_: float = wsv
@right out P0: float = 1.0
@right out V0: float = 0.0

// one slider bar: 10 cells, the knob where the value sits; the selected one is marked with >
mod bar(name: string, v: float, max: float, me: int) -> string {
  let n = floor(v / max * 9.0 + 0.5)
  var b: string = ""
  b = ""
  for i in 0..10 { if i == n { b = b .. "|" } else { b = b .. "-" } }
  let mark = if sel == me then ">" else " "
  return mark .. name .. " [" .. b .. "] \${v}"
}
mod bars(ax: float, ay: float, bx: float, by: float) -> string {
  return bar("A.X", ax, ${W - 1}.0, 0) .. "  " .. bar("A.Y", ay, ${H - 1}.0, 1) .. "  " .. bar("B.X", bx, ${W - 1}.0, 2) .. "  " .. bar("B.Y", by, ${H - 1}.0, 3)
}
mod draw() {
  let ax = min(max(round(x0), 0.0), ${W - 1}.0)
  let ay = min(max(round(y0), 0.0), ${H - 1}.0)
  let bx = min(max(round(x1), 0.0), ${W - 1}.0)
  let by = min(max(round(y1), 0.0), ${H - 1}.0)
  let top = min(ay, by)
  let bot = max(ay, by)
  let dy = by - ay
  hudv = bars(ax, ay, bx, by)
  var acc: string = ""
  for k in 0..${NS} {
    acc = ""
    for j in 0..${STRIP} {
      let r = k * ${STRIP} + j
      var line: string = ""
      line = SP
      if r >= top && r <= bot {
        var s: float = 0.0
        var e: float = 0.0
        if dy == 0.0 {
          s = min(ax, bx)
          e = max(ax, bx) + 1.0
        } else {
          // x where the line enters and leaves this row (half a row either side), clipped to the segment
          let t0 = min(max((r - 0.5 - ay) / dy, 0.0), 1.0)
          let t1 = min(max((r + 0.5 - ay) / dy, 0.0), 1.0)
          let xa = ax + (bx - ax) * t0
          let xb = ax + (bx - ax) * t1
          s = round(min(xa, xb))
          e = round(max(xa, xb)) + 1.0
        }
        s = max(s, 0.0)
        e = min(e, ${W}.0)
        line = SP.Substring(0, s) .. BL.Substring(0, e - s) .. SP.Substring(0, ${W}.0 - e)
      }
      if j < ${STRIP - 1} { acc = acc .. line .. "\\n" } else { acc = acc .. line }
    }
${strips.map(k => `    if k == ${k} { st${k} = acc }`).join('\n')}
  }
}
on Change(a) {
  x0 = a.x
  y0 = a.y
  draw()
}
on Change(b) {
  x1 = b.x
  y1 = b.y
  draw()
}
on ChatCommand("line", "draw a line on the 64x96 screen: /line x0 y0 x1 y1 (0,0 top left)") -> (ctrl, args) {
  // Split cuts once (Left / Right / Found): peel the four numbers off one at a time
  let s1 = args.Split(" ")
  let s2 = s1.Right.Split(" ")
  let s3 = s2.Right.Split(" ")
  if s3.Found {
    x0 = ParseNumber(s1.Left)
    y0 = ParseNumber(s2.Left)
    x1 = ParseNumber(s3.Left)
    y1 = ParseNumber(s3.Right)
    draw()
  }
}
on ChatCommand("lscal", "line screen fit: h+ h- w+ w-") -> (ctrl, args) {
  if args == "h+" { lhv = lhv * 1.05 }
  if args == "h-" { lhv = lhv / 1.05 }
  if args == "w+" { wsv = wsv * 1.05 }
  if args == "w-" { wsv = wsv / 1.05 }
  PrintToConsole("lscal|\${lhv}|\${wsv}")
}
on ServerUptime() {
  if st0 == "" { draw() }
  let now = ServerUptime()
  let dt = min(max(now - lastT, 0.0), 0.2)
  lastT = now
  if seated {
    // slider select (fix: the redraw check ran after lastUp/lastDown were overwritten, so the marker never moved)
    let pu = up && lastUp == false
    let pd = down && lastDown == false
    lastUp = up
    lastDown = down
    if pu { sel = (sel + 3) % 4 }
    if pd { sel = (sel + 1) % 4 }
    if pu || pd { draw() }
    let d = (if right then 1.0 else 0.0) - (if left then 1.0 else 0.0)
    if d != 0.0 {
      let step = d * 30.0 * dt // 30 pixels a second
      if sel == 0 { x0 = min(max(x0 + step, 0.0), ${W - 1}.0) }
      if sel == 1 { y0 = min(max(y0 + step, 0.0), ${H - 1}.0) }
      if sel == 2 { x1 = min(max(x1 + step, 0.0), ${W - 1}.0) }
      if sel == 3 { y1 = min(max(y1 + step, 0.0), ${H - 1}.0) }
      draw()
    }
  }
}
`;
  return { src, W, H, STRIP, PAL, textColor: 'ffffff', clockWhenSeated: false, noClock: true, titleMid: true, titleLH: 4, exactScreen: true, textPorts: true, synths: ['Square'], seatBack: 140 }; // seat 14 studs back from the 192-wide screen
}

// the same span math in JS, for the self-check / tests: which columns row r lights for a line a -> b
export function spanJS([ax, ay], [bx, by], r) {
  if (r < Math.min(ay, by) || r > Math.max(ay, by)) return null;
  const dy = by - ay;
  if (dy === 0) return [Math.min(ax, bx), Math.max(ax, bx) + 1];
  const c = t => Math.min(Math.max(t, 0), 1), t0 = c((r - 0.5 - ay) / dy), t1 = c((r + 0.5 - ay) / dy);
  const xa = ax + (bx - ax) * t0, xb = ax + (bx - ax) * t1;
  return [Math.max(Math.round(Math.min(xa, xb)), 0), Math.min(Math.round(Math.max(xa, xb)) + 1, W)];
}
