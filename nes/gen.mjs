// nes/gen.mjs: the NES cabinet chip (wirescript). The emulator runs on the server (nes/host.mjs); this chip is only
// the screen + controller. Frames arrive as chat commands "/nes <first strip digit><cells>" (1 char a cell = index
// into the 64 NES colours, ALPHA's first 64 chars, 48 cells a row, 4 rows a strip, up to 2 strips a line) and are
// turned into the cabinet's block-text strips. The pad goes out as console line "nesin|<mask>" on every change:
// A 1, B 2, Select 4, Start 8, Up 16, Down 32, Left 64, Right 128, seated 256 (up+down = Start, left+right = Select).
import { PALETTE } from './src/ppu.mjs';

export const W = 48, H = 36, STRIP = 4;
export const AL = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!#'; // 64 safe chat chars
export const PAL = Array.from(PALETTE, c => [c & 255, c >> 8 & 255, c >> 16 & 255].map(v => v.toString(16).padStart(2, '0')).join(''));

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, q = JSON.stringify, A = xs => `[${xs.join(', ')}]`;
  const OPEN = PAL.map(h => `<color="${h}">`), CLOSE = PAL.map(() => '</>');
  const BLK = Array.from({ length: W + 1 }, (_, n) => '█'.repeat(n));
  const MAP = Array.from({ length: 94 }, (_, i) => AL.indexOf(String.fromCharCode(33 + i)));
  const strips = Array.from({ length: NS }, (_, k) => k);
  const src = `// GENERATED by nes/gen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const W = ${W}
const OPEN = ${A(OPEN.map(q))}
const CLOSE = ${A(CLOSE.map(q))}
const BLK = ${A(BLK.map(q))}
const MAP = ${A(MAP)}

${strips.map(k => `var st${k}: string = ""`).join('\n')}
var rowOut: string = ""
var last: int = -1

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = ""
@right out hud_: string = ""
@right out title_: string = "NES"

mod encRow(src: string, off: int) {
  var s: string = ""
  var c0: int = -1
  var n: int = 0
  for c in 0..W {
    let p = MAP[src.Substring(off + c, 1).ToCharCode().Codepoint - 33]
    if p == c0 {
      n += 1
    } else {
      if n > 0 { s = s .. OPEN[c0] .. BLK[n] .. CLOSE[c0] }
      c0 = p
      n = 1
    }
  }
  rowOut = s .. OPEN[c0] .. BLK[n] .. CLOSE[c0]
}
mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { st${k} = v }`).join('\n')}
}

on ChatCommand("nes", "NES frame feed (host.mjs)") -> (ctrl, args) {
  let k0 = args.Substring(0, 1).ToCharCode().Codepoint - 48
  let n = (args.Length() - 1) / ${W * STRIP}
  for s in 0..n {
    var acc: string = ""
    acc = ""
    for r in 0..${STRIP} {
      encRow(args, 1 + (s * ${STRIP} + r) * W)
      if r < ${STRIP - 1} { acc = acc .. rowOut .. "\\n" } else { acc = acc .. rowOut }
    }
    setStrip(k0 + s, acc)
  }
}

${debug ? `on ChatCommand("nesdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("nesrow|${k}|" .. st${k})`).join(String.fromCharCode(10))}
}
` : ''}on tick {
  var m: int = 0
  if seated { m = 256 }
  if ba { m += 1 }
  if bb { m += 2 }
  if up && down { m += 8 } else {
    if up { m += 16 }
    if down { m += 32 }
  }
  if left && right { m += 4 } else {
    if left { m += 64 }
    if right { m += 128 }
  }
  if m != last {
    last = m
    PrintToConsole("nesin|" .. m)
  }
}
`;
  return { src, W, H, STRIP, PAL, synths: [] };
}
