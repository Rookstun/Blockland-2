// parry/gen.mjs: PARRY OR PERISH on the Super Sigmas engine (tools/wspkg + supersigmas/cabinet.mjs). Rookstun's wish
// (a parry game; original knight vs horned demon, original music). 24 x 16 tiles of 2 x 2 block cells (48 x 32 picture).
// The demon winds up a HIGH (yellow) or LOW (orange) strike; the last 7 ticks the tile flashes WHITE: press the right parry then.
//   Space / RMB = high parry, LMB / E = low parry. Only your FIRST press of a wind-up counts. Feints never flash white: don't press.
//   Within 3 ticks of the hit = PERFECT (2 damage). Pressing early / wrong / late = you take the hit. 3 demons, then they loop faster.
//   inputs: tick (20 Hz), seated, a (Space / RMB), b (LMB / E)
//   outputs: strip0..strip7, msg_, hud_, title_, P0/V0 clang, P1/V1 hit, P2/V2 lead, P3/V3 bass
export const W = 48, H = 32, STRIP = 4;
const TW = 24, TH = 16, N = TW * TH;
export const PAL = ['16122c', '4a4458', '6a6478', 'e8e4c0', '3a6ad0', 'f0c898', 'f6f6f6', '5a1020', 'c02030', 'f8d040', '2a2440', 'ff7020', 'a0c0ff', '20a040', 'b0b0c0', '000000'];
// tile kinds: 0 sky, 1 floor, 2 floor top, 3 moon, 4 knight body, 5 knight head, 6 white (blade / flash), 7 demon body, 8 demon head,
// 9 high warning, 10 pillar, 11 low warning, 12 slash, 13 spark, 14 knight legs, 15 demon legs, 16 demon head angry
const LOOK = [[0, 0, 0, 0], [1, 10, 1, 1], [2, 2, 1, 2], [3, 3, 3, 3], [4, 4, 4, 12], [10, 10, 5, 5], [6, 6, 12, 6], [7, 7, 7, 8], [7, 8, 8, 7],
  [9, 9, 9, 9], [10, 1, 10, 10], [11, 11, 11, 11], [6, 6, 8, 8], [9, 6, 6, 9], [4, 4, 10, 10], [7, 7, 15, 15], [8, 9, 8, 9]];

// original music: eighth = 4 ticks (150 bpm), A minor
const NOTE = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
function song(s) {
  const p = [], t = [];
  for (const tok of s.trim().split(/\s+/)) {
    const [n, d] = tok.split(':');
    if (n === 'R') p.push(0);
    else { const m = n.match(/^([A-G])(#?)(\d)$/); p.push(+(2 ** ((12 * (+m[3] + 1) + NOTE[m[1]] + (m[2] ? 1 : 0) - 69) / 12)).toFixed(4)); }
    t.push(+d * 4);
  }
  return { p, t };
}
const LEAD = song(`A4:2 C5:1 E5:1 A5:2 G5:1 E5:1  F5:2 A4:1 C5:1 F5:2 E5:1 C5:1  G4:2 B4:1 D5:1 G5:2 F5:1 D5:1  E5:2 G#5:1 B5:1 E5:2 D5:1 B4:1
  A4:2 C5:1 E5:1 A5:2 B5:1 C6:1  D5:2 F5:1 A5:1 D6:2 C6:1 A5:1  E5:2 G#5:1 B5:1 E6:2 D6:1 B5:1  A5:4 E5:2 A4:2`);
const BASS = song(['A2', 'F2', 'G2', 'E2', 'A2', 'D2', 'E2', 'A2'].map(n => `${n}:1 R:1 ${n}:1 R:1 ${n}:1 R:1 ${n}:1 R:1`).join(' '));

const LEVELS = [{ foe: 5 }, { foe: 6 }, { foe: 8 }];
const NLV = LEVELS.length;

const A = xs => `[${xs.join(', ')}]`;

function scene() {
  const g = Array(N).fill(0);
  const set = (r, c, k) => { g[r * TW + c] = k; };
  for (let c = 0; c < TW; c++) { set(14, c, 2); set(15, c, 1); }
  for (const c of [9, 14]) for (let r = 5; r <= 13; r++) set(r, c, 10);
  for (const [r, c] of [[2, 4], [2, 5], [3, 4], [3, 5]]) set(r, c, 3);
  for (const c of [4, 5]) { set(11, c, 5); set(12, c, 4); set(13, c, 14); }
  for (const c of [17, 18, 19]) { set(10, c, 8); set(11, c, 7); set(12, c, 7); set(13, c, 15); }
  return g;
}

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, PH = 2, ROWS_PH = TH / PH;
  const OPEN = PAL.map((h, i) => i === 0 ? '' : `<color="${h}">`), CLOSE = PAL.map((_, i) => i === 0 ? '' : '</>');
  const BLK = Array.from({ length: W + 1 }, (_, n) => '█'.repeat(n));
  const BAR = Array.from({ length: 13 }, (_, n) => '#'.repeat(n));
  const stripCode = ks => ks.map(k => `    st${k} = ${Array.from({ length: STRIP }, (_, j) => `rows[${k * STRIP + j}]`).join(' .. "\\n" .. ')}`).join('\n');
  const push = (s, c) => `      if ${c} == c${s} { n${s} += 1 } else {
        if n${s} > 0 { s${s} = s${s} .. OPEN[c${s}] .. BLK[n${s}] .. CLOSE[c${s}] }
        c${s} = ${c}
        n${s} = 1
      }`;
  const phaseStrips = ph => Array.from({ length: NS / PH }, (_, j) => ph * (NS / PH) + j);

  const src = `// GENERATED by parry/gen.mjs: edit that, not this file.
// PARRY OR PERISH: logic every 'tick' (20 Hz) while 'seated'; the picture renders half a frame a tick.

@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in a: bool
@left in b: bool

const MAP = ${A(scene())}
const FOES = ${A(LEVELS.map(l => l.foe))}
const LOOK = ${A(LOOK.flat())}
const OPEN = ${JSON.stringify(OPEN)}
const CLOSE = ${JSON.stringify(CLOSE)}
const BLK = ${JSON.stringify(BLK)}
const BAR = ${JSON.stringify(BAR)}
const LP = ${A(LEAD.p)}
const LT = ${A(LEAD.t)}
const BP = ${A(BASS.p)}
const BT = ${A(BASS.t)}

var state: int = 0           // 0 title, 1 idle, 2 wind-up, 3 result, 4 demon down, 5 game over
var stT: int = 0
var t: int = 0
var booted: bool = false
var cur: int[] = ${A(scene())}
var act: int[] = [${Array(N).fill(0).join(', ')}]
var oldA: int[] = [${Array(16).fill(0).join(', ')}]
var nA: int = 0
var lvl: int = 0
var score: int = 0
var hp: int = 5
var foe: int = 5
var combo: int = 0
var rnd: int = 12345
var idleT: int = 30
var wind: int = 28
var atk: int = 0
var feint: bool = false
var pT: int = -1
var pK: int = -1
var resKind: int = 0
var pA: bool = false
var pB: bool = false
var msg: string = ""
var msgT: int = 0
var hud: string = ""
var clangT: int = -99
var clangP: float = 1.4
var hitT: int = -99
var mi: int = 0
var mt: int = 1
var bi: int = 0
var bt: int = 1
var aP2: float = 1.0
var aV2: float = 0.0
var aP3: float = 1.0
var aV3: float = 0.0
var aP0: float = 1.0
var aV0: float = 0.0
var aP1: float = 1.0
var aV1: float = 0.0
var rows: string[] = [${Array(H).fill('""').join(', ')}]
${Array.from({ length: NS }, (_, k) => `var st${k}: string = ""`).join('\n')}

${Array.from({ length: NS }, (_, k) => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = msg
@right out hud_: string = hud
@right out title_: string = if state == 0 then "PARRY OR PERISH" else ""
@right out P0: float = aP0
@right out V0: float = aV0
@right out P1: float = aP1
@right out V1: float = aV1
@right out P2: float = aP2
@right out V2: float = aV2
@right out P3: float = aP3
@right out V3: float = aV3
@right out state_: int = state

mod showHud() {
  hud = if state == 0 then "SPACE = HIGH PARRY     E / LMB = LOW PARRY" else ("HP " .. BAR[hp] .. "  FOE " .. BAR[foe] .. "  COMBO " .. combo .. "  SCORE " .. score)
}

mod say(s: string, n: int) {
  msg = s
  msgT = n
}

mod put(i: int, k: int) {
  act[i] = k
  oldA[nA] = i
  nA += 1
}

mod stamp() {
  for k in 0..16 { act[oldA[k]] = 0 }
  for k in 0..16 { oldA[k] = 0 }
  nA = 0
  let row = if atk == 0 then 11 else 13
  if state == 2 {
    for c in 17..20 { put(10 * ${TW} + c, 16) }
    let late = wind - stT
    var k: int = if atk == 0 then 9 else 11
    if late <= 7 && !feint { k = 6 }
    put(row * ${TW} + 16, k)
  }
  if state == 3 && resKind == 0 {
    put(row * ${TW} + 6, 6)
    put(row * ${TW} + 7, 6)
    put(row * ${TW} + 8, 13)
    if stT < 8 { for c in 9..16 { put(row * ${TW} + c, 12) } }
  }
  if state == 3 && resKind == 1 {
    if stT < 8 {
      for c in 6..16 { put(row * ${TW} + c, 12) }
      put(row * ${TW} + 5, 13)
    }
  }
}

mod loadLevel() {
  let m = lvl % ${NLV}
  for i in 0..${N} { cur[i] = MAP[i] }
  foe = FOES[m] + (lvl / ${NLV}) * 2
  if foe > 12 { foe = 12 }
  wind = 30 - lvl * 3
  if wind < 16 { wind = 16 }
  state = 1
  stT = 0
  idleT = 24
  pT = -1
  say("DEMON " .. (lvl + 1), 40)
  showHud()
}

mod newGame() {
  lvl = 0
  score = 0
  hp = 5
  combo = 0
  loadLevel()
}

mod hurt() {
  hp -= 1
  combo = 0
  hitT = t
}

mod resolve() {
  stT = 0
  state = 3
  resKind = 1
  if feint {
    resKind = 2
    if pT >= 0 {
      hurt()
      say("FEINT! FOOLED", 25)
    } else {
      say("FEINT", 20)
    }
  } else if pT >= 0 && pK == atk && wind - pT <= 7 {
    resKind = 0
    combo += 1
    clangT = t
    if wind - pT <= 3 {
      foe -= 2
      score += 150 * combo
      clangP = 2.2
      say("PERFECT", 25)
    } else {
      foe -= 1
      score += 100 * combo
      clangP = 1.5
      say("PARRY", 20)
    }
    if foe < 0 { foe = 0 }
  } else {
    hurt()
    if pT < 0 { say("TOO SLOW", 25) } else if pK != atk { say("WRONG PARRY", 25) } else { say("TOO EARLY", 25) }
  }
  showHud()
}

mod compose(r0: int, r1: int) {
  for ty in r0..r1 {
    var sT: string = ""
    var cT: int = -1
    var nT: int = 0
    var sB: string = ""
    var cB: int = -1
    var nB: int = 0
    for tx in 0..${TW} {
      let i = ty * ${TW} + tx
      var k: int = act[i]
      if k == 0 { k = cur[i] }
      let o = k * 4
      let a = LOOK[o]
      let b = LOOK[o + 1]
      let c = LOOK[o + 2]
      let d = LOOK[o + 3]
${push('T', 'a')}
${push('T', 'b')}
${push('B', 'c')}
${push('B', 'd')}
    }
    rows[ty * 2] = sT .. OPEN[cT] .. BLK[nT] .. CLOSE[cT]
    rows[ty * 2 + 1] = sB .. OPEN[cB] .. BLK[nB] .. CLOSE[cB]
  }
}

mod powerOn() {
  booted = true
  lvl = 0
  score = 0
  hp = 5
  combo = 0
  loadLevel()
  state = 0
  mi = 0
  mt = LT[0]
  bi = 0
  bt = BT[0]
  say("HOLD SPACE TO START", 0)
  showHud()
}

mod powerOff() {
  booted = false
  state = 0
  msg = ""
  hud = ""
${Array.from({ length: NS }, (_, k) => `  st${k} = ""`).join('\n')}
  aV0 = 0.0
  aV1 = 0.0
  aV2 = 0.0
  aV3 = 0.0
}

${debug ? `var dbk: string = ""
var dumpReq: bool = false
on ChatCommand("pr", "PARRY debug: /pr <keys o(sit) a b> | dump | lvl") -> (ctrl, args) {
  if args == "dump" { dumpReq = true }
  else if args == "lvl" {
    lvl += 1
    loadLevel()
  }
  else { dbk = args }
}
` : ''}on tick {
${debug ? `  let pwr = seated || dbk.Contains("o")` : `  let pwr = seated`}
  if !pwr {
    if booted { powerOff() }
  } else {
    if !booted { powerOn() }
${debug ? `    let ia = a || dbk.Contains("a")
    let ib = b || dbk.Contains("b")
    if t % 20 == 0 { PrintToConsole("prdbg|" .. t .. "|" .. state .. "|hp " .. hp .. "|foe " .. foe .. "|atk " .. atk .. "|wind " .. wind .. "|stT " .. stT .. "|pT " .. pT .. "|combo " .. combo .. "|score " .. score) }
    if dumpReq && t % 2 == 1 {
      dumpReq = false
      for r in 0..${H} { PrintToConsole("prrow|" .. r .. "|" .. rows[r]) }
    }` : `    let ia = a
    let ib = b`}
    t += 1
    rnd = (rnd * 75 + 74) % 65537
    let aE = ia && !pA
    let bE = ib && !pB
    if state == 0 || state == 5 {
      if stT < 100 { stT += 1 }
      if stT > 20 && (aE || bE) { newGame() }
    } else if state == 1 {
      stT += 1
      if stT >= idleT {
        atk = rnd % 2
        feint = lvl >= 1 && (rnd / 2) % 5 == 0
        pT = -1
        pK = -1
        state = 2
        stT = 0
      }
    } else if state == 2 {
      stT += 1
      if pT < 0 {
        if aE {
          pT = stT
          pK = 0
        } else if bE {
          pT = stT
          pK = 1
        }
      }
      if stT >= wind { resolve() }
    } else if state == 3 {
      stT += 1
      if stT >= 14 {
        if foe <= 0 {
          state = 4
          stT = 0
          score += 500
          say("DEMON DOWN", 0)
        } else if hp <= 0 {
          state = 5
          stT = 0
          say("YOU PERISHED", 0)
        } else {
          state = 1
          stT = 0
          idleT = 16 + (rnd / 4) % 24
        }
        showHud()
      }
    } else if state == 4 {
      stT += 1
      if stT >= 50 {
        lvl += 1
        if hp < 5 { hp += 1 }
        loadLevel()
      }
    }
    if msgT > 0 {
      msgT -= 1
      if msgT == 0 { msg = "" }
    }
    // music: lead voice 2, bass voice 3
    mt -= 1
    if mt <= 0 {
      mi = (mi + 1) % ${LEAD.p.length}
      mt = LT[mi]
    }
    bt -= 1
    if bt <= 0 {
      bi = (bi + 1) % ${BASS.p.length}
      bt = BT[bi]
    }
    aP2 = if LP[mi] > 0.0 then LP[mi] else 1.0
    aV2 = if LP[mi] > 0.0 then 0.14 else 0.0
    aP3 = if BP[bi] > 0.0 then BP[bi] else 1.0
    aV3 = if BP[bi] > 0.0 then 0.2 else 0.0
    // sfx: parry clang (voice 0), hit (voice 1, noise)
    let ce = t - clangT
    aV0 = if ce < 6 then 0.5 else 0.0
    aP0 = clangP + ce * 0.05
    let he = t - hitT
    aV1 = if he < 8 then 0.6 else 0.0
    aP1 = 1.0
    stamp()
    let ph = t % ${PH}
    compose(ph * ${ROWS_PH}, ph * ${ROWS_PH} + ${ROWS_PH})
    if ph == 0 {
${stripCode(phaseStrips(0))}
    } else {
${stripCode(phaseStrips(1))}
    }
    pA = ia
    pB = ib
  }
}
`;
  return { src, W, H, STRIP, PAL, synths: ['Square', 'Noise', 'Square', 'Triangle'] };
}
