// node playerhud/build.mjs -> playerhud/playerhud.brz (one hidden chip). Load: br.Prefab.Load "playerhud" x y z 0 16
// Zjenks 2026-11-05: "a ui on the side of the screen listing all players with their coins ... a way to toggle it".
// /players toggles it for the caller only; every 1 s each viewer gets a DisplayText on the right: name, coins, level
// (leaderboards `coins`, `Level` from the XP chip; there is no stars leaderboard).
import fs from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bundle } from '../tools/wsbundle.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OWNER = { id: 'b1a7e400-0000-4b0b-9a11-00000000b1a7', name: 'Players HUD', display_name: 'Players HUD' };
const src = `// GENERATED by playerhud/build.mjs
var viewers: controller[]
var players: controller[]
var list: string = ""

on ChatCommand("players", "toggle the player list (coins, level) on your screen") -> (ctrl, args) {
  let i = viewers.find(ctrl)
  if i >= 0 {
    viewers.swap(i, viewers.length() - 1)
    viewers.pop()
    ctrl.DisplayText("", lifetime = 0.1, textId = 9702)
  } else {
    viewers.push(ctrl)
  }
}

on Clock(interval = 1.0) {
  if viewers.length() > 0 {
    players.fillFromPlayers()
    list = "PLAYERS  coins / lvl"
    for p in 0..players.length() {
      let c = players.get(p)
      list = list .. "\\n\${c.GetUserName()}  \${c.GetLeaderboard("coins")} / \${c.GetLeaderboard("Level")}"
    }
    for v in 0..viewers.length() {
      viewers.get(v).DisplayText(list, positionX = 760.0, positionY = -120.0, fontSize = 18, lifetime = 1.5, textId = 9702)
    }
  }
}
`;
fs.writeFileSync(join(here, 'playerhud.gen.ws'), src);
const sdk = join(here, '..', 'tools', 'wspkg');
const wasm = await import(pathToFileURL(join(sdk, 'wasm.js')).href);
if (typeof wasm.default === 'function') await wasm.default({ module_or_path: fs.readFileSync(join(sdk, 'wasm_bg.wasm')) });
const compile = wasm.wirescript_compile ?? wasm.default?.wirescript_compile, diag = wasm.wirescript_diagnostics ?? wasm.default?.wirescript_diagnostics;
const ds = JSON.parse(diag(src, 'playerhud', '{}') || '[]');
for (const d of ds) console.error(`${d.severity} ${d.code} line ${d.startLine}: ${d.message}`);
if (ds.some(d => /error/i.test(d.severity))) throw Error('wirescript errors');
const b = await bundle(new Uint8Array(compile(src, 'playerhud', '{}', '{}')), { owner: OWNER, hide: true, bare: true });
fs.writeFileSync(join(here, 'playerhud.brz'), b.finish({ description: 'player list hud' }));
console.log('wrote playerhud.brz');
