// pong/gen.mjs: high-res (160x240) cabinet chip. The game runs on the server (pong/host.mjs); the chip only decodes
// changed rows into text strips, so the wire cost is per changed row, not per pixel (that is what caps the old
// on-chip games at 48x32). Feed: "/pg <rec>..." where rec = 2 AL chars row (hi*64+lo), then run lengths (AL index,
// 0..63) alternating space/block starting with space, then '.'. "/pgs <text>" sets the HUD. Pad out as "pgin|<mask>"
// (left 64, right 128, a 1, seated 256).
export const W = 160, H = 240, STRIP = 16;
export const AL = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz!#'; // 64 safe chat chars
export const PAL = ['000000'];

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, q = JSON.stringify;
  const MAP = Array.from({ length: 94 }, (_, i) => AL.indexOf(String.fromCharCode(33 + i)));
  const strips = Array.from({ length: NS }, (_, k) => k);
  const src = `// GENERATED by pong/gen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const MAP = [${MAP.join(', ')}]
const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}

var rows: string[]
var dflag: int[]
${strips.map(k => `var st${k}: string = ""`).join('\n')}
var hudv: string = ""
var mode: int = 0
var r: int = 0
var s: string = ""
var blk: bool = false
var last: int = -1

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "sit down: A/D move"
@right out hud_: string = hudv
@right out title_: string = "PONG"

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { st${k} = v }`).join('\n')}
}

on ChatCommand("pg", "pong frame feed (host.mjs)") -> (ctrl, args) {
  if rows.length() < ${H} {
    rows.resize(${H}, "")
    dflag.resize(${NS}, 0)
  }
  mode = 0
  let n = args.Length()
  for c in 0..n {
    let p = MAP[args.Substring(c, 1).ToCharCode().Codepoint - 33]
    if mode == 0 {
      r = p * 64
      mode = 1
    } else {
      if mode == 1 {
        r = r + p
        mode = 2
        s = ""
        blk = false
      } else {
        if p < 0 {
          rows[r] = "<color=\\"ffffff\\">" .. s .. "</>"
          dflag[r / ${STRIP}] = 1
          mode = 0
        } else {
          if blk {
            s = s .. BL.Substring(0, p)
            blk = false
          } else {
            s = s .. SP.Substring(0, p)
            blk = true
          }
        }
      }
    }
  }
  for k in 0..${NS} {
    if dflag.get(k) == 1 {
      dflag[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}
on ChatCommand("pgs", "pong hud (host.mjs)") -> (ctrl, args) {
  hudv = args
}
${debug ? `on ChatCommand("pgdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("pgrow|${k}|" .. st${k})`).join('\n')}
}
` : ''}on tick {
  var m: int = 0
  if seated { m = 256 }
  if ba { m += 1 }
  if left { m += 64 }
  if right { m += 128 }
  if m != last {
    last = m
    PrintToConsole("pgin|" .. m)
  }
}
`;
  return { src, W, H, STRIP, PAL, synths: [] };
}
