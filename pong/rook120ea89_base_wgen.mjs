// pong/wgen.mjs: PONG 160x240 in pure wires (Rookstun: "just use wires to update and render the pong cabinet").
// No server host: the chip runs the game and draws it. The trick that keeps 160x240 inside the wire budget: a row is
// never drawn per pixel. Each changed row is rebuilt from the objects on it (balls, paddle, game-over bar) as
// intervals, sorted, then joined as SP/BL substrings (a few concats a row); only strips (16 rows) holding a changed
// row are re-joined. Same pins/outputs as pong/gen.mjs, so it uses the same cabinet.
export const W = 240, H = 160, STRIP = 20; // landscape (Rookstun: "each row 240 micro bricks wide, stack 160")
export const PAL = ['000000'];

export function generate({ debug = false } = {}) {
  const NS = H / STRIP, q = JSON.stringify;
  const strips = Array.from({ length: NS }, (_, k) => k);
  const PY = H - 12, PW = 28, BS = 4, CX = 60, CY = 70, CR = 32; // CX/CY/CR = the round bumper
  // The bumper never moves, so its rows are precomputed here as interval lists: plain, and with the win message
  // (Rookstun: at 10 balls "u r did it. winrar!") cut out of it in a 3x5 pixel font. The chip only picks a list.
  const FONT = { U: ['101', '101', '101', '101', '111'], R: ['110', '101', '110', '101', '101'], D: ['110', '101', '101', '101', '110'],
    I: ['111', '010', '010', '010', '111'], T: ['111', '010', '010', '010', '010'], '.': ['000', '000', '000', '000', '010'],
    W: ['101', '101', '101', '111', '101'], N: ['110', '101', '101', '101', '101'], A: ['010', '101', '111', '101', '101'],
    '!': ['010', '010', '010', '000', '010'], ' ': ['000', '000', '000', '000', '000'],
    G: ['011', '100', '101', '101', '011'], M: ['101', '111', '111', '101', '101'], E: ['111', '100', '110', '100', '111'],
    O: ['010', '101', '101', '101', '010'], V: ['101', '101', '101', '101', '010'] };
  const WIN = [['U R DID IT.', CY - 7], ['WINRAR!', CY + 2]], OVER = [['GAME', CY - 7], ['OVER', CY + 2]]; // GAME OVER: Rookstun, black text on the circle
  const circleRows = msgs => Array.from({ length: H }, (_, r) => {
    const cdy = CY - (r + 0.5), iv = [];
    if (Math.abs(cdy) >= CR) return iv;
    const hw = Math.sqrt(CR * CR - cdy * cdy), a = Math.round(CX - hw), b = Math.round(CX + hw), fill = new Array(W).fill(false);
    for (let x = a; x < b; x++) fill[x] = true;
    for (const [txt, top] of msgs) {
      const gy = r - top, x0 = Math.round(CX - (txt.length * 4 - 1) / 2);
      if (gy >= 0 && gy < 5) [...txt].forEach((ch, k) => { for (let c = 0; c < 3; c++) if (FONT[ch][gy][c] === '1') fill[x0 + k * 4 + c] = false; });
    }
    for (let x = a; x < b;) { if (!fill[x]) { x++; continue; } let e = x; while (e < b && fill[e]) e++; iv.push([x, e]); x = e; }
    return iv;
  });
  const flat = rows => { const idx = [0], s = [], e = []; for (const iv of rows) { for (const [x0, x1] of iv) { s.push(x0); e.push(x1); } idx.push(s.length); } return { idx, s, e }; };
  const C0 = flat(circleRows([])), C1 = flat(circleRows(WIN)), C2 = flat(circleRows(OVER));
  const area = c => c.s.reduce((n, x, i) => n + c.e[i] - x, 0);
  if (!(area(C1) < area(C0) && area(C2) < area(C0) && area(C0) > 3000)) throw Error('self-check: win text not cut into the bumper'); // self-check
  const src = `// GENERATED by pong/wgen.mjs: edit that, not this file.
@left in tick: exec
@left in seated: bool
@left in left: bool
@left in right: bool
@left in up: bool
@left in down: bool
@left in ba: bool
@left in bb: bool

const SP = ${q(' '.repeat(W))}
const BL = ${q('█'.repeat(W))}

var rows: string[]
var dfl: int[]
var dl: int[]
var sdf: int[]
var bx: float[]
var by: float[]
var vx: float[]
var vy: float[]
var is: float[]
var ie: float[]
${strips.map(k => `var st${k}: string = ""`).join('\n')}
var hudv: string = ""
var px: float = ${W / 2 - PW / 2}.0
var opx: float = -1.0
var score: int = 0
var best: int = 0
var over: int = 0
var alive: int = 0
var most: int = 0
var gm: int = 0
var was: bool = false
var forced: bool = false
var won: bool = false
var kt: float = 1.0
var lastT: float = 0.0
var overUntil: float = 0.0
var beep: int = 0
var titlev: string = "NIGHT PONG"
var mel: float[]
var melPos: int = 0
var waiting: bool = false
var lastBa: bool = false
var sb: float = 1.0
var aP0: float = 1.0
var aV0: float = 0.0
const CI0 = [${C0.idx.join(', ')}]
const CS0 = [${C0.s.join(', ')}]
const CE0 = [${C0.e.join(', ')}]
const CI1 = [${C1.idx.join(', ')}]
const CS1 = [${C1.s.join(', ')}]
const CE1 = [${C1.e.join(', ')}]
const CI2 = [${C2.idx.join(', ')}]
const CS2 = [${C2.s.join(', ')}]
const CE2 = [${C2.e.join(', ')}]
var half: bool = false
var s: string = ""
var cur: float = 0.0

${strips.map(k => `@right out strip${k}: string = st${k}`).join('\n')}
@right out msg_: string = "A/D move  -  new ball every 2 returns"
@right out hud_: string = hudv
@right out title_: string = titlev
@right out P0: float = aP0
@right out V0: float = aV0

mod setStrip(k: int, v: string) {
${strips.map(k => `  if k == ${k} { st${k} = v }`).join('\n')}
}
mod mark(r: int) {
  if r >= 0 && r < ${H} {
    if dfl.get(r) == 0 {
      dfl[r] = 1
      dl.push(r)
    }
  }
}
mod markBall(i: int) {
  let y0 = floor(by.get(i))
  for k in 0..${BS} { mark(y0 + k) }
}
mod newBall() {
  let a = Random(-0.6, 0.6)
  bx.push(${W / 2 - BS / 2}.0)
  by.push(30.0)
  vx.push(5.0 * sin(a))
  vy.push(5.0 * cos(a))
}
mod reset() {
  gm = 0
  for i in 0..bx.length() { markBall(i) }
  if won {
    won = false
    for r in ${CY - CR}..${CY + CR} { mark(r) }
  }
  bx.resize(0, 0.0)
  by.resize(0, 0.0)
  vx.resize(0, 0.0)
  vy.resize(0, 0.0)
  newBall()
  score = 0
  over = 0
  for r in ${CY - CR}..${CY + CR} { mark(r) }
}
// rebuild one row from the objects on it
mod renderRow(r: int) {
  is.resize(0, 0.0)
  ie.resize(0, 0.0)
  for i in 0..bx.length() {
    let y0 = floor(by.get(i))
    if r >= y0 && r < y0 + ${BS} {
      let x0 = floor(bx.get(i))
      is.push(x0)
      ie.push(x0 + ${BS}.0)
    }
  }
  if r >= ${PY} && r < ${PY + 4} {
    is.push(floor(px))
    ie.push(floor(px) + ${PW}.0)
  }
  if r < 2 {
    is.push(0.0)
    ie.push(${W}.0)
  }
  // round bumper (Rookstun: 64x64 circle on the left): its precomputed spans on this row, with the win text once won
  if over > 0 {
    for j in CI2[r]..CI2[r + 1] {
      is.push(CS2[j])
      ie.push(CE2[j])
    }
  } else { if won {
    for j in CI1[r]..CI1[r + 1] {
      is.push(CS1[j])
      ie.push(CE1[j])
    }
  } else {
    for j in CI0[r]..CI0[r + 1] {
      is.push(CS0[j])
      ie.push(CE0[j])
    }
  } }
  is.sortMultiple(ie)
  s = ""
  cur = 0.0
  for j in 0..is.length() {
    let a = max(max(is.get(j), cur), 0.0)
    let b = min(ie.get(j), ${W}.0)
    if b > a {
      s = s .. SP.Substring(0, a - cur) .. BL.Substring(0, b - a)
      cur = b
    }
  }
  rows[r] = s .. SP.Substring(0, ${W}.0 - cur) // full width: the TextDisplay centres each line, short rows drifted right
  sdf[r / ${STRIP}] = 1
}
mod note(p: float, n: int) {
  for k in 0..n { mel.push(p) }
}
mod sadTune() {
  mel.resize(0, 0.0)
  melPos = 0
  note(1.0, 5)
  note(0.94, 5)
  note(0.89, 5)
  note(0.0, 1)
  note(0.75, 12)
}
mod happyTune() {
  mel.resize(0, 0.0)
  melPos = 0
  note(1.0, 2)
  note(1.26, 2)
  note(1.5, 3)
}
mod winTune() {
  mel.resize(0, 0.0)
  melPos = 0
  note(1.5, 3)
  note(0.0, 1)
  note(1.5, 2)
  note(1.68, 3)
  note(2.0, 3)
  note(0.0, 1)
  note(1.68, 2)
  note(2.0, 10)
}
// DELTA TIME (Rookstun): every tick moves things by the real time since the last one (k = dt / 0.1 s; velocities are
// pixels per 0.1 s), so speed no longer depends on the tick rate; game over lasts 3 s of real time
mod step() {
  let now = ServerUptime()
  kt = min(max((now - lastT) * 10.0, 0.0), 2.5)
  lastT = now
  // bouncy blip (Rookstun): 3 ticks, pitch sweeping up from the surface's base note
  if melPos < mel.length() {
    // tune playing (Rookstun: sad game over, happy new ball, a different happy one at 10 balls): one pitch a tick, 0 = rest
    aP0 = max(mel.get(melPos), 0.1)
    aV0 = if mel.get(melPos) > 0.0 then 0.5 else 0.0
    melPos += 1
    beep = 0
  } else { if beep > 0 {
    aP0 = sb * (1.0 + (3 - beep) * 0.35)
    aV0 = 0.5
    beep -= 1
  } else { aV0 = 0.0 } }
  // a round starts only on the player's confirm (Rookstun): Space / right mouse, after sitting down or a game over
  if waiting {
    if ba && lastBa == false {
      waiting = false
      titlev = "" // Rookstun: the title screen goes once the player confirms
      if over > 0 {
        over = 0
        reset()
      }
    }
  } else {
    if left { px -= 6.0 * kt }
    if right { px += 6.0 * kt }
    px = min(max(px, 0.0), ${W - PW}.0)
    if px != opx {
      for k in 0..4 { mark(${PY} + k) }
      opx = px
    }
    alive = 0
    for i in 0..bx.length() {
      if by.get(i) < ${H}.0 {
        markBall(i)
        var x: float = 0.0
        var y: float = 0.0
        var dx: float = 0.0
        var dy: float = 0.0
        x = bx.get(i) + vx.get(i) * kt
        y = by.get(i) + vy.get(i) * kt
        dx = vx.get(i)
        dy = vy.get(i)
        if x < 0.0 {
          x = 0.0 - x
          dx = 0.0 - dx
        }
        if x > ${W - BS}.0 {
          x = ${2 * (W - BS)}.0 - x
          dx = 0.0 - dx
        }
        if y < 3.0 {
          y = 6.0 - y
          dy = abs(dy)
          sb = 1.6
          beep = 3
        }
        // bumper: ball centre inside radius + half ball and moving inward -> reflect the velocity off the normal, push out
        let nx = x + ${BS / 2}.0 - ${CX}.0
        let ny = y + ${BS / 2}.0 - ${CY}.0
        let d = max(sqrt(nx * nx + ny * ny), 0.01)
        if d < ${CR + BS / 2}.0 {
          let ux = nx / d
          let uy = ny / d
          let vn = dx * ux + dy * uy
          if vn < 0.0 {
            dx = dx - 2.0 * vn * ux
            dy = dy - 2.0 * vn * uy
            sb = 0.7
            beep = 3
          }
          x = ${CX}.0 + ux * ${CR + BS / 2 + 0.5} - ${BS / 2}.0
          y = ${CY}.0 + uy * ${CR + BS / 2 + 0.5} - ${BS / 2}.0
        }
        // swept paddle test (Rookstun: balls went through): where was the ball when its bottom crossed the paddle top?
        let oy = by.get(i)
        let xc = bx.get(i) + vx.get(i) * kt * min(max((${PY}.0 - oy - ${BS}.0) / max(dy * kt, 0.01), 0.0), 1.0)
        if dy > 0.0 && oy + ${BS}.0 <= ${PY + 2}.0 && y + ${BS}.0 >= ${PY}.0 && xc + ${BS}.0 > px - 1.0 && xc < px + ${PW + 1}.0 {
          let off = min(max((xc + ${BS / 2}.0 - (px + ${PW / 2}.0)) / ${PW / 2}.0, -1.0), 1.0)
          x = min(max(xc, 0.0), ${W - BS}.0)
          let sp = min(9.0, sqrt(dx * dx + dy * dy) + 0.15)
          dx = sp * off * 0.8
          dy = 0.0 - sqrt(sp * sp - dx * dx)
          y = ${PY - BS}.0
          score += 1
          sb = 1.2
          beep = 3
          if score % 2 == 0 && alive < 10 {
            newBall() // at most 10 balls (Rookstun)
            happyTune()
          }
        }
        bx[i] = x
        by[i] = y
        vx[i] = dx
        vy[i] = dy
        markBall(i)
        if y < ${H}.0 { alive += 1 }
      }
    }
    if alive >= 10 && won == false {
      won = true
      winTune()
      for r in ${CY - CR}..${CY + CR} { mark(r) }
    }
    if alive == 0 {
      if score > best { best = score }
      over = 1
      waiting = true
      sadTune()
      for r in ${CY - CR}..${CY + CR} { mark(r) }
    }
  }
  lastBa = ba
  if waiting {
    if over > 0 { hudv = "GAME OVER  SCORE \${score}  MOST BALLS \${gm}  -  SPACE TO PLAY AGAIN" } else { hudv = "SCORE \${score}  BALLS \${alive}  MOST SCORE \${best}  MOST BALLS \${most}  -  SPACE TO START" }
  } else {
    if alive > gm { gm = alive }
    if gm > most { most = gm }
    hudv = "SCORE \${score}  BALLS \${alive}  MOST SCORE \${best}  MOST BALLS \${most}"
  } // Rookstun 2026-11-06: board + game over shows this game's score and most balls
}
// the player left: back to idle as if untouched (Rookstun): game stopped, screen blank, score cleared
mod idle() {
  if was {
    was = false
    bx.resize(0, 0.0)
    by.resize(0, 0.0)
    vx.resize(0, 0.0)
    vy.resize(0, 0.0)
    dl.resize(0, 0)
    dfl.fill(0)
    won = false
    over = 0
    score = 0
    aV0 = 0.0
    titlev = "NIGHT PONG"
    mel.resize(0, 0.0)
    melPos = 0
    hudv = ""
${strips.map(k => `    st${k} = ""`).join('\n')}
  }
}
mod flush() {
  for j in 0..dl.length() {
    let r = dl.get(j)
    dfl[r] = 0
    renderRow(r)
  }
  dl.resize(0, 0)
  for k in 0..${NS} {
    if sdf.get(k) == 1 {
      sdf[k] = 0
      var acc: string = ""
      acc = ""
      for j in 0..${STRIP} {
        if j < ${STRIP - 1} { acc = acc .. rows.get(k * ${STRIP} + j) .. "\\n" } else { acc = acc .. rows.get(k * ${STRIP} + j) }
      }
      setStrip(k, acc)
    }
  }
}

${debug ? `on ChatCommand("pgdump", "print the strips") -> (ctrl, args) {
${strips.map(k => `  PrintToConsole("pgrow|${k}|" .. st${k})`).join('\n')}
}
on ChatCommand("pgover", "debug: game over now (3 s)") -> (ctrl, args) {
  over = 1
  waiting = true
  for r in ${CY - CR}..${CY + CR} { mark(r) }
  flush()
}
on ChatCommand("pgwin", "debug: toggle the win text") -> (ctrl, args) {
  won = won == false
  for r in ${CY - CR}..${CY + CR} { mark(r) }
  flush()
}
on ChatCommand("pgsit", "debug: play as if seated (toggle)") -> (ctrl, args) {
  forced = forced == false
}
` : ''}// 20 Hz tick, game at 10 fps; only while somebody sits (a new sitter = new game, full redraw)
on tick {
  if seated || forced {
    if was == false {
      was = true
      rows.resize(${H}, "")
      dfl.resize(${H}, 0)
      sdf.resize(${NS}, 0)
      reset()
      waiting = true
      lastT = ServerUptime()
      for r in 0..${H} { mark(r) }
    }
    step()
    flush()
  } else {
    idle()
  }
}
// the seat emptying resets at once: the release clock stops with the seat (clockWhenSeated), so no tick would come
on Change(seated) {
  if seated == false && forced == false { idle() }
}
`;
  return { src, W, H, STRIP, PAL, textColor: 'ffffff', clockWhenSeated: !debug, titleMid: true, titleLH: 4, synths: ['Square'] }; // P0/V0 = hit blip (paddle high, circle low) // debug builds keep the clock for /pgsit
}
