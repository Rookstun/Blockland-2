// ---- one portal: face = local +x at x 0, screen bricks x -2..0, ring around it, chip in the wall behind
async function portal(name, ring, tint) {
  const CHIP = [-8, 0, 0];
  const root = rootOf(screenChip);
  const b = await bundle(screenChip, { owner: MAP_OWNER, offset: CHIP.map((v, i) => v - root.position[i]), hide: true, bare: true });
  const { w, C, O } = b;
  const ext = [{ type: 'BrickFontDescriptor', name: 'MonaspaceKrypton' }];
  const FONT = b.ext.length;
  const boxes = [{ lo: CHIP.map(v => v - 5), hi: CHIP.map(v => v + 5) }];
  const brick = (size, pos, more) => {
    boxes.push({ lo: pos.map((v, i) => v - size[i]), hi: pos.map((v, i) => v + size[i]) });
    return w.addBrick({ asset: 'PB_DefaultMicroBrick', size, position: pos, owner_index: O, collision: OFF, ...more });
  };
  I.forEach(k => {
    const s = brick([1, SW, CELL], [-1, 0, SH - CELL - k * 2 * CELL], { color: tint,
      components: [{ type: C.TextDisplay.NAME, data: { ...TEXT(FONT), Face: 0, LineHeight: +(CELL * 0.645).toFixed(4), WidthScale: 2 } }] });
    w.addWire({ brick: b.portOut(`strip${k}`), component_type: 'BrickComponentType_Internal_MicrochipOutput', port: 'RER_Output' },
      { brick: s, component_type: C.TextDisplay.NAME, port: 'Text' });
  });
  const G = { color: ring, material: 'BMC_Glow', material_intensity: 3 }, R = 3;
  brick([1, SW + 2 * R, R], [-1, 0, SH + R], G);       // top
  brick([1, SW + 2 * R, R], [-1, 0, -SH - R], G);      // bottom
  brick([1, R, SH], [-1, SW + R, 0], G);               // left (seen from the front: +y)
  brick([1, R, SH], [-1, -SW - R, 0], G);              // right
  overlapCheck(boxes);
  const out = b.finish({ extraAssets: ext, description: `Portal (${name})` });
  fs.writeFileSync(path.join(here, `portal_${name}.brz`), out);
  return out;
}
