// SERVO SPIDER (owner 2026-11-05: "make him out of servos and shit so he moves like the boston dynamics robot, capable
// of falling over and also climbing"). A real physics robot: node spider/bot.mjs -> spider/bot.brz (the robot) +
// spider/botload.brz (static hidden loader chip that spawns it) + spider/bot.gen.ws.
// Robot = spawned prefab: its world grid becomes the BODY (physics, gravity) and carries the brain chip; each leg =
// coxa grid on a yaw servo (axis z) on the body -> femur grid on a hinge servo (axis x) on the coxa -> tibia grid on a
// hinge servo on the femur, rubber foot pad at the tip. Built with every leg straight out sideways (TargetAngle 0);
// the brain fans + bends them. Joint convention (door/iris): child grid origin = its servo, identity rotation, joint
// offset 0 / rotation identity. Gait = joint-space tetrapod (groups alternate), steering by stride per side; fallen
// (|pitch| or |roll| > 70) -> flail to flip back over. Rider on its back -> fit + fling (as the teleport spider).
// Chat: /spider (follow me), here, goto X Y, follow NAME, stop, where, pose C F T (debug: hold angles), /spiderreset
// Load: br.Prefab.Load "botload" x y z 0 16 with z = ground + 300 (the loader floats; robot drops from there - 150).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { reown, OWNER } from '../pots/reown.mjs';
import { bundle } from '../tools/wsbundle.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const MAP_OWNER = { id: OWNER.id, name: OWNER.name, display_name: OWNER.display };
const SPAWN_DROP = Number(process.env.DROP ?? 200);                   // robot spawns this far below the loader chip
// signs found by probing (pose command + SaveRegion readback); CS = coxa, HS = hinge (right side; left = -HS)
const CS = Number(process.env.CS ?? -1), HS = Number(process.env.HS ?? 1);
const HD = Number(process.env.HD ?? 0), HR = Number(process.env.HR ?? 0);   // hinge servo brick direction / rotation
const REST = [35, 12, -12, -35];          // coxa fan per leg, front to back (deg toward the front)
const FEM0 = 25, TIB0 = -115, LIFTA = 28, STRIDE = 22, FREQ = 1.6;

const sdk = path.join(here, '..', 'tools', 'wspkg');
const wasm = await import(pathToFileURL(path.join(sdk, 'wasm.js')).href);
if (typeof wasm.default === 'function') await wasm.default({ module_or_path: fs.readFileSync(path.join(sdk, 'wasm_bg.wasm')) });
const compileWs = wasm.wirescript_compile ?? wasm.default?.wirescript_compile;
const diag = wasm.wirescript_diagnostics ?? wasm.default?.wirescript_diagnostics;
function compile(src, name, prefabs = {}) {
  let bad = 0;
  for (const d of JSON.parse(diag(src, name, '{}') || '[]')) { console.error(`${name}: ${d.severity} ${d.code} line ${d.startLine}: ${d.message}`); if (d.severity === 'error') bad++; }
  if (bad) process.exit(1);
  const reg = Object.fromEntries(Object.entries(prefabs).map(([k, v]) => [k, Array.from(v)]));
  return new Uint8Array(compileWs(src, name, '{}', JSON.stringify(reg)));
}
const lib = await import(pathToFileURL(path.join(here, '..', 'tools', 'brs4', 'dist.mjs')).href);
const rootOf = bytes => { const r = lib.WorldReader.from(bytes), as = r.brickAssets().map(a => a.name ?? a); return [...r.bricks(1)].find(b => as[b.asset_name_index] === 'B_1x1_Microchip'); };
const f1 = v => (Number.isInteger(v) ? v.toFixed(1) : String(+v.toFixed(4)));
const wrap = e => `(${e} - 360.0 * floor((${e} + 180.0) / 360.0))`;

const LEGS = [...Array(8).keys()].map(i => {
  const s = i < 4 ? 1 : -1, j = i % 4;
  return { i, s, j, g: (j + (s > 0 ? 0 : 1)) % 2, hip: [24 - 16 * j, 29 * s, 0] };
});

// ---- brain
const src = `// GENERATED by spider/bot.mjs: servo spider brain (rides on the body grid). Edit bot.mjs, not this file.
@invisible

var mode: int = 0
var ctl: controller
var goal: vector = Vec(0.0, 0.0, 0.0)
var phase: float = 0.0
var hold: bool = false
var hc: float = 0.0
var hf: float = 0.0
var ht: float = 0.0
var pan: float = 0.0
var flk: bool = false
${LEGS.map(({ i }) => `var vc${i}: float = 0.0\nvar vf${i}: float = 0.0\nvar vt${i}: float = 0.0`).join('\n')}
${LEGS.map(({ i }) => `@right out c${i}: float = vc${i}\n@right out f${i}: float = vf${i}\n@right out t${i}: float = vt${i}`).join('\n')}

on ChatCommand("spider", "Spider: /spider (follow me), here, goto X Y, follow NAME, stop, where; /spiderreset") -> (c: controller, args: string) {
  let a = args.Trim()
  let al = a.ToLower()
  if a == "" || al == "come" || al == "me" {
    ctl = c
    mode = 1
    hold = false
    c.ShowStatusMessage("The spider turns all eight of its eyes toward you. Seven of them approve.")
  } else if al == "stop" {
    mode = 0
    hold = false
    c.ShowStatusMessage("The spider sits down and pretends this was its idea.")
  } else if al == "here" {
    goal = c.CharacterOf().GetLocation()
    mode = 2
    hold = false
    c.ShowStatusMessage("The spider memorizes this spot. It has a very small, very loyal brain.")
  } else if al.StartsWith("goto ") {
    let r = a.Substring(5, 200).Trim().Split(" ")
    goal = Vec(ParseNumber(r.Left), ParseNumber(r.Right.Trim()), 0.0)
    mode = 2
    hold = false
    c.ShowStatusMessage("The spider sets off with the confidence of something that cannot read a map.")
  } else if al.StartsWith("follow ") {
    let ch = FindPlayer(a.Substring(7, 200).Trim())
    ctl = ch.ControllerOf()
    mode = 1
    hold = false
    c.ShowStatusMessage("The spider picks up a scent. It is mostly fear, with notes of cheap cologne.")
  } else if al.StartsWith("pose ") {
    let r1 = a.Substring(5, 200).Trim().Split(" ")
    let r2 = r1.Right.Trim().Split(" ")
    hc = ParseNumber(r1.Left)
    hf = ParseNumber(r2.Left)
    ht = ParseNumber(r2.Right.Trim())
    hold = true
    mode = 0
  } else if al == "where" {
    let me = ReadBrickGrid()
    let p = me.GetLocation()
    let e = me.GetRotation().ToEuler()
    PrintToConsole(Fmt("sbot|{0}|{1}|{2}|{3}|{4}|{5}|{6}", p.x, p.y, p.z, e.Pitch, e.Yaw, e.Roll, mode))
    c.ShowStatusMessage(Fmt("The spider is at {0}, {1}, {2}. It would like a raise.", round(p.x), round(p.y), round(p.z)))
  } else {
    c.ShowStatusMessage("The spider tilts its head. Try: /spider, here, goto X Y, follow NAME, stop, where, /spiderreset")
  }
}

on Clock(interval = 0.0) {
  let dt = clamp(DeltaTime(), 0.0, 0.05)
  let u = ServerUptime()
  let me = ReadBrickGrid()
  let P = me.GetLocation()
  let E = me.GetRotation().ToEuler()
  let Y = E.Yaw
  let M = mode
  let G = goal
  let PH = phase
  let PN = pan
  let FL = flk
  let panicking = PN > 0.0
  let fallen = abs(E.Pitch) > 70.0 || abs(E.Roll) > 70.0
  let tgt = if M == 1 then ctl.CharacterOf().GetLocation() else G
  let dx = tgt.x - P.x
  let dy = tgt.y - P.y
  let dist = sqrt(dx * dx + dy * dy)
  let gap = if M == 1 then 220.0 else 40.0
  let active = M != 0 && MagnitudeSq(tgt) > 1.0 && dist > gap && !fallen
  let err = ${wrap('(Rad2Deg(atan2(dy, dx)) + 15.0 * sin(u * 2.7) - Y)')}
  let tr = if active then clamp(err / 35.0, -1.0, 1.0) else 0.0
  let fw = if active then clamp((dist - gap) / 150.0, 0.0, 1.0) * (1.0 - 0.8 * abs(tr)) else 0.0
  let act = if panicking then 1.0 else max(abs(fw), abs(tr))
  let moving = act > 0.05 || fallen
  let freq = if panicking then 4.0 else ${f1(FREQ)}
  let ph2 = if moving then fmod(PH + dt * 6.2832 * freq, 6.2832) else PH
  let sR = ${f1(STRIDE)} * clamp(fw - tr, -1.0, 1.0)
  let sL = ${f1(STRIDE)} * clamp(fw + tr, -1.0, 1.0)
  let shake = if panicking then 20.0 * sin(u * 43.0) else 0.0
  phase = ph2
  if M == 2 && dist <= gap {
    mode = 0
  }
  // rider on its back: fit, then fling (once per fit)
  let rd = Sweep(P + Vec(0.0, 0.0, 40.0), Vec(0.0, 0.0, 1.0), 100.0, radius = 45.0, ignore = me, detectPlayers1 = true, detectPlayers2 = true, detectPlayers3 = true, detectPlayers4 = true)
  if rd.Hit {
    if !panicking {
      pan = 1.4
      flk = false
    } else if PN < 0.5 && !FL {
      rd.HitEntity.AddVelocity(linear = Vec(cos(u * 13.0) * 1100.0, sin(u * 13.0) * 1100.0, 1400.0))
      flk = true
    }
  }
  if panicking {
    pan = PN - dt
  }
${LEGS.map(({ i, s, j, g }) => {
  const rest = f1(-s * REST[j]);
  return `  // leg ${i} (${s > 0 ? 'right' : 'left'} ${j})
  let p${i} = ph2 + ${f1(g * Math.PI)}
  let b${i} = cos(p${i})
  let l${i} = if moving then max(0.0, sin(p${i})) else 0.0
  let yw${i} = ${rest} + ${s > 0 ? `sR * b${i}` : `0.0 - sL * b${i}`} + shake
  let fe${i} = if fallen then 70.0 * sin(u * 5.0 + ${f1(i)}) else ${f1(FEM0)} + ${f1(LIFTA)} * l${i}
  let ti${i} = if fallen then -60.0 + 50.0 * sin(u * 7.0 + ${f1(i * 2)}) else ${f1(TIB0)}
  vc${i} = if hold then hc else ${f1(CS)} * yw${i}
  vf${i} = if hold then ${f1(s * HS)} * hf else ${f1(s * HS)} * fe${i}
  vt${i} = if hold then ${f1(s * HS)} * ht else ${f1(s * HS)} * ti${i}`;
}).join('\n')}
}
`;
fs.writeFileSync(path.join(here, 'bot.gen.ws'), src);
const chip = reown(compile(src, 'bot'));

// ---- robot prefab: world grid = body (+ chip), 24 leg grids on servos
const CHIP = [0, 0, 16];
const root = rootOf(chip);
const b = await bundle(chip, { owner: MAP_OWNER, offset: CHIP.map((v, i) => v - root.position[i]), hide: true, bare: true });
const { w, C, O } = b;
const ALL = { player: true, weapon: true, interaction: true, physics: true, tool: true };
const NOPHYS = { ...ALL, physics: false };
const LEG_DATA = { BouyancyScale: 0.2, MassScale: Number(process.env.MS ?? 0.3), bEnableGravity: true, bUseNewMassCalculation: true, bReceivesDecals: true, bVisible: true, CollisionQuality: 0, EntityTag: 'spider', CustomProperties: { $map: [] }, GameModeTeamName: '', bDetectableByAnyone: false };
const SERVO = { bEnabled: true, TargetAngle: 0, Power: Number(process.env.PW ?? 100), ActiveDamping: 30, ForceLimit: 0, bLimitAngle: false, LimitAngle: 0, CurrentAngle: 0, bAnglesArePercentages: false, bReversed: false, Damping: 1 };
const BLACK = [0, 0, 0], GREY = [86, 86, 86], DARK = [34, 34, 36], RED = [255, 20, 10], GLOW = { material: 'BMC_Glow', material_intensity: 3 };
const boxes = new Map();                  // per grid overlap check
const box = (g, size, pos) => {
  const k = g ?? 'world', lo = pos.map((v, i) => v - size[i]), hi = pos.map((v, i) => v + size[i]);
  for (const q of boxes.get(k) ?? []) if (lo.every((v, i) => v < q.hi[i]) && q.lo.every((v, i) => v < hi[i])) throw Error(`overlap in ${k}: ${pos}`);
  (boxes.get(k) ?? boxes.set(k, []).get(k)).push({ lo, hi });
};
const mb = (g, size, position, color, more = {}) => { box(g, size, position); return w.addBrick({ asset: 'PB_DefaultMicroBrick', size, position, color, owner_index: O, collision: ALL, ...more }, g); };
const servo = (g, position, direction, rotation = 0) => { box(g, [5, 5, 5], position);
  return w.addBrick({ asset: 'B_Joint_Servo', size: [0, 0, 0], position, direction, rotation, color: GREY, owner_index: O, collision: NOPHYS, components: [{ type: C.Servo.NAME, data: { ...SERVO } }] }, g); };
box(undefined, [5, 5, 2], CHIP);
// body (world grid of the spawned prefab)
mb(undefined, [30, 24, 10], [0, 0, 0], DARK);
mb(undefined, [26, 20, 2], [0, 0, 12], GREY);
mb(undefined, [9, 16, 8], [39, 0, 2], BLACK);
mb(undefined, [1, 3, 2], [49, 7, 5], RED, GLOW);
mb(undefined, [1, 3, 2], [49, -7, 5], RED, GLOW);
mb(undefined, [26, 22, 16], [-56, 0, 6], BLACK);
mb(undefined, [16, 4, 1], [-56, 0, 23], [200, 25, 20]);
const wireTo = (label, h) => w.addWire({ brick: b.portOut(label), component_type: 'BrickComponentType_Internal_MicrochipOutput', port: 'RER_Output' },
  { brick: h, component_type: C.Servo.NAME, port: 'TargetAngle' });
const grid = at => w.addBrickGrid({ owner_index: O, location: { X: at[0], Y: at[1], Z: at[2] }, rotation: { X: 0, Y: 0, Z: 0, W: 1 }, data: LEG_DATA });
const ID = [{ X: 0, Y: 0, Z: 0 }, { X: 0, Y: 0, Z: 0, W: 1 }];
// a jointed grid takes its servo brick's frame (probed: dir 0 rot 0 = +90 deg about y, spin axis = world x): undo it
const HQ = process.env.HQ ? [{ X: 0, Y: 0, Z: 0 }, JSON.parse(process.env.HQ)] : [{ X: 0, Y: 0, Z: 0 }, { X: 0, Y: -Math.SQRT1_2, Z: 0, W: Math.SQRT1_2 }];
for (const { i, s, hip } of LEGS) {
  const cs = servo(undefined, hip, 4);                       // coxa yaw servo on the body side
  const cg = grid(hip); w.registerJoint(cs, cg, ...ID); wireTo(`c${i}`, cs);
  mb(cg, [4, 10, 4], [0, s * 15, 0], BLACK, { collision: NOPHYS });
  const fs_ = servo(cg, [0, s * 30, 0], HD, HR);                  // femur hinge (axis x)
  const fpos = [hip[0], hip[1] + s * 30, hip[2]];
  const fg = grid(fpos); w.registerJoint(fs_, fg, ...HQ); wireTo(`f${i}`, fs_);
  mb(fg, [5, 59, 5], [0, s * 65, 0], BLACK, { collision: NOPHYS });
  const ts = servo(fg, [0, s * 130, 0], HD, HR);                  // tibia hinge
  const tg = grid([fpos[0], fpos[1] + s * 130, fpos[2]]); w.registerJoint(ts, tg, ...HQ); wireTo(`t${i}`, ts);
  mb(tg, [5, 59, 5], [0, s * 65, 0], BLACK, { collision: NOPHYS });
  mb(tg, [7, 6, 7], [0, s * 130, 0], DARK, { material: 'BMC_Plastic' });   // foot pad: the only leg brick with physics
}
const bot = b.finish({ description: 'servo spider robot (spider/bot.mjs)' });
fs.writeFileSync(path.join(here, 'bot.brz'), bot);

// ---- loader: static hidden chip, spawns the robot below itself; /spiderreset respawns it
const loadSrc = `// GENERATED by spider/bot.mjs: servo spider loader.
@invisible

var booted: bool = false
var bot: entity
let rs: exec

on Clock(interval = 0.5) {
  if !booted {
    booted = true
    emit rs
  }
}
on ChatCommand("spiderreset", "Put the servo spider back on its feet where it started") -> (c: controller) {
  c.ShowStatusMessage("A new spider is assembled from spare parts and regret.")
  emit rs
}
var fz: bool = false
on ChatCommand("spiderfreeze", "debug: freeze / unfreeze the servo spider body") -> (c: controller) {
  fz = !fz
  bot.SetFrozen(fz)
}
on rs {
  bot.DestroySpawnedPrefab()
  let e = SpawnPrefab(prefab = $./bot.brz, offset = Vec(0.0, 0.0, ${f1(-SPAWN_DROP)}), lifetime = 0.0, limit = 2)
  bot = e
${process.env.FREEZE ? '  e.SetFrozen(true)\n  fz = true\n' : ''}}
`;
fs.writeFileSync(path.join(here, 'botload.gen.ws'), loadSrc);
const lchip = reown(compile(loadSrc, 'botload', { './bot.brz': bot }));
const lb = await bundle(lchip, { owner: MAP_OWNER, hide: true });
const load = lb.finish({ description: 'servo spider loader (spider/bot.mjs)' });
fs.writeFileSync(path.join(here, 'botload.brz'), load);
