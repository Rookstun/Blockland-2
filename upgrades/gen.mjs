// UPGRADES (owner 2026-10-28, clipboard upgrades/panel_owner.brz: 5 columns x 6 tiles).
// Every tile is a button: "<Upgrade> Level N". Click level N = buy every level up to N you can afford
// (cheapest first, stops at the first you can't pay); click Level 1 while owning any = sell all, 100% refund.
// Price of level L = 100 * 2^(L-1) (100, 200, 400, 800, 1600, 3200).
// Levels live on leaderboards up_<key> (saved by the progress plugin, KEYS).
// The panel's own hidden chip (panel.mjs) sends global event "upg" (character, id = col*10 + level);
// this sky chip does the buying and runs the effects:
//   ammo   +level rounds of each ammo type every 5 s
//   regen  heals level HP per second
//   magnet bot kills: level*10% chance the kill pays coins straight to you (DamageLimit/20 + 5)
//   vamp   heals level*5% of the damage you deal
//   hp     max health 100 + 66.7 per level (game max health 500; the excess goes on as damage, regen never heals past it)
//   node upgrades/gen.mjs && node upgrades/build.mjs
import { writeFileSync } from 'node:fs';
export const UP = [
  ['ammo', 'Ammo Regen'], ['regen', 'Health Regen'], ['magnet', 'Coin Magnet'], ['vamp', 'Vampirism'], ['hp', 'Max HP'],
];
export const LEVELS = 6, PRICE = l => 100 * 2 ** (l - 1);
const AMMO = [['Arrow', 1], ['Light', 3], ['Medium', 2], ['Heavy', 1], ['Magnum', 1], ['Shotgun', 1], ['BlackPowder', 1]];
const TICK = 0.2, BASE_HP = 100, HP_PER = (500 - 100) / LEVELS, // game max health is set to 500: level 6 = all of it
  AMMO_EVERY = 5;
const I = s => '${' + s + '}';

// one block per column, lets only (a Var read after its Set in one exec chain is stale)
// level reached with coins C from level c0: max L <= want with C >= 100 * (2^L - 2^c0)
const buy = UP.map(([k, name], c) => `  if col == ${c} {
    let c0 = ctrl.GetLeaderboard("up_${k}")
    if want == 1 && c0 > 0 {
      let back = 100 * (pow(2.0, c0) - 1.0)
      ctrl.IncLeaderboard("coins", back)
      ctrl.SetLeaderboard("up_${k}", 0)
      ctrl.ShowStatusMessage("<color=\\\"ffd34d\\\">${name}</> sold back for <color=\\\"f6ce2a\\\">${I('back')} coins</>. Level 0.")
    } else if want <= c0 {
      ctrl.ShowStatusMessage("<color=\\\"ffd34d\\\">${name}</> is already level ${I('c0')}. Click Level 1 to sell it all back.")
    } else {
      let top = floor(log(coins / 100.0 + pow(2.0, c0), 2.0) + 0.000001)
      let lv = min(want, top)
      if lv > c0 {
        let spent = 100 * (pow(2.0, lv) - pow(2.0, c0))
        ctrl.IncLeaderboard("coins", 0 - spent)
        ctrl.SetLeaderboard("up_${k}", lv)
        ctrl.ShowStatusMessage("<color=\\\"ffd34d\\\">${name}</> level ${I('lv')} for <color=\\\"f6ce2a\\\">${I('spent')} coins</>.")
      } else {
        ctrl.ShowStatusMessage("<color=\\\"ff8888\\\">${name} level ${I('c0 + 1')} costs ${I('100 * pow(2.0, c0)')} coins. You have ${I('coins')}.</>")
      }
    }
  }`).join('\n');
const ammo = AMMO.map(([r, n]) => `        let a${r} = ch.GetAmmo($BRWeaponResource/WeaponResource_Ammo_${r})
        ch.SetAmmo($BRWeaponResource/WeaponResource_Ammo_${r}, a${r} + ${n} * lAmmo)`).join('\n');

const ws = `// GENERATED by upgrades/gen.mjs: edit that, not this
var players: controller[]
var idx: int = 0
var lastAmmo: Map<string, float>
// who last hurt each character, for kill credit when CharacterDied gives no killer
var hitBy: Map<character, controller>

on GlobalCustomEvent("upg") -> (who: character, id: int) {
  let ctrl = who.ControllerOf()
  let col = floor(id / 10)
  let want = id - col * 10
  let coins = ctrl.GetLeaderboard("coins")
${buy}
  // every click answers with all of that player's levels
  ctrl.ShowChatMessage("<color=\\"88ccff\\">${UP.map(([k, n]) => `${n} ${I(`ctrl.GetLeaderboard("up_${k}")`)}`).join(' | ')}</> | <color=\\"f6ce2a\\">${I('ctrl.GetLeaderboard("coins")')} coins</>")
}

// one player per tick, round robin: each visit covers (players x ${TICK} s)
on Clock(interval = ${TICK}) {
  players.fillFromPlayers()
  let n = players.length()
  if n > 0 {
    if idx >= n {
      idx = 0
    }
    let p = players[idx]
    idx = idx + 1
    let ch = p.CharacterOf()
    let d = ch.GetDamage()
    if d.DamageLimit > 0.0 {
      let dt = n * ${TICK}
      let lRegen = p.GetLeaderboard("up_regen")
      let lHp = p.GetLeaderboard("up_hp")
      let cap = min(d.DamageLimit, ${BASE_HP}.0 + ${HP_PER.toFixed(4)} * lHp)
      let floorDmg = d.DamageLimit - cap
      // only touch damage when it changes (owner: the game's own regen healed past the level cap and
      // ticked the hurt sound forever); dead characters left alone
      let target = max(floorDmg, d.Damage - lRegen * dt)
      if d.Damage < d.DamageLimit && target != d.Damage {
        ch.SetDamage(target)
      }
      let lAmmo = p.GetLeaderboard("up_ammo")
      let uid = p.GetUserId()
      let now = ServerUptime()
      if lAmmo > 0 && (!lastAmmo.has(uid) || now - lastAmmo.get(uid) >= ${AMMO_EVERY}.0 || now < lastAmmo.get(uid)) {
        lastAmmo.set(uid, now)
${ammo}
      }
    }
  }
}

on CharacterDamaged() -> (victim, damage, attacker, attackerWeapon, attackerWeaponName) {
  let ac = attacker.ControllerOf()
  if ac.GetUserName().Length() > 0 && victim != attacker {
    hitBy.set(victim, ac)
    let lVamp = ac.GetLeaderboard("up_vamp")
    if lVamp > 0 {
      let ad = attacker.GetDamage()
      attacker.SetDamage(max(ad.DamageLimit - min(ad.DamageLimit, ${BASE_HP}.0 + ${HP_PER.toFixed(4)} * ac.GetLeaderboard("up_hp")), ad.Damage - damage * 0.05 * lVamp))
    }
  }
}

on CharacterDied() -> (who, killer, killerWeapon, killerWeaponName) {
  if who.ControllerOf().GetUserName().Length() == 0 {
    var kc = killer.ControllerOf()
    if kc.GetUserName().Length() == 0 && hitBy.has(who) {
      kc = hitBy.get(who)
    }
    hitBy.remove(who)
    if kc.GetUserName().Length() > 0 {
      let lMag = kc.GetLeaderboard("up_magnet")
      if lMag > 0 && Random(0, 99) < 10 * lMag {
        let pay = floor(who.GetDamage().DamageLimit / 20.0) + 5
        kc.IncLeaderboard("coins", pay)
        kc.ShowStatusMessage("<color=\\"f6ce2a\\">Coin Magnet: +${I('pay')} coins</>")
      }
    }
  }
}
`;
writeFileSync(new URL('./upgrades.ws', import.meta.url), ws);
console.log('wrote upgrades/upgrades.ws');
